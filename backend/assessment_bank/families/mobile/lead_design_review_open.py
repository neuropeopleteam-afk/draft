    org, obj = rng.choice(ORGS)
    vals = dict(org=org, obj=obj, dau=rng.choice([80, 250, 600, 1500]), weak=rng.choice([25, 35, 45]),
                px=rng.choice([720, 1080]), cache=rng.choice([100, 200, 300]), orig=rng.choice([3, 5, 8]),
                page=rng.choice([20, 30, 50]), days=rng.choice([7, 14, 30]), keep=rng.choice([50, 100, 200]),
                rate=rng.choice([3, 5, 10]), batch=rng.choice([30, 60, 120]))
    return design_review_variant(
        FAMILY_ID, seed, rng, context=org, doc_title="Лента в мобильном приложении",
        intro=f"Организация — {org}: команда переделывает ленту {obj} в мобильном приложении.", lines=LINES,
        issues=ISSUES, vals=vals,
        priority_crit="Расставляет приоритет по влиянию на пользователей (падения и нарушение требования офлайн — "
                      "первыми, затем батарея и трафик) и предлагает проверку (замер памяти, профилирование, "
                      "поэтапная выкатка)",
        extra_notes="Уровень Lead: для каждой проблемы — последствие на устройствах пользователей (память, батарея, "
                    "сеть, невозможность откатить релиз) и исправление.")

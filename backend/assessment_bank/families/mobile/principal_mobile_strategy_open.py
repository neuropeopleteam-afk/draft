def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    org = rng.choice(ORGS)
    topic = rng.choice(sorted(TOPICS))
    cf = rng.choice([98.6, 99.0, 99.2, 99.4])
    vals = dict(org=org, teams=rng.choice([8, 12, 16, 24]), build=rng.choice([18, 25, 35, 45]),
                incr=rng.choice([4, 6, 9]), months=rng.choice([6, 9, 12]), and_dev=rng.choice([6, 9, 14]),
                ios_dev=rng.choice([5, 8, 12]), lag=rng.choice([2, 3, 4, 6]), users=rng.choice([2, 5, 12, 30]),
                weeks=rng.choice([2, 3, 4]), changes=rng.choice([120, 180, 260, 400]), hotfix=rng.choice([30, 45, 60]),
                cf=str(cf).replace(".", ","), cf_target=str(round(cf + rng.choice([0.4, 0.6]), 1)).replace(".", ","),
                anr=str(rng.choice([0.6, 0.9, 1.4])).replace(".", ","), top=rng.choice([5, 10]),
                top_share=rng.choice([48, 55, 63]), partners=rng.choice([8, 15, 30]))
    for k, forms in (("teams", ("команда", "команды", "команд")), ("months", ("месяц", "месяца", "месяцев")),
                     ("lag", ("неделю", "недели", "недель")), ("weeks", ("неделю", "недели", "недель"))):
        vals[k + "_w"] = plural(vals[k], *forms)
    return open_variant(FAMILY_ID, seed, topic=topic, spec=TOPICS[topic], vals=vals, context=org,
                        extra_notes="Уровень Principal: решение на уровне нескольких команд и продукта с "
                                    "компромиссами и планом проверки; перечень технологий без критериев выбора — "
                                    "не выше среднего эталона.")

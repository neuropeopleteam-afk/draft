"""devops.strategy.principal_platform_eng_open — open_answer (Principal): внутренняя платформа разработки.

Дана компания варианта: продуктовые команды, заявки в команду эксплуатации в неделю на типовые действия
(новый сервис, база, доступы, домен, секрет), среднее ожидание по заявке, срок запуска нового сервиса,
размер команды платформы, рост облачных расходов. Опорные числа для рубрики: сколько заявок в год
закрывает самообслуживание при доле типовых, и сколько команд-недель ожидания в год сейчас (заявки ×
ожидание) — то есть чем платформа окупает себя.
Кандидат предлагает: платформу как продукт (пользователи — команды, дорожная карта по их боли),
«золотые пути» (шаблон сервиса с CI/CD, наблюдаемостью, безопасностью по умолчанию), самообслуживание
через декларативные описания и проверки политик, модель владения, добровольное или обязательное
использование, метрики (время до первого выпуска нового сервиса, доля сервисов на золотом пути,
удовлетворённость команд, расходы на облако по командам).
Особенность: команды не хотят переходить, требование работы в двух облаках, рост облачных расходов.
Рубрика 0–4: числа и окупаемость, золотой путь и самообслуживание, модель и принятие, особенность, метрики и этапы.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant
from assessment_bank.gen_utils import plural

FAMILY_ID = "devops.strategy.principal_platform_eng_open"

CONTEXTS = ["банк", "маркетплейс", "телеком-оператор", "экосистема сервисов для бизнеса", "онлайн-ритейлер",
            "логистическая компания"]

TWISTS = {
    "resist": dict(
        text="{resist} % команд уже построили свои конвейеры и шаблоны и не хотят переходить",
        crit=("сопротивление {resist} % команд: золотой путь добровольный и должен быть удобнее своего (быстрее "
              "запуск, меньше поддержки), обязательны только политики безопасности и соответствия (проверки на "
              "входе), миграция — по ценности для команды, их лучшие решения — в платформу"),
        strong=("{resist} % команд со своими конвейерами не заставляю переходить: золотой путь добровольный и должен "
                "выигрывать сам (запуск за день вместо недель, меньше поддержки), обязательны только политики "
                "безопасности на входе, а их удачные решения забираю в платформу.")),
    "multicloud": dict(
        text="регулятор и закупки требуют, чтобы критичные сервисы могли работать в двух облаках",
        crit=("два облака: абстракция на уровне платформы (Kubernetes, Terraform-модули, общий формат описания "
              "сервиса) только для критичных сервисов, управляемые сервисы — через модули с одинаковым "
              "интерфейсом; цена — наименьший общий знаменатель и двойные учения; не делать всё мультиоблачным"),
        strong=("два облака — только для критичных сервисов: общий формат описания сервиса и Terraform-модули с "
                "одинаковым интерфейсом над управляемыми сервисами каждого облака, учения переключения раз в "
                "квартал; остальное не делаю мультиоблачным — платить наименьшим общим знаменателем везде дорого.")),
    "cost": dict(
        text="облачные расходы растут на {cost_g} % в квартал, и никто не знает, какая команда сколько тратит",
        crit=("рост расходов на {cost_g} % в квартал: обязательные метки владельца на ресурсах в шаблоне, расходы "
              "по командам на панели (showback), бюджеты с алертами, разумные лимиты по умолчанию, отключение "
              "сред вне рабочего времени, разбор крупных статей"),
        strong=("расходы растут на {cost_g} % в квартал без владельцев — шаблон ставит метки владельца на каждый "
                "ресурс, расходы по командам видны на панели, у команд бюджеты с алертами, тестовые среды гаснут "
                "вне рабочего времени.")),
}


def _build(rng, ctx):
    teams = rng.choice([25, 40, 70, 120])
    tickets_w = rng.choice([60, 120, 250])
    wait_d = rng.choice([2, 3, 5])                     # рабочих дней ожидания по заявке
    typical = rng.choice([0.6, 0.7, 0.8])              # доля типовых заявок
    launch_w = rng.choice([3, 4, 6])                   # недель до первого выпуска нового сервиса
    plat = rng.choice([5, 8, 12])
    kind = rng.choice(sorted(TWISTS))
    self_y = round(tickets_w * 52 * typical)
    wait_team_weeks = tickets_w * 52 * wait_d / 5
    v = dict(resist=rng.choice([25, 40, 55]), cost_g=rng.choice([15, 25, 40]))
    T = TWISTS[kind]
    stem = (f"Вы — главный инженер по инфраструктуре; компания — {ctx}, {teams} продуктовых команд. В команду "
            f"эксплуатации приходит ≈ {tickets_w} заявок в неделю (новый сервис, база, доступы, домен, секрет), из них "
            f"≈ {fmt_num(100 * typical, 0)} % типовые; ожидание по заявке — в среднем {wait_d} {plural(wait_d, 'рабочий день', 'рабочих дня', 'рабочих дней')}. "
            f"Запуск нового сервиса до первого выпуска занимает ≈ {launch_w} {plural(launch_w, 'неделю', 'недели', 'недель')}. Под платформу выделяют команду из {plat} "
            f"человек. Особенность: {T['text'].format(**v)}.\n\nПредложите стратегию внутренней платформы на год: "
            "что именно она даёт командам и чем окупается (посчитайте), что входит в «золотой путь», как устроено "
            "самообслуживание и проверки, как добиться использования, ответ на особенность, этапы и метрики. "
            "Ответ — 12–18 предложений.")
    criteria = [
        ("numbers", (f"Числа: типовых заявок ≈ {tickets_w} × 52 × {fmt_num(typical, 1)} ≈ {fmt_num(self_y, 0)} в год "
                     f"уходят в самообслуживание; ожидание сейчас ≈ {tickets_w} × 52 × {wait_d} / 5 ≈ "
                     f"{fmt_num(wait_team_weeks, 0)} команд-недель в год; цель — запуск нового сервиса за день вместо "
                     f"≈ {launch_w} нед."), 0.18),
        ("golden", ("Золотой путь: шаблон сервиса с CI/CD, наблюдаемостью, журналами, секретами и безопасностью по "
                    "умолчанию; самообслуживание через декларативное описание (портал или репозиторий) с проверками "
                    "политик на входе; документация и каталог сервисов с владельцами"), 0.18),
        ("model", (f"Модель: платформа как продукт — пользователи команды, дорожная карта по их боли, команда из "
                   f"{plat} не обслуживает заявки, а убирает их; использование добровольное, обязательны только "
                   f"политики безопасности и соответствия; интервью и опросы команд"), 0.18),
        ("twist", T["crit"].format(**v), 0.24),
        ("metrics", ("Этапы и метрики: квартал — самые частые типовые заявки в самообслуживание и шаблон нового "
                     "сервиса; затем перенос существующих по ценности; метрики — время до первого выпуска, доля "
                     "заявок через самообслуживание, доля сервисов на золотом пути, удовлетворённость команд, "
                     "расходы по командам"), 0.22),
    ]
    strong = (f"Самообслуживание закроет ≈ {fmt_num(self_y, 0)} типовых заявок в год, а ожидание сейчас стоит "
              f"≈ {fmt_num(wait_team_weeks, 0)} команд-недель в год — это и есть окупаемость команды из {plat}. "
              f"Золотой путь — шаблон сервиса с CI/CD, наблюдаемостью, секретами и безопасностью по умолчанию; "
              f"новый сервис запускается за день вместо ≈ {launch_w} нед. Самообслуживание — декларативное "
              f"описание в репозитории или портале с проверками политик на входе, каталог сервисов с владельцами. "
              f"Платформа — продукт: пользователи — команды, дорожная карта — по их боли, использование "
              f"добровольное, обязательны только политики безопасности. " + T["strong"].format(**v) + " Квартал — "
              "самые частые заявки и шаблон нового сервиса, затем перенос существующих по ценности; метрики — время "
              "до первого выпуска, доля заявок через самообслуживание, доля сервисов на золотом пути, опрос команд.")
    medium = ("Сделать портал разработчика (Backstage) с шаблонами сервисов и автоматизировать типовые заявки.")
    weak = "Нанять больше инженеров эксплуатации, чтобы заявки закрывались быстрее."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: ≈ {self_y} заявок в год в самообслуживание; ≈ {wait_team_weeks:.0f} команд-недель "
                       f"ожидания в год. «Портал ради портала» без метрик и модели принятия — критерий model не выше 1. "
                       f"Особенность — {kind}."),
                explanation=(f"≈ {self_y} заявок в год в самообслуживание, ≈ {wait_team_weeks:.0f} команд-недель ожидания; "
                             f"особенность — {kind}."),
                params=dict(kind=kind, teams=teams, tickets_w=tickets_w, wait_d=wait_d, typical=typical,
                            launch_w=launch_w, plat=plat, self_y=self_y, wait_team_weeks=round(wait_team_weeks, 1)))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

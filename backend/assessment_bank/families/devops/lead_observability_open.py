"""devops.mon.lead_observability_open — open_answer (Lead): наблюдаемость группы сервисов в пределах бюджета.

Дана система варианта: число сервисов и экземпляров, конечных точек, поток запросов, объём строки журнала,
текущее число алертов в неделю и доля неприменимых. Кандидат проектирует наблюдаемость: метрики по
SLO (RED/USE), бюджет кардинальности, журналы (структура, уровни, срок хранения, выборка), трассировки
(выборка по хвосту с сохранением ошибок и медленных), алерты по симптомам и скорости расхода бюджета,
связку метрика → трасса → журнал. Опорные числа для рубрики: число временных рядов гистограммы задержки
(сервисы × экземпляры × точки × коды × корзины) и во сколько раз его умножит метка с идентификатором
пользователя; объём журналов в сутки (поток × байт × 86 400).
Особенность варианта: взрыв кардинальности, усталость от алертов, выборка трасс теряет редкие ошибки.
Рубрика 0–4: метрики и кардинальность с числами, журналы с объёмом, трассы, алерты, особенность.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant
from assessment_bank.gen_utils import plural

FAMILY_ID = "devops.mon.lead_observability_open"

CONTEXTS = ["платёжный шлюз", "маркетплейс", "платформа найма", "онлайн-кинотеатр", "сервис такси",
            "интернет-банк"]

TWISTS = {
    "cardinality": dict(
        text="команда добавила к метрике задержки метку user_id — активных пользователей ≈ {users}",
        crit=("метка user_id при ≈ {users} пользователях умножает ряды гистограммы до ≈ {series_uid} — хранилище "
              "метрик ляжет; идентификаторы — в трассы и журналы, а не в метки; лимит рядов на сервис и "
              "проверка кардинальности в CI или на приёме (relabel, отбрасывание)"),
        strong=("метка user_id превратит ≈ {series} рядов в ≈ {series_uid} — это смерть хранилища метрик; "
                "идентификаторы пользователя кладу в трассы и журналы, в метках — только ограниченные множества, "
                "ставлю лимит рядов на сервис и отбрасывание лишних меток на приёме.")),
    "fatigue": dict(
        text="дежурные получают ≈ {alerts} алертов в неделю, {noise} % из них не требуют действий",
        crit=("усталость от алертов ({alerts} в неделю, {noise} % неприменимых): алерт — только по симптомам "
              "пользователя (SLO, скорость расхода бюджета, многооконный), причины — на панели, а не пейджером; "
              "у каждого алерта — инструкция и владелец, ежемесячный разбор шумных; цель — единицы страниц в "
              "неделю"),
        strong=("{alerts} алертов в неделю, из них {noise} % без действий, — дежурный перестаёт реагировать; "
                "пейджер оставляю только для симптомов (скорость расхода бюджета SLO в двух окнах), причины "
                "(CPU, очередь) — на панели; у каждого алерта — инструкция и владелец, шумные разбираю раз в месяц.")),
    "sampling": dict(
        text="трассы пишутся с выборкой {head} % в начале запроса, а редкие ошибки оплаты (≈ {rare} % запросов) в трассах не находятся",
        crit=("выборка {head} % в начале запроса при ошибках ≈ {rare} % — трасса нужной ошибки сохраняется в "
              "{head} % случаев; выборка по хвосту (решение после завершения: все ошибки и медленные, плюс доля "
              "обычных), связь трассы с журналом по trace_id, примеры (exemplars) в метриках"),
        strong=("при выборке {head} % в начале запроса трасса редкой ошибки сохраняется лишь в {head} % случаев; "
                "перехожу на выборку по хвосту: сохраняю все ошибки и медленные плюс небольшую долю обычных, "
                "trace_id пишу в журналы и в примеры к метрикам задержки.")),
}


def _build(rng, ctx):
    services = rng.choice([20, 40, 80])
    inst = rng.choice([3, 6, 10])
    endpoints = rng.choice([8, 15, 25])
    codes = 5
    buckets = rng.choice([10, 14])
    rps = rng.choice([2000, 5000, 15000])
    log_b = rng.choice([400, 800, 1500])
    lines = rng.choice([2, 4, 8])                      # строк журнала на запрос
    users = rng.choice([50_000, 200_000, 1_000_000])
    series = services * inst * endpoints * codes * buckets
    series_uid = series * users
    log_gb = rps * lines * log_b * 86400 / 1e9
    kind = rng.choice(sorted(TWISTS))
    v = dict(users=fmt_num(users, 0), series=fmt_num(series, 0), series_uid=f"{series_uid:.1e}".replace(".", ","),
             alerts=rng.choice([150, 300, 600]), noise=rng.choice([60, 75, 90]), head=rng.choice([1, 5, 10]),
             rare=rng.choice(["0,05", "0,1", "0,3"]))
    T = TWISTS[kind]
    stem = (f"Вы — ведущий SRE; система — {ctx}: {services} сервисов по {inst} экземпляров, в среднем по {endpoints} "
            f"конечных точек на сервис, поток — {fmt_num(rps, 0)} запросов в секунду, каждый запрос пишет ≈ {lines} "
            f"{plural(lines, 'строку', 'строки', 'строк')} журнала по ≈ {log_b} байт. Гистограмма задержки — {buckets} корзин, коды ответа сведены в 5 "
            f"классов. Сейчас единой наблюдаемости нет: у каждой команды свои панели. Особенность: "
            f"{T['text'].format(**v)}.\n\nСпроектируйте наблюдаемость: какие метрики и метки (посчитайте число "
            "временных рядов задержки), журналы (структура, объём в сутки — посчитайте, срок хранения, выборка), "
            "трассы и выборка, какие алерты будят дежурного, как перейти от алерта к причине, ответ на особенность. "
            "Ответ — 10–16 предложений.")
    criteria = [
        ("metrics", (f"Метрики по симптомам (RED: поток, ошибки, задержка; USE для ресурсов) и SLO; ряды задержки: "
                     f"{services} × {inst} × {endpoints} × 5 × {buckets} ≈ {fmt_num(series, 0)}; метки — только "
                     f"ограниченные множества, бюджет рядов на сервис"), 0.2),
        ("logs", (f"Журналы: структурированные (JSON) с trace_id, уровни; объём ≈ {fmt_num(rps, 0)} × {lines} × "
                  f"{log_b} Б × 86 400 ≈ {fmt_num(log_gb, 0)} ГБ в сутки — горячее хранение дни, холодное дольше, "
                  f"выборка или снижение уровня для «успешных» строк, PII маскируется"), 0.18),
        ("traces", ("Трассы: распространение контекста (W3C traceparent) через все сервисы и очереди, выборка по "
                    "хвосту (все ошибки и медленные), связь метрика → трасса → журнал (exemplars, trace_id)"), 0.16),
        ("alerts", ("Алерты: пейджер — по симптомам пользователя (скорость расхода бюджета SLO, многооконный), "
                    "причины — на панелях; у каждого алерта владелец и инструкция; панели по сервисам из шаблона"),
         0.18),
        ("twist", T["crit"].format(**v), 0.28),
    ]
    strong = (f"Метрики — RED по каждому сервису и USE по ресурсам, SLO на ключевые пути; рядов задержки "
              f"≈ {services} × {inst} × {endpoints} × 5 × {buckets} ≈ {fmt_num(series, 0)}, метки — только ограниченные "
              f"множества, бюджет рядов на сервис. Журналы — JSON с trace_id: ≈ {fmt_num(log_gb, 0)} ГБ в сутки, поэтому "
              f"горячее хранение — несколько дней, дальше холодное, успешные строки — с выборкой, персональные "
              f"данные маскирую. Трассы — W3C traceparent через сервисы и очереди, выборка по хвосту, из метрики "
              f"задержки — переход в пример трассы, из трассы — в журналы по trace_id. Пейджер — только по скорости "
              f"расхода бюджета SLO в двух окнах, у алерта владелец и инструкция. " + T["strong"].format(**v))
    medium = ("Поставить Prometheus, Grafana, Loki и Jaeger, собрать метрики со всех сервисов, настроить алерты на "
              "ошибки и задержку.")
    weak = "Писать в журнал всё подробно и искать по нему, когда что-то сломается."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: ≈ {series} рядов задержки; ≈ {series_uid:.2e} с меткой user_id; журналы "
                       f"≈ {log_gb:.0f} ГБ в сутки. «Писать всё и искать» — критерий logs не выше 1. Особенность — {kind}."),
                explanation=f"≈ {series} рядов задержки; журналы ≈ {log_gb:.0f} ГБ/сутки; особенность — {kind}.",
                params=dict(kind=kind, services=services, inst=inst, endpoints=endpoints, buckets=buckets, rps=rps,
                            log_b=log_b, lines=lines, users=users, series=series, log_gb=round(log_gb, 1)))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

"""devops.ci.lead_cicd_platform_open — open_answer (Lead): конвейер CI/CD для многих сервисов, который не тормозит команды.

Дан репозиторий варианта (монорепозиторий или много репозиториев): коммитов в час в пике, длительность
конвейера, число исполнителей, число нестабильных тестов и вероятность ложного падения каждого. Опорные
числа для рубрики: вероятность ложного «красного» конвейера 1 − (1 − f)^k при k нестабильных тестах
с частотой f и нужное число исполнителей в пике (коммитов в час × минут / 60 с запасом) против текущего.
Кандидат проектирует: сборку только затронутого и кэш, параллелизм, карантин нестабильных тестов с
владельцем и сроком, артефакт собирается один раз и продвигается по средам, выкладка (канарейка или
поэтапная с автоматическим откатом по метрикам), секреты и цепочка поставки (подпись, SBOM), метрики DORA.
Особенность варианта: нестабильные тесты, очередь в пике, секреты в переменных конвейера.
Рубрика 0–4: скорость с числами, нестабильные тесты, продвижение артефакта и выкладка, особенность, метрики.
"""
from __future__ import annotations

import math

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant

FAMILY_ID = "devops.ci.lead_cicd_platform_open"

CONTEXTS = [("интернет-банк", "монорепозиторий"), ("маркетплейс", "монорепозиторий"),
            ("платформа найма", "много репозиториев"), ("сервис доставки", "много репозиториев"),
            ("онлайн-школа", "монорепозиторий"), ("страховая компания", "много репозиториев")]

TWISTS = {
    "flaky": dict(
        text="разработчики привыкли нажимать «перезапустить» — каждый третий конвейер перезапускают",
        crit=("нестабильные тесты: при {k} тестах с ложным падением {f} % вероятность ложного «красного» ≈ "
              "{p_red} % — перезапуски маскируют настоящие падения; автоматический карантин по истории "
              "(тест падает и проходит на одном коммите), владелец и срок исправления, бюджет нестабильности, "
              "повтор только для теста в карантине, а не всего конвейера"),
        strong=("{k} нестабильных тестов по {f} % дают ложный «красный» в ≈ {p_red} % конвейеров — отсюда "
                "привычка перезапускать; ставлю автоматический карантин по истории (падает и проходит на одном "
                "коммите), каждому — владелец и срок, а повтор разрешаю только для тестов в карантине.")),
    "queue": dict(
        text="в пике (перед релизом) ожидание исполнителя доходит до {wait} мин",
        crit=("очередь в пике: нужно ≈ {need} исполнителей (коммитов в час × минут конвейера / 60, с запасом), "
              "сейчас {runners}; автомасштабирование исполнителей по длине очереди, отмена устаревших конвейеров "
              "той же ветки, приоритет главной ветки, сокращение длительности — сборка только затронутого"),
        strong=("в пике нужно ≈ {need} исполнителей, а их {runners} — отсюда ожидание до {wait} мин; ставлю "
                "автомасштабирование исполнителей по длине очереди, отменяю устаревшие конвейеры той же ветки, "
                "главной ветке даю приоритет и сокращаю длительность сборкой только затронутого.")),
    "secrets": dict(
        text="ключи к продакшену лежат в переменных конвейера и доступны любому запуску из любой ветки",
        crit=("секреты в переменных конвейера доступны из любой ветки (в том числе из запроса на слияние с "
              "чужим кодом): короткоживущие учётные данные по OIDC от конвейера к облаку, секреты продакшена — "
              "только для защищённых веток и окружений с подтверждением, подпись артефактов и SBOM, "
              "ротация утёкших"),
        strong=("ключи продакшена в переменных, доступных любой ветке, — любой запрос на слияние может их "
                "вывести; перевожу на короткоживущие учётные данные по OIDC, секреты продакшена — только для "
                "защищённых веток и окружения с подтверждением, артефакты подписываю, текущие ключи ротирую.")),
}


def _build(rng, ctx_t):
    ctx, repo = ctx_t
    services = rng.choice([30, 60, 120])
    commits_h = rng.choice([40, 80, 150])
    dur = rng.choice([25, 40, 60])                     # минут конвейер
    runners = rng.choice([20, 30, 40])
    k = rng.choice([15, 30, 60])
    f = rng.choice([0.5, 1, 2])                        # % ложных падений на тест
    kind = rng.choice(sorted(TWISTS))
    p_red = 100 * (1 - (1 - f / 100) ** k)
    need = math.ceil(commits_h * dur / 60 * 1.3)
    v = dict(k=k, f=fmt_num(f, 1), p_red=fmt_num(p_red, 0), need=need, runners=runners, wait=rng.choice([20, 35, 50]))
    T = TWISTS[kind]
    stem = (f"Вы — ведущий DevOps-инженер; компания — {ctx}, {repo}, {services} сервисов. В пике — ≈ {commits_h} "
            f"коммитов в час, конвейер (сборка, тесты, выкладка на тестовую среду) идёт ≈ {dur} мин, исполнителей — "
            f"{runners}. В наборе тестов ≈ {k} нестабильных, каждый ложно падает примерно в {fmt_num(f, 1)} % запусков. "
            f"В продакшен выкладывают раз в неделю вручную. Особенность: {T['text'].format(**v)}.\n\n"
            "Предложите, как перестроить CI/CD: что ускорит обратную связь (посчитайте, сколько исполнителей нужно в "
            "пике и как часто конвейер ложно «красный»), что делать с нестабильными тестами, как артефакт доходит "
            "до продакшена и как выкладка откатывается сама, ответ на особенность и по каким метрикам поймёте, что "
            "стало лучше. Ответ — 10–16 предложений.")
    criteria = [
        ("speed", (f"Скорость: сборка и тесты только затронутого (граф зависимостей), кэш сборки и зависимостей, "
                   f"параллельные задания; исполнителей в пике ≈ {commits_h} × {dur} / 60 × 1,3 ≈ {need} против "
                   f"{runners} — автомасштабирование по очереди, отмена устаревших конвейеров ветки"), 0.2),
        ("flaky", (f"Нестабильные тесты: ложный «красный» ≈ 1 − (1 − {fmt_num(f / 100, 3)})^{k} ≈ {fmt_num(p_red, 0)} % "
                   f"конвейеров; карантин по истории, владелец и срок, повтор только теста в карантине"), 0.18),
        ("promote", ("Артефакт собирается один раз (неизменяемый образ с версией) и продвигается по средам; выкладка "
                     "частая и малыми порциями — канарейка или поэтапная с автоматическим откатом по метрикам SLO; "
                     "флаги функций отделяют выкладку от включения"), 0.2),
        ("twist", T["crit"].format(**v), 0.24),
        ("metrics", ("Метрики DORA: частота выкладок, время от коммита до продакшена, доля неудачных изменений, время "
                     "восстановления; плюс p50/p95 длительности конвейера, ожидание исполнителя, доля перезапусков"),
         0.18),
    ]
    strong = (f"Сборка и тесты — только затронутого по графу зависимостей, кэш зависимостей и сборки, параллельные "
              f"задания. В пике нужно ≈ {commits_h} × {dur} / 60 × 1,3 ≈ {need} исполнителей при {runners} — "
              f"автомасштабирование по очереди и отмена устаревших конвейеров ветки. Ложный «красный» сейчас ≈ "
              f"{fmt_num(p_red, 0)} % ({k} тестов по {fmt_num(f, 1)} %) — карантин по истории с владельцем и сроком. "
              f"Образ собирается один раз и продвигается по средам, выкладка — ежедневно канарейкой с автоматическим "
              f"откатом по SLO, функции включаются флагами. " + T["strong"].format(**v) + " Смотрю метрики DORA "
              "(частота выкладок, время от коммита до продакшена, доля неудачных изменений, время восстановления), "
              "p95 длительности конвейера и долю перезапусков.")
    medium = ("Добавить кэширование и параллельные задания, нестабильные тесты отключить, выкладывать через "
              "канарейку.")
    weak = "Купить больше исполнителей и запретить коммиты перед релизом."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: ложный «красный» ≈ {p_red:.0f} %; нужно ≈ {need} исполнителей при {runners}. "
                       f"«Отключить нестабильные тесты навсегда» без карантина и владельца — критерий flaky не выше 1. "
                       f"Особенность — {kind}."),
                explanation=f"Ложный «красный» ≈ {p_red:.0f} %, исполнителей ≈ {need}; особенность — {kind}.",
                params=dict(kind=kind, repo=repo, services=services, commits_h=commits_h, dur=dur, runners=runners,
                            k=k, f=f, p_red=round(p_red, 1), need=need))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

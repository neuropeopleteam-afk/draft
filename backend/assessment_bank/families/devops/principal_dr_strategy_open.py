"""devops.strategy.principal_dr_open — open_answer (Principal): стратегия отказоустойчивости между регионами.

Дано: система в одном регионе (дата-центре), требования бизнеса к RTO/RPO по классам сервисов, бюджет,
ограничение варианта (регуляторное хранение данных в стране, бюджет не больше определённой доли текущих
расходов или стабильная запись с конфликтами при active-active). Кандидат выбирает схему по классам
(резервные копии, тёплый резерв, active-passive, active-active) с ценой, решает вопросы данных
(репликация, задержка и RPO, разрешение конфликтов), описывает переключение и его учения, порядок
внедрения и метрики. Уровень Principal: решение на годы, баланс риска и денег для всей компании.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import scenario_variant

FAMILY_ID = "devops.strategy.principal_dr_open"

CONTEXTS = ["маркетплейс", "банк", "сервис доставки", "платформа онлайн-обучения", "оператор связи",
            "медицинская информационная система"]

CONSTRAINTS = {
    "budget": dict(
        text="бюджет на отказоустойчивость — не больше {cap} % текущих расходов на инфраструктуру",
        core=("active-active для всего не по карману: тёплый резерв или active-passive только для критичного класса, "
              "остальным — резервные копии в другой площадке с проверкой восстановления; цена каждой схемы "
              "считается явно")),
    "residency": dict(
        text="персональные данные по закону должны храниться только на площадках в стране, а вторая площадка в стране у провайдера одна",
        core=("вторая площадка — единственная в стране, поэтому для данных: синхронная или асинхронная репликация "
              "туда же, а для третьей копии — резервные копии у другого провайдера в стране; схема переключения "
              "проверяется на соответствие требованиям хранения")),
    "conflicts": dict(
        text="продукт хочет active-active, а запись идёт в одни и те же сущности (остатки, балансы) из обоих регионов",
        core=("active-active для изменяемых общих сущностей требует разрешения конфликтов: закрепление сущности за "
              "регионом (домашний регион) или синхронный консенсус с ценой задержки; active-active — только для "
              "чтения и сущностей без общих записей")),
}


def _build(rng, ctx):
    kind = rng.choice(sorted(CONSTRAINTS))
    C = CONSTRAINTS[kind]
    v = dict(services=rng.choice([40, 80, 150]), crit=rng.choice([5, 8, 12]), rto=rng.choice([15, 30, 60]),
             rpo=rng.choice([0, 1, 5]), rto2=rng.choice([4, 8, 24]), cap=rng.choice([15, 25, 35]),
             lag=rng.choice([20, 40, 80]), outage=rng.choice([6, 9, 14]))
    cons = C["text"].format(**v)
    rpo_s = "без потери подтверждённых операций" if v["rpo"] == 0 else f"не больше {v['rpo']} мин потерянных данных"
    stem = (f"Вы — главный инженер, компания — {ctx}. Все {v['services']} сервисов работают в одном "
            f"регионе. Недавний сбой площадки остановил всё на {v['outage']} часов. Требования бизнеса: "
            f"{v['crit']} критичных сервисов (оплата, вход, основное действие) — восстановление за {v['rto']} мин, "
            f"{rpo_s}; остальные — за {v['rto2']} ч, потеря до часа данных допустима. Задержка сети до второго "
            f"региона — {v['lag']} мс. Ограничение: {cons}.\n\n"
            "Предложите стратегию на 1–2 года: какие схемы (резервные копии, тёплый резерв, active-passive, "
            "active-active) для каких классов и почему; как устроены данные и чего стоит выбранный RPO; как "
            "происходит и проверяется переключение; в каком порядке внедряете и чем измеряете готовность. "
            "Ответ — 15–25 предложений.")
    sync_cost = (f"синхронная репликация на {v['lag']} мс добавляет не меньше {v['lag']} мс к каждой записи"
                 if v["rpo"] == 0 else f"асинхронная репликация с отставанием меньше {v['rpo']} мин")
    criteria = [
        ("tiering", (f"Разные схемы по классам с ценой: для {v['crit']} критичных (RTO {v['rto']} мин) — тёплый "
                     f"резерв или active-passive, для остальных (RTO {v['rto2']} ч) — резервные копии с "
                     "восстановлением; не «active-active для всех»"), 0.25),
        ("data", (f"Данные и RPO: {sync_cost}; зависимость RPO от схемы репликации, порядок записи и разрешение "
                  f"конфликтов, общие зависимости (DNS, секреты, очереди) тоже во втором регионе"), 0.2),
        ("constraint", f"Учёт ограничения варианта: {C['core']}", 0.2),
        ("failover", ("Переключение: кто и по какому критерию решает, автоматизация с ручным подтверждением, "
                      "регулярные учения (game day) с измерением фактических RTO/RPO, обратное переключение"), 0.2),
        ("plan_metrics", ("Порядок и метрики: начать с критичного класса и проверяемого восстановления копий; "
                          "измерять фактические RTO/RPO на учениях, долю сервисов с проверенным планом, стоимость "
                          "резерва"), 0.15),
    ]
    strong = (f"Схемы — по классам, а не одна на всё. Для {v['crit']} критичных сервисов с RTO {v['rto']} мин — "
              f"active-passive с тёплым резервом во втором регионе: инфраструктура готова, данные реплицируются, "
              f"переключение — минуты. Для остальных {v['services'] - v['crit']} сервисов RTO {v['rto2']} ч позволяет "
              f"обойтись резервными копиями в другой площадке и автоматическим развёртыванием — это на порядок "
              f"дешевле. Данные: {sync_cost}; это осознанная цена RPO, и я считаю, какие операции её выдержат. "
              f"Во втором регионе должны быть и общие зависимости — DNS, секреты, очереди, иначе переключение "
              f"упрётся в них. Ограничение: {C['core']}. Переключение запускается по критерию (недоступность "
              f"площадки дольше N минут), автоматически готовится и подтверждается дежурным руководителем; "
              f"обратное переключение описано отдельно. Раз в квартал — учения с реальным переключением, на них "
              f"измеряем фактические RTO и RPO. Порядок: сначала проверяемое восстановление копий для всех, затем "
              f"резерв для критичных, затем учения. Метрики: фактические RTO/RPO на учениях, доля сервисов с "
              f"проверенным планом, стоимость резерва в процентах расходов.")
    medium = ("Нужно развернуть второй регион, сделать active-active для всех сервисов и настроить репликацию "
              "баз данных, а также регулярно тестировать переключение.")
    weak = "Нужно делать резервные копии каждый день — этого достаточно."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=f"Ограничение варианта — {kind}; схема должна его учитывать.",
                explanation=f"Ограничение — {kind}: {cons}. Ожидаемо: {C['core']}.",
                params=dict(kind=kind, services=v["services"], crit=v["crit"], rto=v["rto"], rpo=v["rpo"],
                            lag=v["lag"]))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

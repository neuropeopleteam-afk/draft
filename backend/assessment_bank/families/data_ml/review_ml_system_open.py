def generate(seed: int):
    v = review_variant(FAMILY_ID, seed, contexts=_ctx_names(), facts=_facts, flaws=FLAWS, sound=SOUND, k=3, ask=ASK,
                       weak="Модель хорошая — AUC высокий; можно выкатывать, а потом посмотрим метрики.")
    return v

def _facts(rng, ctx_t):
    ctx, target = ctx_t
    n = rng.choice([2000, 5000, 20000])
    k = rng.choice([50, 100, 200])
    vals = dict(auc=rng.choice(["0,97", "0,98", "0,99"]), per_client=rng.choice([12, 30, 60]), k=k, n=n,
                top_pct=str(round(100 * k / n, 1)).replace(".", ","), pos=rng.choice(["0,8", "1,5", "3"]),
                label_days=rng.choice([30, 60, 90]), who=rng.choice(["клиентам", "пользователям"]))
    intro = (f"Вы — ведущий ML-инженер. Команда запускает модель «{ctx}» (целевая переменная — {target}) и принесла "
             f"на ревью дизайн-документ.")
    return vals, intro


def _ctx_names():
    return [c for c in CONTEXTS]



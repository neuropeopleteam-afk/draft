def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    feat, ctx, (lo, hi) = rng.choice(CONTEXTS)
    fn = rng.choice(["psi", "population_stability", "drift_psi"])
    nb = rng.choice([4, 5])
    for _ in range(1000):
        ref = sorted(rng.sample(range(lo, hi + 1), 3 * nb))
        edges = [ref[3 * i + 2] for i in range(nb - 1)]
        if all(edges[i] + 1 < edges[i + 1] for i in range(nb - 2)) and edges[0] > lo + 1 and edges[-1] < hi - 1:
            break
    rng.shuffle(ref)
    cands = _currents(rng, edges, lo, hi, nb)
    for c in cands[1:]:
        assert _psi("buggy", ref, c, edges) == _psi("good", ref, c, edges)
    assert _psi("buggy", ref, cands[0], edges) != _psi("good", ref, cands[0], edges)
    code = _code("buggy", fn)
    describe = lambda c: f"current = {c!r}"
    opts1, key1 = balanced_options(FAMILY_ID, seed, rng, (describe(cands[0]), None),
                                   [(describe(c), None) for c in cands[1:]], step=1)
    by_text = {describe(c): c for c in cands}
    chosen = rng.sample(DISTRACTORS, 3)
    opts2, key2 = balanced_options(FAMILY_ID, seed, rng, ("Заменить функцию на:", _code("good", fn)),
                                   [("Заменить функцию на:", _code(d, fn)) for d in chosen],
                                   step=2, salt="step2")
    # тесты шага 2: пусто в current, пусто в reference, разные размеры, совпадение
    t_cases = [([1, 2, 3, 4, 5, 6, 7, 8], [1, 1, 2, 2, 2, 1], [2, 4, 6]),
               ([1, 1, 2, 2, 5, 6, 7, 8], [1, 3, 4, 5, 7, 8, 8, 9, 2, 6], [2, 4, 6]),
               ([10, 20, 30, 40, 50, 60], [15, 25, 35, 45, 55, 65, 65, 65, 12], [20, 40]),
               ([3, 6, 9, 12], [12, 9, 6, 3], [4, 8])]
    for d in chosen:
        assert any(_psi(d, *t) != _psi("good", *t) for t in t_cases), d
    t_expected = "\n".join(repr(_psi("good", *t)) for t in t_cases)
    checks = []
    for o in opts1:
        cur = by_text[o.text]
        prog = code + f"\n\n\nprint({fn}({ref!r}, {cur!r}, {edges!r}))\n"
        checks.append(Check(name=f"step1:{o.id}", runner="python", program=prog,
                            expect="stdout_differs" if o.id == key1 else "stdout_equals",
                            expected_stdout=repr(_psi("good", ref, cur, edges))))
    for o in opts2:
        prog = o.code + "\n\n\n" + "\n".join(f"print({fn}({r!r}, {c!r}, {e!r}))" for r, c, e in t_cases) + "\n"
        checks.append(Check(name=f"step2:{o.id}", runner="python", program=prog,
                            embeds_display_code=False,
                            expect="stdout_equals" if o.id == key2 else "stdout_differs",
                            expected_stdout=t_expected))
    cond_name = rng.choice(sorted(CONDITIONS))
    cond = CONDITIONS[cond_name]
    stem = (f"Сервис мониторинга модели ({ctx}) раз в сутки считает PSI признака `{feat}`: "
            f"PSI = Σ (c_i − r_i)·ln(c_i / r_i), где r_i и c_i — доли эталонной (reference) и "
            f"текущей (current) выборки в корзине i. Границы корзин edges — квантили эталона; "
            f"значение, равное границе, попадает в нижнюю корзину. По регламенту пустая корзина "
            f"считается долей 0,0001, иначе логарифм не определён; PSI > 0,25 — алерт. Недавно "
            f"источник данных сломался, признак резко изменился, а алерта не было.\n"
            f"reference = {ref!r}\nedges = {edges!r}")
    steps = ob3_steps(
        "Шаг 1. На какой выборке current функция вернёт значение, отличающееся от PSI по "
        "регламенту?",
        "Шаг 2. Выберите исправленную функцию.",
        "Шаг 3. " + cond["text"] + " Ответьте развёрнуто (5–10 предложений).")
    why = {"ref_only": "пропускает корзины, пустые в эталоне, — недооценивает появление новых значений",
           "kl_only": "Σ c·ln(c/r) — это KL-дивергенция, а не PSI",
           "abs_diff": "|c − r|·ln(c/r) меняет знак слагаемых, где c < r",
           "ref_len": "доли текущей выборки делятся на размер эталона"}
    ak = AnswerKey(kind="steps", value={"1": key1, "2": key2, "3": "rubric"},
                   explanation=("Корзины, где одна из долей нулевая, пропускаются — а именно "
                                "они дают самый большой вклад при «схлопывании» признака. Шаг 1: "
                                "выборка, у которой опустела хотя бы одна корзина (остальные "
                                "заполняют все корзины, и функция совпадает с регламентом). "
                                "Шаг 2: заменить пропуск на max(доля, 0,0001). Дистракторы: "
                                + "; ".join(why[d] for d in chosen) + f". Шаг 3 — «{cond_name}»."))
    rubric = rubric_from({**cond, "notes": "Оценивается шаг 3; шаги 1–2 проверяются автоматически."})
    return build_variant(FAMILY_ID, seed, stem=stem, code=code, options=opts1 + opts2,
                         answer_key=ak, rubric=rubric, context=ctx, verification="execution",
                         checks=checks, steps=steps, defect_type="psi_zero_bins",
                         params={"distractors": chosen, "condition": cond_name, "bins": nb})

def _code(kind, fn):
    shares_ret = "        return [c / len(values) for c in counts]"
    if kind == "ref_len":
        shares_ret = "        return [c / len(reference) for c in counts]"
    lines = ["import math", "", "",
             f"def {fn}(reference, current, edges):",
             "    def shares(values):",
             "        counts = [0] * (len(edges) + 1)",
             "        for v in values:",
             "            counts[sum(v > e for e in edges)] += 1",
             shares_ret,
             "",
             "    total = 0.0",
             "    for r, c in zip(shares(reference), shares(current)):"]
    if kind == "buggy":
        lines += ["        if r == 0 or c == 0:", "            continue",
                  "        total += (c - r) * math.log(c / r)"]
    elif kind == "ref_only":
        lines += ["        if r == 0:", "            continue", "        c = max(c, 0.0001)",
                  "        total += (c - r) * math.log(c / r)"]
    elif kind == "kl_only":
        lines += ["        r, c = max(r, 0.0001), max(c, 0.0001)", "        total += c * math.log(c / r)"]
    elif kind == "abs_diff":
        lines += ["        r, c = max(r, 0.0001), max(c, 0.0001)",
                  "        total += abs(c - r) * math.log(c / r)"]
    else:  # good, ref_len
        lines += ["        r, c = max(r, 0.0001), max(c, 0.0001)",
                  "        total += (c - r) * math.log(c / r)"]
    lines.append("    return round(total, 4)")
    return "\n".join(lines)


def _shares(values, edges, denom=None):
    counts = [0] * (len(edges) + 1)
    for v in values:
        counts[sum(v > e for e in edges)] += 1
    return [c / (denom or len(values)) for c in counts]


def _psi(kind, ref, cur, edges):
    """Независимая модель каждой реализации (для подбора данных и ожидаемого вывода)."""
    rs = _shares(ref, edges)
    cs = _shares(cur, edges, len(ref) if kind == "ref_len" else None)
    total = 0.0
    for r, c in zip(rs, cs):
        if kind == "buggy":
            if r == 0 or c == 0:
                continue
        elif kind == "ref_only":
            if r == 0:
                continue
            c = max(c, EPS)
        else:
            r, c = max(r, EPS), max(c, EPS)
        if kind == "kl_only":
            total += c * math.log(c / r)
        elif kind == "abs_diff":
            total += abs(c - r) * math.log(c / r)
        else:
            total += (c - r) * math.log(c / r)
    return round(total, 4)


def _bucket(v, edges):
    return sum(v > e for e in edges)


def _sample_in(rng, edges, lo, hi, buckets):
    """Значение из заданной корзины (по границам edges и диапазону [lo, hi])."""
    b = rng.choice(buckets)
    bounds = [lo] + [e + 1 for e in edges]
    tops = list(edges) + [hi]
    return rng.randint(bounds[b], tops[b])


def _currents(rng, edges, lo, hi, nb):
    for _ in range(2000):
        n = rng.randint(8, 10)
        # ключ: признак «схлопнулся» — пусто как минимум в одной корзине
        keep = sorted(rng.sample(range(nb), rng.randint(1, nb - 2)))
        collapsed = [_sample_in(rng, edges, lo, hi, keep) for _ in range(n)]
        shifted = [_sample_in(rng, edges, lo, hi, [nb - 1] * 5 + list(range(nb))) for _ in range(n)]
        similar = [_sample_in(rng, edges, lo, hi, list(range(nb))) for _ in range(n)]
        skewed = [_sample_in(rng, edges, lo, hi, [0] * 4 + list(range(nb))) for _ in range(n)]
        cands = [collapsed, shifted, similar, skewed]
        full = [len({_bucket(v, edges) for v in c}) == nb for c in cands[1:]]
        if all(full) and len({tuple(c) for c in cands}) == 4:
            return cands
    raise RuntimeError("не удалось подобрать выборки")



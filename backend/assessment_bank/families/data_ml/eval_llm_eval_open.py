"""data_ml.eval.llm_eval_open — open_answer (Lead): система оценки функции на большой языковой модели.

Дана функция продукта варианта на LLM (ответы поддержки по базе знаний, разбор документов, черновики писем,
поиск по внутренней документации): текущая доля приемлемых ответов, нужная точность оценки, цена редкой,
но дорогой ошибки и её допустимая частота, ежедневный поток. Кандидат строит оценку: эталонный набор
(состав, срезы, размер — посчитать по точности), автоматические метрики и модель-судья с калибровкой по
разметке людей, ворота регрессии в CI при смене промпта, модели или базы знаний, онлайн-сигналы.
Опорные числа для рубрики: размер набора для ±m при доле p (n ≈ 1,96² · p(1 − p) / m²) и сколько примеров
нужно, чтобы с вероятностью 95 % увидеть хотя бы одну редкую ошибку частоты r (n ≈ 3 / r, «правило трёх»).
Особенность варианта: судья предпочитает длинные ответы, провайдер молча обновил модель, утечка эталонов
в промпт или в базу знаний.
Рубрика 0–4: набор и размер, судья и калибровка, ворота регрессии, особенность, онлайн-сигналы и редкие ошибки.
"""
from __future__ import annotations

import math

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant

FAMILY_ID = "data_ml.eval.llm_eval_open"

CONTEXTS = [("ответы службы поддержки по базе знаний", "совет, противоречащий правилам возврата"),
            ("разбор входящих договоров", "пропущенное условие о неустойке"),
            ("черновики писем клиентам банка", "обещание ставки, которой нет в тарифах"),
            ("поиск по внутренней документации", "ссылка на устаревший регламент безопасности"),
            ("ответы кандидатам на платформе найма", "дискриминирующая формулировка"),
            ("справка для пациентов клиники", "рекомендация дозировки препарата")]

TWISTS = {
    "length_bias": dict(
        text="модель-судья ставит длинным ответам в среднем на {bias} балла выше при той же оценке людей",
        crit=("смещение судьи к длине (+{bias} балла): калибровка судьи по разметке людей (согласие, κ), "
              "контроль длины (парное сравнение с перестановкой порядка, штраф или нормировка), проверка "
              "судьи на парах «короткий верный — длинный неверный»"),
        strong=("судья добавляет длинным ответам ≈ {bias} балла — значит, оптимизируя промпт по судье, мы "
                "научим модель многословию; калибрую судью по разметке людей (κ), сравниваю ответы парами с "
                "перестановкой порядка и держу контрольные пары «короткий верный — длинный неверный».")),
    "silent_update": dict(
        text="провайдер модели без предупреждения обновил версию — жалобы выросли в {x} раза за неделю",
        crit=("молчаливое обновление модели (жалобы ×{x}): закрепить версию модели в запросах, ворота регрессии "
              "на эталонном наборе при любой смене версии, ежедневный прогон контрольного поднабора по проду "
              "и сравнение распределения оценок, план отката на прошлую версию или другого провайдера"),
        strong=("жалобы выросли в {x} раза после молчаливого обновления — закрепляю версию модели, любую смену "
                "пропускаю через ворота на эталонном наборе, ежедневно прогоняю контрольный поднабор и сравниваю "
                "распределение оценок, держу откат на прошлую версию.")),
    "leak": dict(
        text="выяснилось, что {leak} % эталонных вопросов попали в примеры промпта и в базу знаний",
        crit=("утечка эталонов ({leak} % в промпте и базе знаний): оценка завышена; отделить набор разработки от "
              "закрытого контрольного набора с доступом по правилам, проверка пересечений (хэши, близость "
              "эмбеддингов) перед каждым прогоном, обновление контрольного набора из свежих обращений"),
        strong=("{leak} % эталонов оказались в промпте и базе знаний — оценка завышена; делю набор на "
                "разработочный и закрытый контрольный, перед прогоном проверяю пересечения по хэшам и близости "
                "эмбеддингов и пополняю контрольный набор свежими обращениями.")),
}


def _build(rng, ctx_t):
    ctx, rare = ctx_t
    p = rng.choice([0.7, 0.8, 0.85, 0.9])
    m = rng.choice([0.02, 0.03, 0.05])
    r = rng.choice([0.001, 0.002, 0.005])
    daily = rng.choice([3000, 10000, 40000])
    kind = rng.choice(sorted(TWISTS))
    n_acc = math.ceil(1.96 ** 2 * p * (1 - p) / m ** 2)
    n_rare = math.ceil(3 / r)
    v = dict(bias=rng.choice(["0,4", "0,6", "0,9"]), x=rng.choice([2, 3, 4]), leak=rng.choice([10, 18, 30]))
    T = TWISTS[kind]
    stem = (f"Вы — ведущий ML-инженер. Функция на большой языковой модели — {ctx}; поток ≈ {fmt_num(daily, 0)} "
            f"обращений в сутки. По выборочной ручной проверке приемлемых ответов ≈ {fmt_num(100 * p, 0)} %. Команда "
            f"хочет менять промпт и базу знаний еженедельно и видеть, стало ли лучше, с точностью ±{fmt_num(100 * m, 0)} "
            f"п. п. (95 %). Самая дорогая ошибка — «{rare}»; допустимая частота — не больше {fmt_num(100 * r, 1)} % "
            f"ответов. Особенность: {T['text'].format(**v)}.\n\nОпишите систему оценки: эталонный набор (что в нём, "
            "какие срезы и сколько примеров — посчитайте), автоматические метрики и модель-судья (как ей доверять), "
            "ворота регрессии при смене промпта, модели или базы знаний, как ловить редкую дорогую ошибку, ответ "
            "на особенность и какие сигналы смотреть в проде. Ответ — 10–16 предложений.")
    criteria = [
        ("set", (f"Эталонный набор: реальные обращения по срезам (темы, сложность, язык, редкие случаи), ответы-"
                 f"эталоны или критерии; размер для ±{fmt_num(100 * m, 0)} п. п. при доле ≈ {fmt_num(100 * p, 0)} % — "
                 f"n ≈ 1,96² · p(1 − p) / m² ≈ {fmt_num(n_acc, 0)}; для сравнения двух версий — парное сравнение на "
                 f"одних и тех же примерах"), 0.22),
        ("judge", ("Модель-судья: рубрика с явными критериями, калибровка по разметке людей на подвыборке (согласие, "
                   "κ, матрица ошибок), повторная проверка калибровки при смене судьи, люди — на спорных и "
                   "пограничных"), 0.18),
        ("gate", ("Ворота регрессии в CI: любая смена промпта, модели или базы знаний прогоняется на наборе, "
                  "выпуск блокируется при падении доли приемлемых больше порога или росте дорогих ошибок; версии "
                  "промпта, модели и базы знаний закреплены"), 0.16),
        ("twist", T["crit"].format(**v), 0.22),
        ("rare", (f"Редкая ошибка «{rare}» с допустимой частотой {fmt_num(100 * r, 1)} %: на общем наборе из "
                  f"≈ {fmt_num(n_acc, 0)} её не увидеть — нужен целевой набор провокаций и ≈ 3 / r ≈ {fmt_num(n_rare, 0)} "
                  f"примеров, чтобы с 95 % увидеть хотя бы одну; отдельный классификатор-ограничитель в проде и "
                  f"онлайн-сигналы (жалобы, эскалации, выборочная проверка ≈ доли потока)"), 0.22),
    ]
    strong = (f"Набор — реальные обращения по срезам с эталонами или критериями; для ±{fmt_num(100 * m, 0)} п. п. при "
              f"{fmt_num(100 * p, 0)} % нужно ≈ 1,96² · {fmt_num(p, 2)} · {fmt_num(1 - p, 2)} / {fmt_num(m, 2)}² ≈ "
              f"{fmt_num(n_acc, 0)} примеров, версии сравниваю парно на одних примерах. Судья работает по рубрике и "
              f"откалиброван по разметке людей (κ на подвыборке), спорные смотрят люди. Любая смена промпта, модели "
              f"или базы знаний проходит ворота в CI, версии закреплены. " + T["strong"].format(**v) +
              f" Ошибку «{rare}» на общем наборе не увидеть: при частоте {fmt_num(100 * r, 1)} % нужно ≈ 3 / r ≈ "
              f"{fmt_num(n_rare, 0)} примеров на одну находку с 95 %, поэтому держу целевой набор провокаций, "
              f"ограничитель в проде и онлайн-сигналы — жалобы, эскалации, выборочную проверку.")
    medium = ("Собрать эталонный набор из нескольких сотен вопросов, оценивать ответы моделью-судьёй и прогонять "
              "перед выпуском; смотреть жалобы пользователей.")
    weak = "Попросить нескольких сотрудников проверить пару десятков ответов после каждого изменения."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: n ≈ {n_acc} для ±{m} при p = {p}; ≈ {n_rare} для редкой ошибки частоты {r} "
                       f"(правило трёх). Судья без калибровки по людям — критерий judge не выше 1. Особенность — {kind}."),
                explanation=f"n ≈ {n_acc} для точности, ≈ {n_rare} для редкой ошибки; особенность — {kind}.",
                params=dict(kind=kind, p=p, m=m, r=r, daily=daily, n_acc=n_acc, n_rare=n_rare))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

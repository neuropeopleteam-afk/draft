"""data_ml.strategy.ml_platform_open — open_answer (Principal): стратегия ML-платформы компании.

Дано: число ML-команд и моделей в продакшне, у каждой команды свой путь до продакшна, главная боль задаётся
параметром варианта (долгий путь от идеи до продакшна, тихие деградации моделей или рост стоимости
вычислений), регуляторные требования к части моделей. Кандидат определяет объём платформы от боли, что
стандартизировать и чего сознательно не делать, строить или покупать, как внедрять без принуждения,
как управлять рисками моделей и чем измерить успех. Уровень Principal: решение для многих команд на годы.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import scenario_variant

FAMILY_ID = "data_ml.strategy.ml_platform_open"

CONTEXTS = ["банк", "маркетплейс", "платформа найма", "страховая компания", "телеком-оператор", "сеть клиник"]

PAINS = {
    "lead_time": dict(
        text="от готовой модели до продакшна в среднем {weeks} недель: у каждой команды свой путь выкладки и ручные согласования",
        core=("сначала — «мощёная дорога» выкладки: реестр моделей, шаблон сервиса инференса, автоматические проверки "
              "качества и совместимости перед выкладкой, единый процесс согласования; хранилище признаков — позже "
              "и только для признаков, которые переиспользуют несколько команд"),
        metric="время от готовой модели до продакшна ≤ 2 недель для моделей на мощёной дороге"),
    "silent_decay": dict(
        text="за полгода {incidents} случаев тихой деградации моделей, замеченной бизнесом спустя недели",
        core=("сначала — наблюдаемость моделей: журналирование входов и предсказаний, мониторинг дрейфа и качества "
              "по мере прихода меток, владельцы и алерты, реестр с версиями данных; выкладку и обучение у команд "
              "пока не трогаю"),
        metric="доля моделей с мониторингом дрейфа и качества — 100 % для критичных, время обнаружения деградации ≤ 2 дней"),
    "cost": dict(
        text="расходы на вычисления для обучения и инференса растут на {growth} % в квартал, загрузка GPU — около {util} %",
        core=("сначала — общий пул вычислений с очередью и квотами, учёт затрат по командам и моделям, правила для "
              "инференса (пакетная обработка, квантизация, автомасштабирование); остальные компоненты платформы — "
              "позже"),
        metric="загрузка GPU ≥ 60 %, стоимость тысячи предсказаний — минус треть, рост затрат ниже роста трафика"),
}


def _build(rng, ctx):
    kind = rng.choice(sorted(PAINS))
    P = PAINS[kind]
    v = dict(teams=rng.choice([5, 8, 12]), models=rng.choice([30, 60, 120]), weeks=rng.choice([8, 12, 16]),
             incidents=rng.choice([4, 6, 9]), growth=rng.choice([25, 40, 60]), util=rng.choice([15, 20, 25]),
             reg=rng.choice([10, 20, 30]), people=rng.choice([6, 8, 10]))
    pain = P["text"].format(**v)
    stem = (f"Вы — главный инженер по машинному обучению, компания — {ctx}. {v['teams']} ML-команд, "
            f"{v['models']} моделей в продакшне, у каждой команды свой путь обучения и выкладки. Главная боль: {pain}. "
            f"Около {v['reg']} % моделей влияют на решения о клиентах и подпадают под внутренние требования к "
            f"управлению рисками моделей. Под платформу дают команду из {v['people']} инженеров на год.\n\n"
            "Предложите стратегию ML-платформы: что строите первым и почему, что сознательно не делаете, строить "
            "или брать готовое, как команды перейдут на платформу, как будете управлять рисками моделей и чем "
            "измерите успех. Ответ — 15–25 предложений.")
    criteria = [
        ("scope", f"Объём от боли ({pain}), а не «платформа для всего»: {P['core']}", 0.25),
        ("build_buy", ("Строить или брать: готовые открытые или облачные компоненты там, где нет отличия "
                       "(оркестрация, реестр, трекинг экспериментов), своё — только интеграция и мощёная дорога; "
                       f"соотносит с командой из {v['people']} человек и стоимостью сопровождения"), 0.2),
        ("adoption", ("Внедрение без принуждения: 1–2 пилотные команды с самой острой болью, мощёная дорога легче "
                      "своего пути, миграция по мере выкладки новых версий, поддержка и документация; критерий "
                      "остановки, если пилоты не выигрывают"), 0.2),
        ("governance", ("Риски моделей: реестр с владельцем, версиями данных и кода, обязательная оценка и "
                        f"согласование для {v['reg']} % моделей, влияющих на клиентов (документация, проверка на "
                        "смещения, журнал решений), остальным — облегчённый путь"), 0.2),
        ("metrics", f"Метрики с числами: {P['metric']}; доля моделей на платформе; базовая линия до начала", 0.15),
    ]
    strong = (f"Платформа отвечает на конкретную боль — {pain}. Поэтому {P['core']}. Универсальную платформу «для "
              f"всего» не строю: с командой из {v['people']} человек её не сопроводить. Беру готовое там, где нет "
              f"отличия, — оркестрацию, реестр моделей и трекинг экспериментов (открытые или облачные компоненты), "
              f"своё — интеграции и мощёную дорогу, то есть путь, который проще, чем свой у команды. Внедрение — "
              f"через две пилотные команды с самой острой болью; остальные переходят при выкладке новых версий "
              f"моделей, без приказа; если через квартал пилоты не выигрывают по метрике, пересматриваю объём. Риски "
              f"моделей: у каждой модели в реестре владелец, версии данных и кода; для {v['reg']} % моделей, влияющих "
              f"на клиентов, — обязательная документация, проверка на смещения по группам, журнал решений и "
              f"согласование перед выкладкой, для остальных — облегчённый путь. Метрики: {P['metric']}; доля моделей "
              f"на платформе; базовая линия — текущий квартал.")
    medium = ("Нужно построить ML-платформу: хранилище признаков, реестр моделей, мониторинг и CI/CD для моделей, "
              "и перевести на неё все команды.")
    weak = "Нужно купить одну большую MLOps-платформу и обязать все команды перейти на неё за месяц."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=f"Боль варианта — {kind}; первый компонент должен следовать из неё.",
                explanation=f"Боль — {kind}: {pain}. Ожидаемо: {P['core']}.",
                params=dict(kind=kind, teams=v["teams"], models=v["models"], people=v["people"], reg=v["reg"]))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

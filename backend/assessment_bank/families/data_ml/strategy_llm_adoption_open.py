"""data_ml.strategy.llm_adoption_open — open_answer (Principal): стратегия внедрения больших языковых моделей в компании.

Дана компания варианта: несколько продуктовых команд хотят функции на LLM; поток запросов сейчас и через
год, средние длины входа и выхода, цена внешнего API за миллион токенов, производительность и месячная
стоимость своего GPU-сервера с открытой моделью, люди на эксплуатацию. Опорные числа для рубрики:
месячная стоимость внешнего API сейчас и через год, число GPU-серверов в пике (выходные токены в секунду
в пике / производительность × запас) и месячная стоимость своей установки — что дешевле сейчас и что через год.
Кандидат предлагает общую платформу (шлюз к моделям, учёт расходов по командам, ограничители, оценка,
каталог промптов), выбор «внешний API / своя установка / гибрид» с ценой, управление рисками и этапы.
Особенность варианта: персональные данные нельзя передавать за периметр, требование задержки, рост
цены провайдера и зависимость от одного поставщика.
Рубрика 0–4: числа и выбор с ценой, платформа, риски и ограничители, особенность, этапы и метрики.
"""
from __future__ import annotations

import math

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant

FAMILY_ID = "data_ml.strategy.llm_adoption_open"

CONTEXTS = ["банк", "страховая компания", "телеком-оператор", "крупный онлайн-ритейлер", "логистическая компания",
            "группа частных клиник"]

TWISTS = {
    "pd": dict(
        text="в запросах части функций ({pd} % потока) есть персональные данные клиентов, передавать их за периметр нельзя",
        crit=("персональные данные ({pd} % потока): эти запросы — только в своей установке внутри периметра (или "
              "обезличивание до отправки с проверкой качества обезличивания), маршрутизация в шлюзе по "
              "классификации данных, журнал обращений; расчёт своей установки — хотя бы на эту долю потока"),
        strong=("{pd} % потока несут персональные данные — их маршрутизирую в шлюзе только на свою установку "
                "внутри периметра (или обезличиваю до отправки с проверкой), остальное может идти во внешний API; "
                "значит, своя установка нужна в любом случае хотя бы на эту долю.")),
    "latency": dict(
        text="функции в звонках колл-центра требуют первого токена не позже {ttft} мс (p95)",
        crit=("задержка первого токена ≤ {ttft} мс (p95): внешний API с общим пулом даёт хвосты — своя установка "
              "или выделенная ёмкость рядом, меньшая модель для этих функций, потоковая выдача; измерение p95 "
              "первого токена под нагрузкой"),
        strong=("для звонков нужен первый токен за {ttft} мс по p95 — у общего внешнего пула хвосты длиннее, поэтому "
                "эти функции идут на свою установку или выделенную ёмкость меньшей моделью с потоковой выдачей, "
                "и p95 первого токена меряю под нагрузкой.")),
    "lock_in": dict(
        text="единственный провайдер объявил рост цены в {x} раза через полгода",
        crit=("рост цены провайдера ×{x} и зависимость от одного поставщика: шлюз с единым интерфейсом и "
              "несколькими провайдерами и своей моделью, эталонный набор для быстрой проверки замены, пересчёт "
              "окупаемости своей установки при новой цене"),
        strong=("рост цены в {x} раза меняет расчёт: при новой цене API стоит ≈ {api_new} млн ₽ в месяц; шлюз "
                "с единым интерфейсом и эталонный набор позволяют переключить часть потока на другого провайдера или "
                "свою модель за недели, а не за квартал.")),
}


def _build(rng, ctx):
    for _ in range(500):
        req_day = rng.choice([200_000, 500_000, 1_000_000, 2_000_000])
        growth = rng.choice([2, 3, 5])                    # рост потока за год, раз
        tok_in = rng.choice([1500, 3000, 6000])
        tok_out = rng.choice([200, 400, 800])
        p_in = rng.choice([30, 60, 100])                  # ₽ за 1 млн входных токенов
        p_out = rng.choice([120, 240, 400])               # ₽ за 1 млн выходных
        peak_x = rng.choice([2.5, 3, 4])                  # пик к среднему
        gpu_tps = rng.choice([1500, 2500, 4000])          # выходных токенов/с на сервер (пакетно)
        gpu_month = rng.choice([0.35, 0.5, 0.8])          # млн ₽ в месяц за сервер
        ops_people = rng.choice([2, 3])
        eng_month = 0.5                                   # млн ₽ в месяц за инженера
        api = req_day * 30 * (tok_in * p_in + tok_out * p_out) / 1e6 / 1e6        # млн ₽ в месяц
        api_y = api * growth

        def self_cost(rd):
            peak_tps = rd / 86400 * peak_x * tok_out
            n = max(2, math.ceil(peak_tps / gpu_tps * 1.3))
            return n, n * gpu_month + ops_people * eng_month

        n_now, own = self_cost(req_day)
        n_y, own_y = self_cost(req_day * growth)
        if abs(api - own) / max(api, own) > 0.15 and abs(api_y - own_y) / max(api_y, own_y) > 0.15:
            break
    cheaper_now = "внешний API" if api < own else "своя установка"
    cheaper_y = "внешний API" if api_y < own_y else "своя установка"
    kind = rng.choice(sorted(TWISTS))
    x = rng.choice([2, 3])
    v = dict(pd=rng.choice([20, 35, 60]), ttft=rng.choice([300, 500, 800]), x=x, api_new=fmt_num(api * x, 1))
    T = TWISTS[kind]
    stem = (f"Вы — главный инженер по машинному обучению; компания — {ctx}. Шесть продуктовых команд хотят функции "
            f"на больших языковых моделях; сейчас каждая подключает внешний API сама. Поток — ≈ {fmt_num(req_day, 0)} "
            f"запросов в сутки, через год ожидается в {growth} раза больше; пик — в {fmt_num(peak_x, 1)} раза выше "
            f"среднего. Средний запрос — {fmt_num(tok_in, 0)} входных и {tok_out} выходных токенов. Внешний API: "
            f"{p_in} ₽ за 1 млн входных и {p_out} ₽ за 1 млн выходных токенов. Своя установка открытой модели: сервер "
            f"выдаёт ≈ {fmt_num(gpu_tps, 0)} выходных токенов в секунду, стоит ≈ {fmt_num(gpu_month, 2)} млн ₽ в месяц, "
            f"эксплуатация — {ops_people} инженера по ≈ 0,5 млн ₽ в месяц (не меньше двух серверов). Особенность: "
            f"{T['text'].format(**v)}.\n\nПредложите стратегию на год: что дешевле сейчас и через год (посчитайте), "
            "внешний API, своя установка или гибрид и чем платите за выбор, какая общая платформа нужна командам, "
            "как управлять качеством и рисками, ответ на особенность, этапы и метрики. Ответ — 12–18 предложений.")
    criteria = [
        ("numbers", (f"Расчёт: внешний API сейчас ≈ {fmt_num(api, 1)} млн ₽ в месяц, через год ≈ {fmt_num(api_y, 1)}; "
                     f"своя установка — в пике ≈ {fmt_num(req_day / 86400 * peak_x * tok_out, 0)} выходных токенов в "
                     f"секунду → {n_now} серверов (с запасом 30 %) ≈ {fmt_num(own, 1)} млн ₽ в месяц с людьми, через год "
                     f"{n_y} серверов ≈ {fmt_num(own_y, 1)}; дешевле сейчас — {cheaper_now}, через год — {cheaper_y}"),
         0.2),
        ("choice", ("Выбор с ценой: внешний API — быстрый старт и сильные модели, цена растёт с потоком и "
                    "зависимость от поставщика; своя установка — постоянная цена, периметр и контроль задержки, "
                    "цена — люди, эксплуатация GPU и более слабая открытая модель; гибрид по типам задач и данным "
                    "с точкой пересмотра по объёму"), 0.16),
        ("platform", ("Общая платформа: шлюз к моделям с единым интерфейсом, учёт токенов и расходов по командам, "
                      "квоты, кэш, ограничители (фильтры ввода и вывода, защита от внедрения инструкций), каталог "
                      "промптов с версиями, общий сервис оценки и эталонные наборы"), 0.18),
        ("risk", ("Качество и риски: ворота оценки перед выпуском каждой функции, люди в контуре для решений с "
                  "последствиями, журнал запросов, политика данных (что можно отправлять наружу), план на отказ "
                  "провайдера"), 0.14),
        ("twist", T["crit"].format(**v), 0.18),
        ("phases", ("Этапы и метрики: квартал — шлюз и учёт расходов, перевод команд на него; затем — своя "
                    "установка для задач, где она выгоднее или обязательна; метрики — стоимость на запрос и по "
                    "командам, доля потока через шлюз, качество по эталонам, p95 задержки, инциденты"), 0.14),
    ]
    strong = (f"Внешний API сейчас ≈ {fmt_num(api, 1)} млн ₽ в месяц, через год ≈ {fmt_num(api_y, 1)}. Своя установка: "
              f"в пике ≈ {fmt_num(req_day / 86400 * peak_x * tok_out, 0)} выходных токенов в секунду, с запасом 30 % — "
              f"{n_now} серверов ≈ {fmt_num(own, 1)} млн ₽ в месяц с людьми, через год {n_y} ≈ {fmt_num(own_y, 1)}. "
              f"Значит, сейчас дешевле — {cheaper_now}, через год — {cheaper_y}; выбираю гибрид с точкой пересмотра "
              f"по объёму: API — быстрый старт и сильные модели, но растёт с потоком и привязывает к поставщику; "
              f"своя — периметр и задержка, но люди и эксплуатация GPU. Всем командам — один шлюз: единый "
              f"интерфейс, учёт токенов по командам, квоты, кэш, фильтры ввода и вывода, каталог промптов, общий "
              f"сервис оценки. " + T["strong"].format(**v) + " Этапы: квартал — шлюз и перевод команд, затем своя "
              "установка там, где выгодно или обязательно; метрики — стоимость на запрос по командам, доля "
              "потока через шлюз, качество по эталонам, p95 задержки.")
    medium = ("Сделать общий шлюз к внешнему API с учётом расходов, а для чувствительных данных развернуть свою "
              "открытую модель.")
    weak = "Купить подписку у самого сильного провайдера для всех команд и разрешить им использовать её как хотят."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: API ≈ {api:.2f} → {api_y:.2f} млн ₽/мес; своя ≈ {own:.2f} ({n_now} серв.) → "
                       f"{own_y:.2f} ({n_y} серв.); дешевле сейчас — {cheaper_now}, через год — {cheaper_y}. Выбор без "
                       f"расчёта — критерий numbers 0–1. Особенность — {kind}."),
                explanation=(f"Сейчас дешевле — {cheaper_now} ({api:.2f} против {own:.2f} млн ₽/мес), через год — "
                             f"{cheaper_y} ({api_y:.2f} против {own_y:.2f}); особенность — {kind}."),
                params=dict(kind=kind, req_day=req_day, growth=growth, tok_in=tok_in, tok_out=tok_out, p_in=p_in,
                            p_out=p_out, peak_x=peak_x, gpu_tps=gpu_tps, gpu_month=gpu_month, api=round(api, 2),
                            own=round(own, 2), n_now=n_now, n_y=n_y, cheaper_now=cheaper_now, cheaper_y=cheaper_y))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

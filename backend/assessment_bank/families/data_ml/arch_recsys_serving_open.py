"""data_ml.arch.recsys_serving_open — open_answer (Lead): архитектура выдачи рекомендаций под бюджет задержки.

Дан продукт варианта: размер каталога, поток запросов в пике, бюджет задержки p99 всей выдачи, стоимость
оценки одного кандидата ранжирующей моделью, доля новых объектов. Кандидат проектирует двухэтапную
схему (отбор кандидатов — ранжирование, при необходимости переранжирование с бизнес-правилами), признаки
в реальном времени и офлайн с одним определением (против расхождения обучения и выдачи), холодный старт,
запасной путь при отказе, проверку. Опорные числа для рубрики: сколько кандидатов успевает оценить
ранжирование в своей доле бюджета и сколько ядер нужно на ранжирование в пике.
Особенность варианта: петля популярности, признаки «последних действий» с расхождением обучения и выдачи,
большая доля новых объектов.
Рубрика 0–4: схема этапов с числами, признаки и согласованность, холодный старт и запасной путь,
особенность, проверка офлайн и онлайн.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant

FAMILY_ID = "data_ml.arch.recsys_serving_open"

CONTEXTS = [("маркетплейс", "товаров"), ("стриминговый сервис", "фильмов и сериалов"),
            ("платформа найма", "вакансий"), ("сервис объявлений", "объявлений"),
            ("музыкальный сервис", "треков"), ("сервис доставки еды", "блюд и ресторанов")]

TWISTS = {
    "feedback_loop": dict(
        text="модель учится на кликах по собственной выдаче, и доля показов топ-1 % объектов выросла до {top} %",
        crit=("петля популярности (топ-1 % объектов — {top} % показов): обучение на собственной выдаче усиливает "
              "популярное; доля исследования (случайные или мало показанные кандидаты в небольшой доле слотов), "
              "поправка на позицию и вероятность показа при обучении, метрики разнообразия и покрытия каталога"),
        strong=("топ-1 % объектов уже получает {top} % показов — модель учится на своей выдаче и усиливает "
                "популярное; выделяю небольшую долю слотов под исследование, при обучении учитываю позицию и "
                "вероятность показа, слежу за покрытием каталога и разнообразием.")),
    "skew": dict(
        text="онлайн-метрика модели с признаками «последние действия за час» на {gap} % хуже офлайн-оценки",
        crit=("расхождение обучения и выдачи (онлайн на {gap} % хуже офлайн): признаки «последних действий» в "
              "обучении посчитаны по данным, которых в момент запроса ещё не было (утечка по времени), или другим "
              "кодом; одно определение признака для офлайн и онлайн (хранилище признаков), восстановление "
              "значений на момент запроса (point-in-time), логирование признаков выдачи и сверка"),
        strong=("онлайн на {gap} % хуже офлайн — типичное расхождение обучения и выдачи: «последние действия» в "
                "обучении взяты с утечкой по времени или посчитаны другим кодом; делаю одно определение в "
                "хранилище признаков, собираю обучающую выборку на момент запроса и логирую признаки выдачи, "
                "чтобы сверять распределения.")),
    "cold_start": dict(
        text="{new} % объектов в каталоге появились за последнюю неделю, по ним почти нет взаимодействий",
        crit=("холодный старт ({new} % новых объектов): отбор кандидатов по содержанию (эмбеддинги текста и "
              "картинок, атрибуты), квота показов новым объектам с быстрым обновлением оценок, отдельная метрика "
              "по новым объектам; для новых пользователей — популярное в сегменте и онбординг"),
        strong=("{new} % объектов — новые, по ним нет взаимодействий: добавляю отбор кандидатов по содержанию "
                "(эмбеддинги текста и картинок), квоту показов новым с быстрым пересчётом оценок и считаю метрики "
                "по новым отдельно.")),
}


def _build(rng, ctx_t):
    ctx, items = ctx_t
    catalog = rng.choice([200_000, 1_000_000, 5_000_000, 20_000_000])
    qps = rng.choice([300, 800, 2000, 5000])
    p99 = rng.choice([80, 120, 150, 200])
    share = rng.choice([0.4, 0.5])                       # доля бюджета на ранжирование
    score_us = rng.choice([20, 40, 80])                  # мкс на кандидата на одном ядре, пакетно
    par = rng.choice([4, 8])                             # ядер на один запрос ранжирования (параллельно)
    kind = rng.choice(sorted(TWISTS))
    rank_ms = p99 * share
    max_cand = int(rank_ms * 1000 / score_us * par)
    cand = min(max_cand, rng.choice([300, 500, 1000, 2000]))
    cores = qps * cand * score_us / 1e6
    v = dict(top=rng.choice([35, 50, 65]), gap=rng.choice([8, 12, 20]), new=rng.choice([15, 25, 40]))
    T = TWISTS[kind]
    stem = (f"Вы — ведущий ML-инженер; продукт — {ctx}, в каталоге ≈ {fmt_num(catalog, 0)} {items}. Нужна "
            f"персональная выдача на главной: поток в пике — {fmt_num(qps, 0)} запросов в секунду, бюджет задержки "
            f"всей выдачи p99 — {p99} мс, из него на ранжирование можно отдать {fmt_num(100 * share, 0)} %. "
            f"Ранжирующая модель оценивает одного кандидата за ≈ {score_us} мкс процессорного времени (пакетно), один "
            f"запрос можно распараллелить на {par} ядер. Особенность: {T['text'].format(**v)}.\n\n"
            "Предложите архитектуру выдачи: этапы и сколько кандидатов на каждом (посчитайте по бюджету), откуда "
            "берутся признаки и как добиться, чтобы при обучении и при выдаче они считались одинаково, что делать с "
            "новыми объектами и при отказе модели, ответ на особенность и как проверите качество офлайн и онлайн. "
            "Ответ — 10–16 предложений.")
    criteria = [
        ("stages", (f"Двухэтапная схема: отбор кандидатов (ANN по эмбеддингам, популярное, правила) сокращает "
                    f"{fmt_num(catalog, 0)} до сотен–тысяч; ранжирование успевает в {fmt_num(rank_ms, 0)} мс оценить не "
                    f"больше ≈ {fmt_num(max_cand, 0)} кандидатов ({fmt_num(rank_ms, 0)} мс × 1000 / {score_us} мкс × {par} "
                    f"ядер); в пике на ранжирование ≈ {fmt_num(cores, 0)} ядер при {fmt_num(cand, 0)} кандидатах; "
                    f"переранжирование с бизнес-правилами и разнообразием в конце"), 0.24),
        ("features", ("Признаки: пакетные (профиль, статистики объекта) и в реальном времени (последние действия); "
                      "одно определение признака для обучения и выдачи (хранилище признаков), обучающая выборка — "
                      "значения на момент запроса, логирование признаков выдачи"), 0.18),
        ("fallback", ("Холодный старт и запасной путь: кандидаты по содержанию для новых объектов, популярное в "
                      "сегменте для новых пользователей; при отказе или превышении бюджета — кэш прошлой выдачи "
                      "или популярное, тайм-аут на каждом этапе"), 0.16),
        ("twist", T["crit"].format(**v), 0.24),
        ("verify", ("Проверка: офлайн — метрики ранжирования (NDCG, recall@K отбора) на отложенной по времени "
                    "выборке; онлайн — A/B-тест с целевой метрикой и защитными (задержка p99, доля запасного "
                    "пути, разнообразие); мониторинг дрейфа признаков"), 0.18),
    ]
    strong = (f"Схема двухэтапная: отбор кандидатов (ANN по эмбеддингам пользователя и объектов, популярное в "
              f"сегменте, правила) сокращает {fmt_num(catalog, 0)} {items} до {fmt_num(cand, 0)}, ранжирование в "
              f"{fmt_num(rank_ms, 0)} мс успевает не больше ≈ {fmt_num(max_cand, 0)} кандидатов при {par} ядрах на "
              f"запрос, в пике это ≈ {fmt_num(cores, 0)} ядер; в конце — переранжирование с бизнес-правилами и "
              f"разнообразием. Признаки — пакетные и последние действия из потока, определение одно для обучения "
              f"и выдачи через хранилище признаков, выборка — на момент запроса. Новым объектам — кандидаты по "
              f"содержанию, при отказе — кэш прошлой выдачи или популярное по тайм-ауту. " + T["strong"].format(**v) +
              " Проверка — NDCG и recall@K отбора на отложенной по времени выборке, затем A/B с защитными метриками "
              "(p99, доля запасного пути, разнообразие).")
    medium = ("Сначала отбирать кандидатов через ANN, потом ранжировать градиентным бустингом; признаки хранить в "
              "feature store; проверять A/B-тестом.")
    weak = "Обучить нейросеть, которая оценивает все объекты каталога для каждого пользователя."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: на ранжирование {rank_ms:.0f} мс → не больше ≈ {max_cand} кандидатов; в пике "
                       f"≈ {cores:.0f} ядер при {cand} кандидатах. Оценка всего каталога моделью — критерий stages 0. "
                       f"Особенность — {kind}."),
                explanation=f"Не больше ≈ {max_cand} кандидатов в бюджете, ≈ {cores:.0f} ядер в пике; особенность — {kind}.",
                params=dict(kind=kind, catalog=catalog, qps=qps, p99=p99, share=share, score_us=score_us, par=par,
                            max_cand=max_cand, cand=cand, cores=round(cores, 1)))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    ctx, pos, unit = rng.choice(CTX)
    topic = rng.choice(sorted(TOPICS))
    T = TOPICS[topic]
    rate = rng.choice(["0,1", "0,3", "0,5", "1,2", "2"])
    acc = {"0,1": "99,9", "0,3": "99,7", "0,5": "99,5", "1,2": "98,8", "2": "98"}[rate]
    a1 = rng.choice([0.812, 0.794, 0.77, 0.731, 0.856])
    vals = dict(ctx=ctx, pos=pos, unit=unit, features=rng.choice([80, 250, 600, 1200]),
                rows=rng.choice([40, 120, 500, 900]), train=rng.choice(["0,99", "0,97", "0,96"]),
                val=rng.choice(["0,86", "0,83", "0,81"]), oot=rng.choice(["0,74", "0,71", "0,69"]),
                rate=rate, acc=acc, a1=str(a1).replace(".", ","),
                a2=str(round(a1 - rng.choice([0.018, 0.026, 0.031]), 3)).replace(".", ","),
                a0=str(round(a1 + rng.choice([0.012, 0.021]), 3)).replace(".", ","),
                traffic=rng.choice([20, 60, 150, 400]), lag=rng.choice([30, 60, 90, 120]))
    stem = T["text"].format(**vals) + " Ответ — 8–15 предложений."
    spec = {**T, "strong": T["strong"].format(**vals), "medium": T["medium"].format(**vals),
            "weak": T["weak"].format(**vals),
            "notes": "Оценка по критериям рубрики; эталоны — ориентиры уровня, а не требуемая "
                     "формулировка. Числа из условия должны использоваться в рассуждении."}
    ak = AnswerKey(kind="rubric", value="rubric",
                   explanation="Открытый ответ оценивается по рубрике (сильный/средний/слабый).")
    return build_variant(FAMILY_ID, seed, stem=stem, answer_key=ak, rubric=rubric_from(spec),
                         context=ctx, verification="rubric_only", language="text",
                         params={"topic": topic})

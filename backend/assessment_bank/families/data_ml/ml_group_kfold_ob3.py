DISTRACTORS = ["rowmod", "ord_sum", "first_index", "rotate"]


def _code(kind, fn, arg):
    assign = "            fold_of[uid] = len(fold_of) % k"
    if kind == "ord_sum":
        assign = "            fold_of[uid] = sum(map(ord, uid)) % k"
    elif kind == "first_index":
        assign = "            fold_of[uid] = i % k"
    put = "        folds[fold_of[uid]].append(i)"
    if kind == "buggy":
        put = "        folds[len(fold_of) % k].append(i)"
    elif kind == "rowmod":
        put = "        folds[i % k].append(i)"
    lines = [f"def {fn}({arg}, k):",
             "    fold_of = {}",
             "    folds = [[] for _ in range(k)]",
             f"    for i, uid in enumerate({arg}):",
             "        if uid not in fold_of:",
             assign]
    if kind == "rotate":
        lines += ["        else:", "            fold_of[uid] = (fold_of[uid] + 1) % k"]
    lines += [put, "    return folds"]
    return "\n".join(lines)


def _assign(kind, users, k):
    """Независимая модель каждой реализации: список фолдов (индексы строк)."""
    fold_of, folds = {}, [[] for _ in range(k)]
    for i, u in enumerate(users):
        if u not in fold_of:
            fold_of[u] = {"ord_sum": sum(map(ord, u)) % k, "first_index": i % k}.get(kind, len(fold_of) % k)
        elif kind == "rotate":
            fold_of[u] = (fold_of[u] + 1) % k
        f = {"buggy": len(fold_of) % k, "rowmod": i % k}.get(kind, fold_of[u])
        folds[f].append(i)
    return folds


def _props(folds, users, full=True):
    where: dict[str, set[int]] = {}
    for f, idxs in enumerate(folds):
        for i in idxs:
            where.setdefault(users[i], set()).add(f)
    leaks = sorted(u for u, fs in where.items() if len(fs) > 1)
    if not full:
        return f"leaks={leaks!r}"
    per = [len({users[i] for i in idxs}) for idxs in folds]
    balanced = max(per) - min(per) <= 1
    covered = sorted(i for idxs in folds for i in idxs) == list(range(len(users)))
    return f"leaks={leaks!r} balanced={balanced} covered={covered}"



def _datasets(rng, prefix, k):
    """Наборы для шага 1: один с утечкой, три без (уникальные, повтор подряд, повтор через k новых)."""
    pool = [f"{prefix}{x}" for x in rng.sample(range(10, 99), 14)]
    take = iter(pool)
    a = next(take)
    gap = rng.randint(1, k - 1)
    repro = [next(take) for _ in range(rng.randint(0, 1))] + [a] + [next(take) for _ in range(gap)] + [a]
    repro += [next(take) for _ in range(rng.randint(0, 1))]
    take = iter(rng.sample(pool, len(pool)))
    unique = [next(take) for _ in range(rng.randint(5, 6))]
    take = iter(rng.sample(pool, len(pool)))
    b = next(take)
    adjacent = [next(take)] + [b, b] + [next(take) for _ in range(rng.randint(2, 3))]
    take = iter(rng.sample(pool, len(pool)))
    c = next(take)
    kgap = [c] + [next(take) for _ in range(k)] + [c]
    sets = [repro, unique, adjacent, kgap]
    if len({tuple(s) for s in sets}) < 4:
        raise RuntimeError("совпали наборы")
    return sets


def _check_program(code, fn, users, k, full):
    return (code + "\n" + PROPS_SRC + f"\n\nprint(__props({fn}({users!r}, {k}), {users!r}, {full}))\n")



SERVICES = ["платежи", "уведомления", "каталог", "профили", "расчёт тарифов", "заявки"]
MQ = ["Kafka", "RabbitMQ", "NATS"]
EXT = ["антифрод-сервис", "служба доставки", "сервис скоринга", "почтовый шлюз"]


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    prod, flow, flow2 = rng.choice(PRODUCTS)
    bug, change = rng.choice(HOTFIX_CHANGES)
    topic = rng.choice(sorted(TOPICS))
    T = TOPICS[topic]
    cov = rng.choice([70, 80, 85, 90])
    red = rng.choice([7, 12, 18, 25])
    vals = dict(prod=prod, flow=flow, flow2=flow2, bug=bug, change=change,
                h=rng.choice([2, 3, 4]) if topic == "hotfix" else rng.choice([8, 12, 24]),
                full=rng.choice([6, 8, 12, 16]), svc=rng.choice(SERVICES), mq=rng.choice(MQ),
                ext=rng.choice(EXT), n=rng.choice([40, 60, 120]) if topic == "pyramid"
                else rng.choice([900, 1500, 2400, 3200]),
                t=rng.choice([45, 70, 90]) if topic == "pyramid" else rng.choice([3, 4, 5]),
                crit=rng.choice([1, 2, 3]), major=rng.choice([4, 6, 9]), cov=cov, rest=100 - cov,
                red=red, flaky=red - rng.choice([1, 2, 3]), target=rng.choice([20, 30, 40]),
                rps=rng.choice([300, 800, 1500]), k=rng.choice([2, 3, 5]),
                p1=rng.choice([120, 180, 250]), p2=rng.choice([900, 1400, 2600]))
    for key in ("t", "h", "k"):
        vals[key + "_h"] = plural(vals[key], "час", "часа", "часов")
    stem = T["text"].format(**vals) + " Ответ — 8–15 предложений."
    spec = {**T, "criteria": [(n, d.format(**vals), w) for n, d, w in T["criteria"]],
            "strong": T["strong"].format(**vals), "medium": T["medium"].format(**vals),
            "weak": T["weak"].format(**vals),
            "notes": "Оценка по критериям рубрики; эталоны — ориентиры уровня, а не требуемая "
                     "формулировка. Числа из условия должны использоваться в рассуждении."}
    ak = AnswerKey(kind="rubric", value="rubric",
                   explanation="Открытый ответ оценивается по рубрике (сильный/средний/слабый).")
    ctx = vals["svc"] if topic in ("pyramid", "soak") else prod
    return build_variant(FAMILY_ID, seed, stem=stem, answer_key=ak, rubric=rubric_from(spec),
                         context=ctx, verification="rubric_only", language="text",
                         params={"topic": topic})

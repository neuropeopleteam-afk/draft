def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    # версия 2: только квадранты, где серьёзность и приоритет расходятся (HL, LH). Панель 06.10 показала,
    # что HH/LL решаются заметно легче, и семейство распадалось на два уровня трудности (σ_вар > 0,5).
    quad = rng.choice(["HL", "LH"])
    tpl, slots, why = rng.choice(DEFECTS[quad])
    defect = tpl.format(**{k: rng.choice(v) for k, v in slots.items()})
    context = " ".join(tpl.split()[:3])
    others = [q for q in LABELS if q != quad]
    opts, key = balanced_options(FAMILY_ID, seed, rng, (LABELS[quad], None),
                                 [(LABELS[q], None) for q in others])
    intro = rng.choice(["Найден дефект", "В баг-трекере новая запись", "Тестировщик завёл дефект",
                        "На триаже разбирают дефект", "Из отчёта о тестировании"])
    stem = (f"{intro}: {defect}. Как его классифицировать по "
            f"серьёзности (влияние на работу системы) и приоритету (срочность исправления "
            f"для бизнеса)?")
    ak = AnswerKey(kind="option", value=key,
                   explanation=(f"{LABELS[quad]}: {why}. Серьёзность оценивает влияние на "
                                "систему, приоритет — срочность для бизнеса; они независимы "
                                "(глоссарий ISTQB)."))
    return build_variant(FAMILY_ID, seed, stem=stem, options=opts, answer_key=ak,
                         context=context, verification="reference_table", language="text",
                         params={"quadrant": quad,
                                 "reference": "ISTQB Glossary: severity, priority"})

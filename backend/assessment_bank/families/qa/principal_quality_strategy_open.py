def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    org = rng.choice(ORGS)
    topic = rng.choice(sorted(TOPICS))
    esc0 = rng.choice([14, 18, 22, 27])
    vals = dict(org=org, teams=rng.choice([6, 9, 12, 15, 21]), svcs=rng.choice([40, 65, 90, 120, 180]),
                esc0=esc0, esc1=esc0 + rng.choice([9, 14, 19, 26]), mttr=rng.choice([3, 5, 7, 11]),
                down=rng.choice([18, 25, 32, 41]), e2e=rng.choice([70, 95, 140, 210]),
                flaky=rng.choice([12, 18, 27, 35]), months=rng.choice([4, 6, 9]),
                weeks=rng.choice([2, 3, 4]), days=rng.choice([3, 4, 5, 6]), testers=rng.choice([8, 12, 17, 25]),
                auto=rng.choice([15, 25, 35, 45]), queue=rng.choice([3, 4, 6, 8]),
                rows=rng.choice([4, 12, 30, 85]))
    vals["teams_acc"] = plural(vals["teams"], "команду", "команды", "команд")
    for k, forms in (("teams", ("команда", "команды", "команд")), ("months", ("месяц", "месяца", "месяцев")),
                     ("weeks", ("неделю", "недели", "недель")), ("days", ("день", "дня", "дней")),
                     ("queue", ("день", "дня", "дней"))):
        vals[k + "_w"] = plural(vals[k], *forms)
    return open_variant(FAMILY_ID, seed, topic=topic, spec=TOPICS[topic], vals=vals, context=org,
                        extra_notes="Уровень Principal: решения на уровне нескольких команд, этапы перехода и "
                                    "критерии успеха; перечень общих практик без плана — не выше среднего эталона.")

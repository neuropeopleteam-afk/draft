"""qa.lead.retry_tradeoff_mcq — mcq_concept (Lead): повторы тестов против ложных красных и пропуска регрессий.

Набор из N тестов, каждый независимо «мигает» (падает без причины) с вероятностью p за запуск. Тест красный, только
если красны все r попыток. Ложный красный конвейер: 1 − (1 − p^r)^N. Регрессия, проявляющаяся в доле q запусков
(гонка, таймаут), ловится одним прогоном конвейера с вероятностью q^r — повторы, убирающие шум, прячут и
нестабильные регрессии. Нужно найти минимальное r под целевую долю ложных красных и цену этого r.

Дистракторы (фиксированный состав): ``per_test`` — цель применена к одному тесту (p^r ≤ T), а не к набору;
``any_fail`` — вероятность поймать посчитана как «хотя бы одна попытка красная» 1 − (1 − q)^r; ``no_effect`` —
повторы будто не меняют вероятность поймать (q). Ключ проверяется исполнением: программа перебирает r по тем же
числам и печатает верный вариант.
"""
from __future__ import annotations

from assessment_bank.families._lead_b_utils import computed_mcq, pct, ru_num
from assessment_bank.gen_utils import make_rng

FAMILY_ID = "qa.lead.retry_tradeoff_mcq"

CONTEXTS = ["платёжный шлюз", "сервис бронирования", "мобильный бэкенд", "каталог товаров", "биллинг связи",
            "сервис логистики", "личный кабинет страховой", "платформа объявлений"]
RACES = ["гонка при параллельной записи корзины", "таймаут при холодном кэше", "гонка обработчиков вебхука",
         "сброс соединения пула под нагрузкой", "порядок сообщений из очереди", "истечение токена посреди теста"]

PROGRAM = '''N, P, T, Q = {n}, {p!r}, {t!r}, {q!r}
r = 1
while 1 - (1 - P ** r) ** N > T:
    r += 1
det = Q ** r
pct = f"{{100 * det:.1f}}".replace(".", ",")
pct = pct.rstrip("0").rstrip(",") if "," in pct else pct
print(f"r = {{r}}; поймает примерно в {{pct}} % прогонов")
'''


def _fmt(r: int, det: float) -> str:
    return f"r = {r}; поймает примерно в {pct(det)} прогонов"


def _min_r(pred) -> int:
    r = 1
    while not pred(r):
        r += 1
    return r


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    ctx = rng.choice(CONTEXTS)
    race = rng.choice(RACES)
    for _ in range(500):
        n = rng.choice([600, 900, 1200, 1800, 2500, 3200, 4000, 6000])
        inv = rng.choice([150, 200, 300, 400, 500, 800, 1000])
        p = 1 / inv
        t = rng.choice([0.005, 0.01, 0.02, 0.05])
        q = rng.choice([0.2, 0.25, 0.3, 0.35, 0.4, 0.5, 0.6])
        r = _min_r(lambda k: 1 - (1 - p ** k) ** n <= t)
        r_test = _min_r(lambda k: p ** k <= t)
        if r < 2 or r > 3 or r_test >= r:
            continue
        opts = {"good": _fmt(r, q ** r), "per_test": _fmt(r_test, q ** r_test),
                "any_fail": _fmt(r, 1 - (1 - q) ** r), "no_effect": _fmt(r, q)}
        if len(set(opts.values())) == 4 and q ** r >= 0.01:
            break
    else:  # pragma: no cover
        raise RuntimeError("не нашлось параметров")
    fr1 = 1 - (1 - p) ** n
    stem = (f"{ctx.capitalize()}: в регрессе {ru_num(n)} автотестов. По истории каждый тест независимо падает без "
            f"причины примерно в 1 из {ru_num(inv)} запусков, и сейчас ложными красными оказываются около "
            f"{pct(fr1, 0)} прогонов конвейера. Команда вводит повторы: упавший тест перезапускается, всего до r "
            f"попыток, и тест красный, только если красны все r. Цель — не больше {pct(t)} ложных красных прогонов. "
            f"При этом в коде может оказаться регрессия ({race}), из-за которой затронутый тест падает в "
            f"{pct(q, 0)} запусков. Какое минимальное r выполняет цель и с какой вероятностью один прогон "
            f"конвейера с этим r поймает такую регрессию?")
    why = (f"Ложный красный прогон: 1 − (1 − p^r)^N, p = 1/{inv}, N = {n}; минимальное r = {r}. Тест с регрессией "
           f"красный, только если красны все r попыток: q^r = {pct(q ** r)}. Повторы, гасящие шум, гасят и "
           f"нестабильные регрессии — поэтому нужны отдельные меры (журнал повторов, тест падал и проходил — "
           f"сигнал). Ошибки дистракторов: цель для одного теста (p^r ≤ {pct(t)}) вместо всего набора даёт "
           f"r = {r_test}; «хотя бы одна попытка красная» 1 − (1 − q)^r описывает не правило повтора; q без "
           f"учёта повторов.")
    return computed_mcq(FAMILY_ID, seed, rng, stem=stem, correct=opts["good"],
                        distractors=[opts[k] for k in ("per_test", "any_fail", "no_effect")],
                        program=PROGRAM.format(n=n, p=p, t=t, q=q), why=why, context=ctx, language="text",
                        params={"n": n, "inv": inv, "t": t, "q": q, "r": r})

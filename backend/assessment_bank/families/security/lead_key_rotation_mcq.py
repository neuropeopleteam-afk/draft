"""security.lead.key_rotation_mcq — mcq_concept (Lead): плановая ротация ключа подписи токенов без отказов.

Издатель подписывает токены доступа (время жизни L мин); проверяющие сервисы обновляют набор открытых ключей по
расписанию не реже раза в C мин и не перезапрашивают его при незнакомом идентификаторе ключа; допуск расхождения часов
S мин (токен принимается до exp + S). Порядок ротации: опубликовать новый ключ рядом со старым → через T1 начать
подписывать новым → через D после перехода убрать старый. Минимальные значения: T1 = C (каждый кэш должен успеть
получить новый ключ), D = L + S (последний токен на старом ключе живёт до exp + S, а сервис может обновить набор
сразу после удаления).

Дистракторы (фиксированный состав): ``no_prepublish`` — подписывать новым сразу (T1 = 0); ``no_skew`` — D = L без
допуска часов; ``extra_cache`` — D = L + S + C (кэш на удалении не нужен: он только дольше держит старый ключ —
не минимально). Ключ проверяется исполнением: программа моделирует фазы обновления кэшей на сетке со сдвигом
полшага и ищет минимальные T1 и D перебором.
"""
from __future__ import annotations

from assessment_bank.families._lead_b_utils import computed_mcq
from assessment_bank.gen_utils import make_rng, plural

FAMILY_ID = "security.lead.key_rotation_mcq"

CONTEXTS = ["единый вход сотрудников", "API партнёров банка", "сервис авторизации маркетплейса",
            "шлюз мобильного приложения", "внутренняя шина сервисов", "кабинет поставщика",
            "портал услуг региона (учебный стенд)", "платформа онлайн-обучения"]

PROGRAM = '''L, C, S = {L}, {C}, {S}
H = 0.25
PHASES = [H / 2 + k * H for k in range(int(C / H))]   # моменты первого обновления кэша после публикации, [0, C)


def rejects_new(t1):
    # токен на новом ключе выпущен в t1; кэш с фазой p до момента p держит набор без нового ключа
    return any(p > t1 for p in PHASES)


def rejects_old(t1, d):
    # последний токен на старом ключе принимается до t1 + L + S; после удаления (t1 + d) любой кэш может обновиться
    t2 = t1 + d
    moments = [t2 + H / 2 + k * H for k in range(int((L + S + C) / H))]   # обновление кэша после удаления
    return any(m < t1 + L + S for m in moments)


t1 = 0
while rejects_new(t1):
    t1 += 1
d = 0
while rejects_old(t1, d):
    d += 1
print(f"переход на новый ключ — через {{t1}} мин после публикации; старый убрать через {{d}} мин после перехода")
'''


def _opt(t1: int, d: int) -> str:
    return f"переход на новый ключ — через {t1} мин после публикации; старый убрать через {d} мин после перехода"


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    ctx = rng.choice(CONTEXTS)
    L = rng.choice([5, 10, 15, 20, 30, 45, 60])
    C = rng.choice([5, 10, 15, 20, 30, 60])
    S = rng.choice([1, 2, 3, 5])
    n = rng.choice([12, 18, 25, 40, 70])
    opts = {"good": _opt(C, L + S), "no_prepublish": _opt(0, L + S), "no_skew": _opt(C, L),
            "extra_cache": _opt(C, L + S + C)}
    assert len(set(opts.values())) == 4
    lw = plural(L, "минута", "минуты", "минут")
    stem = (f"{ctx.capitalize()}: издатель подписывает токены доступа, время жизни токена — {L} {lw}. Токены "
            f"проверяют {n} сервисов; каждый держит набор открытых ключей в кэше и обновляет его по своему "
            f"расписанию не реже раза в {C} мин; при незнакомом идентификаторе ключа (kid) набор заново не "
            f"запрашивается — токен отклоняется. Допуск расхождения часов — {S} мин: токен принимается до exp + {S} "
            f"мин. Плановая ротация: новый ключ публикуется в наборе рядом со старым, через T1 издатель начинает "
            f"подписывать новым, через D после этого старый ключ удаляется из набора. Какие минимальные T1 и D "
            f"гарантируют, что ни один действительный токен не будет отклонён?")
    why = (f"T1 = {C} мин: сервис, обновивший кэш за мгновение до публикации, получит новый ключ только через {C} "
           f"мин, а до того отклонит токены на новом ключе. D = L + S = {L + S} мин: последний токен на старом "
           f"ключе выпущен непосредственно перед переходом и принимается ещё {L} + {S} мин, а сервис может обновить набор сразу "
           f"после удаления — кэш тут не помогает, он лишь дольше держит старый ключ, поэтому D = L + S + C не "
           f"минимально. Подписывать новым ключом сразу после публикации нельзя (кэши ещё старые); забытый допуск "
           f"часов отклоняет токены последних {S} мин. Отдельно: при компрометации ключа ждать нельзя — старый "
           f"ключ удаляется сразу, токены на нём отзываются.")
    return computed_mcq(FAMILY_ID, seed, rng, stem=stem, correct=opts["good"],
                        distractors=[opts[k] for k in ("no_prepublish", "no_skew", "extra_cache")],
                        program=PROGRAM.format(L=L, C=C, S=S), why=why, context=ctx, language="text",
                        note="Программа моделирует фазы обновления кэшей (сетка 0,25 мин со сдвигом полшага) и "
                             "ищет минимальные T1 и D перебором по тем же числам.",
                        params={"L": L, "C": C, "S": S})

"""security.lead.token_length_mcq — mcq_concept (Lead): минимальная длина одноразового токена против распределённого подбора.

Токены ссылок сброса пароля (или кодов приглашения) — случайные строки из алфавита размера A. Ограничение частоты —
r попыток в минуту с одного IP-адреса; у атакующего ботнет из B адресов; одновременно действуют V токенов (любой
подходит атакующему); атака идёт непрерывно весь год — токены перевыпускаются, поэтому срок жизни одного токена
перебор не ограничивает. Требование: вероятность хотя бы одного успешного подбора за год ≤ p. Оценка сверху:
P ≤ G · V / A^L, G = r · B · 525 600 (минут в году). Ответ — наименьшее L.

Дистракторы — из пула пяти ошибок, по seed 0, 1 или 2 из них завышают длину (ранг верной длины меняется, «самое
большое число» ключ не выдаёт). Занижают: ``single_target`` — без числа одновременно действующих токенов (V = 1);
``per_ip`` — ограничение частоты считается общим, а не на адрес (B = 1); ``lifetime`` — перебор только в течение
срока жизни одного токена, один токен. Завышают: ``issued_total`` — целями считаются все токены, выпущенные за
год; ``birthday`` — требование стойкости к коллизиям (показатель удваивается). Числа подобраны так, что дробная часть логарифма не ближе 0,05 к целому
(приближённый расчёт даёт тот же ответ), а все четыре длины различны. Ключ проверяется исполнением: программа ищет
наименьшее L в целых числах.
"""
from __future__ import annotations

import math

from assessment_bank.families._lead_b_utils import computed_mcq, ru_num
from assessment_bank.gen_utils import make_rng, plural

FAMILY_ID = "security.lead.token_length_mcq"

CONTEXTS = [("ссылки сброса пароля", "интернет-банк"), ("коды приглашения в рабочее пространство", "сервис задач"),
            ("ссылки подтверждения почты", "маркетплейс"), ("ссылки доступа к документу", "облачный диск"),
            ("одноразовые ссылки входа", "портал поставщиков"), ("коды восстановления доступа", "мессенджер"),
            ("ссылки на оплату счёта", "сервис выставления счетов"), ("ссылки сброса пароля", "онлайн-школа")]
ALPHABETS = [("десятичные цифры", 10), ("шестнадцатеричные символы (0–9, a–f)", 16),
             ("base32 (A–Z, 2–7)", 32), ("латинские буквы обоих регистров и цифры", 62)]
MINUTES_YEAR = 525600
SMALLER = ["single_target", "per_ip", "lifetime"]   # ошибки, занижающие длину
LARGER = ["issued_total", "birthday"]                # ошибки, завышающие длину
WHY = {"single_target": "без числа одновременно действующих токенов (одна цель)",
       "per_ip": "если считать ограничение частоты общим, а не на адрес",
       "lifetime": "если считать перебор только за срок жизни одного токена (токены перевыпускаются — атака "
                   "продолжается на новых)",
       "issued_total": "если считать целями все токены, выпущенные за год, а не действующие одновременно "
                       "(просроченный токен атакующему не нужен)",
       "birthday": "если требовать стойкость к коллизиям (парадокс дней рождения) — это другая задача: атакующий "
                   "угадывает, а не ищет два совпадающих токена"}

PROGRAM = '''A, R, B, V, P_DEN = {a}, {r}, {b}, {v}, {p_den}
MINUTES_YEAR = 525600
guesses = R * B * MINUTES_YEAR                 # попыток за год со всех адресов
L = 1
while guesses * V * P_DEN > A ** L:           # P ≤ guesses · V / A^L ≤ 1 / P_DEN — в целых числах
    L += 1
print(f"L = {{L}}")
'''


def _min_len(a: int, total: int, p_den: int) -> tuple[int, float]:
    x = math.log(total * p_den) / math.log(a)
    L = 1
    while total * p_den > a ** L:
        L += 1
    return L, x


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    what, ctx = rng.choice(CONTEXTS)
    for _ in range(5000):
        alpha, a = rng.choice(ALPHABETS)
        r = rng.choice([5, 10, 20, 30, 60])
        b = rng.choice([200, 500, 1000, 5000, 20000])
        v = rng.choice([50, 200, 1000, 5000, 20000])
        t = rng.choice([10, 15, 30, 60])
        p_den = rng.choice([10 ** 4, 10 ** 5, 10 ** 6])
        g = r * b * MINUTES_YEAR
        allc = {"good": _min_len(a, g * v, p_den), "single_target": _min_len(a, g, p_den),
                "per_ip": _min_len(a, r * MINUTES_YEAR * v, p_den), "lifetime": _min_len(a, r * b * t, p_den),
                "issued_total": _min_len(a, g * v * (MINUTES_YEAR // t), p_den),
                "birthday": _min_len(a, (g * v * p_den) ** 2, 1)}
        # ранг верной длины среди вариантов меняется по seed: 0, 1 или 2 дистрактора длиннее верного
        n_up = seed % 3
        down = sorted(SMALLER, key=lambda k: rng.random())[:3 - n_up]
        up = sorted(LARGER, key=lambda k: rng.random())[:n_up]
        cands = {"good": allc["good"], **{k: allc[k] for k in down + up}}
        lens = [c[0] for c in cands.values()]
        if len(set(lens)) != 4:
            continue
        if any(min(x % 1, 1 - x % 1) < 0.05 for _, x in cands.values()):
            continue
        break
    else:  # pragma: no cover
        raise RuntimeError("не удалось построить вариант")
    good = cands["good"][0]
    opt = {k: f"L = {c[0]}" for k, c in cands.items()}
    p_txt = {10 ** 4: "1 на 10 000", 10 ** 5: "1 на 100 000", 10 ** 6: "1 на 1 000 000"}[p_den]
    stem = (f"{ctx.capitalize()}: {what} содержат случайный токен из {_genitive(alpha)} (алфавит — {a} {plural(a, 'символ', 'символа', 'символов')}). "
            f"Ограничение частоты проверки токенов — {r} попыток в минуту с одного IP-адреса; модель угроз — ботнет "
            f"из {ru_num(b)} адресов, атака непрерывно весь год. Одновременно действуют до {ru_num(v)} токенов "
            f"(любой подходит атакующему), срок жизни токена — {t} мин, после чего выпускаются новые. Требование: "
            f"вероятность хотя бы одного успешного подбора за год — не больше {p_txt}. Какая наименьшая длина токена "
            f"L (в символах) удовлетворяет требованию?")
    g = r * b * MINUTES_YEAR
    why = (f"За год атакующий делает G = {r} · {ru_num(b)} · 525 600 = {ru_num(g)} попыток (ограничение — на адрес, "
           f"адресов {ru_num(b)}). Каждая попытка угадывает любой из {ru_num(v)} действующих токенов: P ≤ G · V / "
           f"{a}^L. Нужно {a}^L ≥ G · V · {ru_num(p_den)} → L ≥ {ru_num(round(cands['good'][1], 2))} → L = {good}. "
           f"Ошибки: "
           + "; ".join(f"{WHY[k]} — L = {cands[k][0]}" for k in cands if k != "good")
           + f". Для Lead: длина токена "
           f"выводится из модели угроз (распределённый перебор, многоцелевая атака, срок кампании), а ограничение "
           f"частоты — дополнительный, а не единственный барьер.")
    return computed_mcq(FAMILY_ID, seed, rng, stem=stem, correct=opt["good"],
                        distractors=[opt[k] for k in cands if k != "good"],
                        program=PROGRAM.format(a=a, r=r, b=b, v=v, p_den=p_den), why=why, context=ctx,
                        language="text",
                        note="Программа ищет наименьшую длину в целых числах (без округлений логарифмов) по тем же "
                             "числам.",
                        params={"A": a, "r": r, "B": b, "V": v, "T": t, "p_den": p_den})


def _genitive(alpha: str) -> str:
    return {"десятичные цифры": "десятичных цифр",
            "шестнадцатеричные символы (0–9, a–f)": "шестнадцатеричных символов (0–9, a–f)",
            "base32 (A–Z, 2–7)": "символов base32 (A–Z, 2–7)",
            "латинские буквы обоих регистров и цифры": "латинских букв обоих регистров и цифр"}[alpha]

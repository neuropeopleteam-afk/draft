def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    org = rng.choice(ORGS)
    topic = rng.choice(sorted(TOPICS))
    vals = dict(org=org, svcs=rng.choice([45, 80, 120, 200, 350]), owners=rng.choice([3, 4]),
                months=rng.choice([6, 9, 12]), contractors=rng.choice([40, 120, 300]), hours=rng.choice([2, 3, 4, 6]),
                repos=rng.choice([150, 300, 600, 1200]), days=rng.choice([5, 9, 12, 21]),
                teams=rng.choice([12, 18, 25, 40]), sec=rng.choice([3, 4, 5]), finds=rng.choice([60, 80, 120]),
                repeat=rng.choice([35, 45, 55]), rows=rng.choice([40, 180, 650]), years=rng.choice([2, 3, 4]))
    for k, forms in (("months", ("месяц", "месяца", "месяцев")), ("hours", ("час", "часа", "часов")),
                     ("days", ("день", "дня", "дней")), ("teams", ("команда", "команды", "команд")),
                     ("sec", ("человек", "человека", "человек")), ("years", ("год", "года", "лет"))):
        vals[k + "_w"] = plural(vals[k], *forms)
    return open_variant(FAMILY_ID, seed, topic=topic, spec=TOPICS[topic], vals=vals, context=org,
                        extra_notes="Уровень Principal: системные причины, меры по риску с этапами и управление "
                                    "программой; перечень средств защиты без порядка и критериев — не выше "
                                    "среднего эталона. Инструкции по проведению атак не требуются и не "
                                    "засчитываются.")

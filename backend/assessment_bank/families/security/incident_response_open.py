"""Защитный план реагирования на учебный инцидент."""
from __future__ import annotations

from assessment_bank.gen_utils import build_variant, make_rng, rubric_from
from assessment_bank.schema import AnswerKey
from ._support import CONTEXTS, SOURCES

FAMILY_ID = "security.response.incident_plan_open"


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    ctx = rng.choice(CONTEXTS)
    duration, accounts = rng.choice([10, 20, 40, 60]), rng.choice([20, 60, 150, 400])
    asset = rng.choice(["тексты документов", "метаданные заявок", "черновики отчётов", "история бронирований"])
    issue = rng.choice(["ошибка проверки владельца после релиза",
                        "подозрение на раскрытие сервисного секрета в диагностике"])
    sla = rng.choice([15, 30, 45])
    stem = (f"{ctx.capitalize()}: в учебной настольной тренировке мониторинг отметил "
            f"нетипичные обращения к чужим объектам за последние {duration} минут. "
            f"Рабочая гипотеза — {issue}, но факт раскрытия данных не подтверждён. "
            f"Возможная область: {accounts} учётных записей и {asset}. "
            f"Первые согласованные действия нужны в течение {sla} минут; обслуживание собственных "
            "документов желательно сохранить. Есть ответственный дежурный, журнал аудита, "
            "предыдущая версия и механизм отзыва сессий/секретов. "
            "Составьте план: роли и первые шаги, безопасная локализация, сохранение доказательств, "
            "проверка масштаба, исправление, критерии восстановления и коммуникация. "
            "Только защитные организационные действия, без экспериментов над чужими системами. "
            "Ответ — 8–15 предложений.")
    rub = dict(
        criteria=[
            ("containment", "Назначает координатора и ограничивает только затронутую функцию; "
             "отзыв/ротация или откат обоснованы гипотезой, сохраняет минимальные привилегии", 0.35),
            ("evidence", "До разрушительных изменений сохраняет аудит и временную шкалу с "
             "контролем доступа; проверяет масштаб и отделяет гипотезу от подтверждённого факта", 0.35),
            ("recovery", "Исправление и тесты, критерии восстановления, мониторинг, ответственная "
             "коммуникация и разбор причин; не объявляет юридическую обязанность без проверки", 0.3),
        ],
        strong="Назначаю координатора, владельца сервиса и ответственного за коммуникацию, "
               "фиксирую временную шкалу и канал принятия решений. Сохраняю относящийся к "
               "событию аудит и диагностические материалы с ограниченным доступом и проверкой "
               "целостности, не удаляю журнал ради очистки. Отделяю нетипичное поведение от "
               "подтверждённого доступа к данным. Временно ограничиваю затронутую операцию; "
               "при ошибке авторизации — безопасный откат или выключение функции, при "
               "раскрытии ключа — отзыв и управляемая ротация, без переноса секрета в чат. "
               "Проверяю релиз, временной диапазон, объекты и разрешённые роли по имеющимся "
               "доказательствам. Исправление сопровождаю тестами своего/чужого объекта, "
               "отзывом доступа и контролируемым выпуском. Восстановление возможно после "
               "проверки контроля доступа, завершённой ротации при необходимости и спокойного "
               "мониторинга. Заинтересованных лиц информирую фактами и оценённым масштабом; "
               "юридические сроки отдельно проверяет ответственная функция. Разбор завершает "
               "план предупреждения повторения с владельцами и сроками.",
        medium="Сообщу дежурному, сохраню журнал и временно отключу проблемную функцию. "
               "Проверю доступы и масштаб по аудиту, исправлю дефект и прогоню тесты. "
               "При раскрытии секрета заменю его и отзову старый. Пользователей нужно "
               "информировать после подтверждения фактов.",
        weak="Сразу удалю подозрительные строки журнала, перезапущу сервис и объявлю, "
             "что данные не раскрывались, потому что ошибок больше нет.",
        notes="Каждый критерий оценивается отдельно: 0 — отсутствует или опасен, 0.5 — "
              "частично раскрыт, 1 — выполнен; итог — взвешенная сумма. Не требуются "
              "названия продуктов. Необоснованное уничтожение доказательств обнуляет evidence; "
              "один опасный совет не компенсируется многословием. Примеры — ориентиры, не шаблон.",
    )
    return build_variant(
        FAMILY_ID, seed, stem=stem, context=ctx, verification="rubric_only",
        answer_key=AnswerKey(kind="rubric", value="rubric",
                            explanation="План оценивается по трём критериям и эталонам; "
                            "автоматическое исполнение организационного решения не имитируется."),
        rubric=rubric_from(rub), params={"source_urls": [SOURCES["coding"]],
                                         "issue": issue, "duration": duration, "accounts": accounts},
    )

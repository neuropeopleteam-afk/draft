"""Модель угроз простого собственного сервиса: активы, границы, меры и тесты."""
from __future__ import annotations

from assessment_bank.gen_utils import build_variant, make_rng, rubric_from
from assessment_bank.schema import AnswerKey
from ._support import CONTEXTS, SOURCES

FAMILY_ID = "security.design.threat_model_open"


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    ctx = rng.choice(CONTEXTS)
    tenants = rng.choice([5, 15, 40, 100])
    count = rng.choice([200, 1000, 5000, 12000])
    count = max(count, tenants * 10)  # не меньше десяти документов на организацию
    retention = rng.choice([7, 14, 30, 90])
    asset = rng.choice(["личные заметки", "черновики заявок", "внутренние отчёты", "документы курсов"])
    condition = rng.choice(["совместный просмотр внутри организации разрешён только редакторам",
                            "экспорт разрешён только владельцу документа и аудитору организации"])
    stem = (f"{ctx.capitalize()}: простой проект хранит {asset} для {tenants} организаций, "
            f"около {count} документов. Браузер → HTTPS API → SQLite с метаданными и отдельный "
            "каталог вложений. API передаёт задания фоновому обработчику экспорта; "
            f"аудит хранится {retention} дней. Вход по cookie-сессии, роли: пользователь, "
            f"редактор, аудитор; {condition}. Все названия и данные учебные. "
            "Опишите активы и потоки, минимум три границы доверия, четыре конкретные угрозы "
            "с защитой и проверяемым критерием. Приоритизируйте две меры для первого выпуска "
            "и объясните остаточный риск. Не перечисляйте инструкции по атакам. "
            "Ответ — 10–16 предложений; схема словами достаточна.")
    rub = dict(
        criteria=[
            ("model", "Выделяет документы, сессии, ключи, аудит; потоки и границы "
             "браузер/API, API/хранилище, API/очередь/worker с межорганизационной изоляцией", 0.3),
            ("controls", "Не менее четырёх пар угроза–мера–тест, включая объектную авторизацию, "
             "запросы/вывод, путь вложения и фоновые задания; соблюдает данные роли", 0.45),
            ("priority", "Выбирает два контроля по ущербу и вероятности, отмечает допущения "
             "и остаточный риск, назначает дальнейшую проверку", 0.25),
        ],
        strong="Активы — содержание документов, метаданные владельца и организации, "
               "сессионные значения, сервисные секреты и целостность аудита. Прослеживаю "
               "создание, чтение, загрузку вложения и экспорт через браузер, API, БД, "
               "файловую область и worker. Границы — внешний клиент/API, API/хранилища "
               "и API/очередь/worker; соседние организации не становятся доверенными друг "
               "для друга. Первая угроза — выдача чужого объекта: проверка tenant и роли "
               "на сервере, тест разрешённой и запрещённой роли между организациями. "
               "Вторая — смешение данных с запросом или разметкой: параметры SQL и "
               "контекстное экранирование, тесты обычных специальных символов. "
               "Третья — чтение вложения вне разрешённой области: серверный id, "
               "канонический путь и безопасное открытие, тест границы каталога. "
               "Четвёртая — экспорт после утраты прав: задания от доверенного API, "
               "повторная проверка актуальных прав worker и ограниченный срок результата, "
               "тест отзыва между постановкой и выполнением. Cookie-запросы изменения "
               "защищаю CSRF, аудит не содержит секретов и имеет ограниченный доступ. "
               "В первый выпуск ставлю межорганизационную авторизацию и проверку экспорта "
               "как меры против наиболее тяжёлой потери конфиденциальности. "
               "Остаточный риск связан с ошибками реализации, компрометацией служебного "
               "доступа и доступностью очереди; нужны ревью, ограничение привилегий "
               "и последующая проверка наблюдаемости.",
        medium="Нужно защитить документы и сессии. Основные границы — браузер/API, "
               "API/БД и API/worker. Проверю владельца и организацию, использую параметры "
               "SQL, экранирование и проверку пути; добавлю тесты чужого объекта и "
               "специальных символов. Первой сделаю авторизацию, затем защиту экспорта.",
        weak="Достаточно поставить HTTPS и антивирус; после входа всем пользователям "
             "можно выдавать любые документы, потому что база находится внутри сервиса.",
        notes="Критерии оцениваются 0/0.5/1 с заданными весами. Принимаются другие "
              "релевантные угрозы с защитой и тестом, если соблюдён контракт ролей. "
              "Четыре названия уязвимостей без потока данных и тестов — не сильный ответ. "
              "Широкий STRIDE-список не компенсирует отсутствие межорганизационной авторизации.",
    )
    return build_variant(
        FAMILY_ID, seed, stem=stem, context=ctx, verification="rubric_only",
        answer_key=AnswerKey(kind="rubric", value="rubric",
                            explanation="Оценивается связная модель потока данных, защитные "
                            "решения с тестами и обоснованная приоритизация, а не знание аббревиатур."),
        rubric=rubric_from(rub), params={"source_urls": [SOURCES["coding"]],
                                         "tenants": tenants, "condition": condition},
    )

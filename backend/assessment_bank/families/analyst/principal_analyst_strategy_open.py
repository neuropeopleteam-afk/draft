def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    org = rng.choice(ORGS)
    topic = rng.choice(sorted(TOPICS))
    vals = dict(org=org, integr=rng.choice([45, 80, 120, 300]), rules=rng.choice([400, 900, 1500, 3000]),
                months=rng.choice([6, 9, 12, 18]), deps=rng.choice([3, 4, 5, 6]), manual=rng.choice([18, 25, 35, 40]),
                changes=rng.choice([9, 14, 21, 30]), systems=rng.choice([7, 12, 18, 25]),
                incidents=rng.choice([4, 6, 9, 11]), teams=rng.choice([4, 5, 7, 9]))
    for k, forms in (("integr", ("интеграция", "интеграции", "интеграций")),
                     ("months", ("месяц", "месяца", "месяцев")),
                     ("deps", ("подразделение", "подразделения", "подразделений")),
                     ("systems", ("система", "системы", "систем")),
                     ("incidents", ("инцидент", "инцидента", "инцидентов")),
                     ("teams", ("команда", "команды", "команд"))):
        vals[k + "_w"] = plural(vals[k], *forms)
    return open_variant(FAMILY_ID, seed, topic=topic, spec=TOPICS[topic], vals=vals, context=org,
                        extra_notes="Уровень Principal: решение на уровне организации — постановка по данным, "
                                    "артефакты с компромиссами и порядок управления; перечень техник анализа без "
                                    "критериев выбора — не выше среднего эталона.")

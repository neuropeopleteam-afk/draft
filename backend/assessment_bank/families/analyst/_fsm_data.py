def _ctx(initial, transitions, reqs):
    """Контекст с мутациями по исходному переходу: (текст, проверка, (исходный, мутированный)) → индекс."""
    tr = list(transitions)
    events = list(dict.fromkeys(e for _, e, _ in tr))
    out = []
    for text, pred, (orig, new) in reqs:
        out.append((text, pred, (tr.index(orig), new)))
    return dict(initial=initial, transitions=tr, events=events, reqs=out)



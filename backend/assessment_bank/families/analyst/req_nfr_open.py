def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    topic = rng.choice(sorted(TOPICS))
    T = TOPICS[topic]
    ctx = rng.choice(CTX)
    vals = dict(ctx=ctx, u=rng.choice([2000, 5000, 12000, 30000]), k=rng.choice([4, 6, 10]),
                cost=rng.choice([150, 400, 900]), n=rng.choice([80, 250, 600]), d=rng.choice([3, 5, 8]),
                a=rng.choice([40, 120, 300]), gb=rng.choice([200, 500, 1200]))
    stem = T["text"].format(**vals) + " Ответ — 8–15 предложений."
    crit = [(c[0], c[1].format(**vals), c[2]) for c in T["criteria"]]
    spec = {**T, "criteria": crit, "strong": T["strong"].format(**vals), "medium": T["medium"].format(**vals),
            "notes": "Оценка по критериям рубрики; эталоны — ориентиры уровня, числа в них — пример, не норма."}
    ak = AnswerKey(kind="rubric", value="rubric",
                   explanation="Открытый ответ оценивается по рубрике (сильный/средний/слабый).")
    return build_variant(FAMILY_ID, seed, stem=stem, answer_key=ak, rubric=rubric_from(spec),
                         context=ctx, verification="rubric_only", language="text",
                         params={"topic": topic, **{k: v for k, v in vals.items() if k != "ctx"}})

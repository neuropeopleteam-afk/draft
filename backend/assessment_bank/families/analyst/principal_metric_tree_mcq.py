"""analyst.principal.metric_tree_mcq — mcq_concept (Principal, короткое): совокупный прирост выручки от трёх
инициатив на разных ветвях дерева метрик и разных сегментах.

Выручка = покупатели × заказов на покупателя × средний чек. Инициатива 1 поднимает конверсию в сегменте A (доля
выручки r_A, доля пользователей u_A) на x, инициатива 2 — средний чек у всех на y, инициатива 3 — частоту заказов в
сегменте B (доля выручки r_B) на z; A и B не пересекаются. Новая выручка: r_A(1 + x)(1 + y) + r_B(1 + z)(1 + y) +
(1 − r_A − r_B)(1 + y). Ключ — прирост в процентах.

Ловушки: выше ключа — ``sum_all`` (x + y + z), ``product_all`` ((1 + x)(1 + y)(1 + z) − 1: все инициативы на всю
выручку); ниже — ``additive_weighted`` (r_A·x + y + r_B·z: без перекрёстных членов), ``max_only`` (только самая
сильная инициатива); ``user_share`` (веса по доле пользователей, а не выручки) — с любой стороны. Сколько ловушек
меньше ключа — 1–3 равновероятно. Ключ проверяется исполнением: программа строит модельную базу из 100 покупателей
по долям и пересчитывает выручку каждого после инициатив точными дробями.
"""
from __future__ import annotations

from assessment_bank.families._principal_c_utils import formatter, numeric_mcq, pick_traps
from assessment_bank.gen_utils import make_rng

FAMILY_ID = "analyst.principal.metric_tree_mcq"

CONTEXTS = [("интернет-магазин", "новые покупатели", "подписчики доставки"),
            ("сервис доставки еды", "новые клиенты", "клиенты с подпиской"),
            ("онлайн-кинотеатр", "пробный период", "семейный тариф"),
            ("маркетплейс услуг", "новые заказчики", "корпоративные клиенты"),
            ("сеть аптек", "покупатели без карты", "участники программы лояльности"),
            ("сервис такси", "новые пассажиры", "бизнес-аккаунты")]

PROGRAM = """from fractions import Fraction as F

{fmt}
# модельная база: доли выручки сегментов (из 100), прирост инициатив (из 100)
R = {{"A": F({rA}, 100), "B": F({rB}, 100)}}
R["прочие"] = 1 - R["A"] - R["B"]
x, y, z = F({x}, 100), F({y}, 100), F({z}, 100)
before = after = F(0)
for seg, share in R.items():
    conv = freq = aov = F(1)          # выручка сегмента = конверсия × частота × чек (база — доля выручки)
    if seg == "A":
        conv *= 1 + x
    if seg == "B":
        freq *= 1 + z
    aov *= 1 + y
    before += share
    after += share * conv * freq * aov
print(fmt(float(after / before - 1)))
"""


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    ctx, segA, segB = rng.choice(CONTEXTS)
    n_below = rng.choice([0, 1, 2, 3])  # ранг ключа равномерный (аудит 21.10: без крайнего ранга ключ угадывался)
    fmt, fmt_src = formatter("p0")
    for _ in range(6000):
        uA, rA = rng.choice([(30, 10), (40, 15), (35, 10), (50, 20), (45, 15)])
        uB, rB = rng.choice([(10, 30), (15, 40), (20, 45), (10, 25), (15, 35)])
        x, y, z = rng.choice([20, 30, 40, 50, 60]), rng.choice([5, 8, 10, 12, 15, 20]), rng.choice([20, 30, 40, 50])
        X, Y, Z = x / 100, y / 100, z / 100
        a, b = rA / 100, rB / 100
        good = a * (1 + X) * (1 + Y) + b * (1 + Z) * (1 + Y) + (1 - a - b) * (1 + Y) - 1
        ua, ub = uA / 100, uB / 100
        pool = {"sum_all": X + Y + Z, "product_all": (1 + X) * (1 + Y) * (1 + Z) - 1,
                "additive_weighted": a * X + Y + b * Z, "max_only": max(a * X, Y, b * Z),
                "user_share": ua * (1 + X) * (1 + Y) + ub * (1 + Z) * (1 + Y) + (1 - ua - ub) * (1 + Y) - 1}
        traps = pick_traps(good, pool, n_below, rng, fmt, "p0", rel=0.05, lo=0.1, hi=1.0)
        if traps:
            break
    else:  # pragma: no cover
        raise RuntimeError("не удалось подобрать параметры")
    code = "\n".join(["Выручка = покупатели × заказов на покупателя × средний чек",
                      f"Сегмент «{segA}»: {uA} % пользователей, {rA} % выручки",
                      f"Сегмент «{segB}»: {uB} % пользователей, {rB} % выручки (сегменты не пересекаются)",
                      f"Инициатива 1: конверсия в покупку в сегменте «{segA}» +{x} %",
                      f"Инициатива 2: средний чек у всех +{y} %",
                      f"Инициатива 3: заказов на покупателя в сегменте «{segB}» +{z} %",
                      "Эффекты оценены по отдельности на своих ветвях; остальные метрики не меняются."])
    stem = (f"{ctx.capitalize()}: в плане на год три инициативы на разных ветвях дерева метрик. Финансовый директор "
            f"просит общий прирост выручки (в целых процентах), если все три сработают как оценено. Каков он?")
    why = (f"Сегменты взвешиваются по доле выручки, а не пользователей; в каждом сегменте эффекты множатся: "
           f"{rA} % × (1 + {x} %)(1 + {y} %) + {rB} % × (1 + {z} %)(1 + {y} %) + {100 - rA - rB} % × (1 + {y} %) − 1 = "
           f"{fmt(good)}. Ошибки: сумма приростов — {fmt(pool['sum_all'])}; все инициативы на всю выручку — "
           f"{fmt(pool['product_all'])}; взвешенная сумма без перекрёстных членов — {fmt(pool['additive_weighted'])}; "
           f"только самая сильная — {fmt(pool['max_only'])}; веса по доле пользователей — {fmt(pool['user_share'])}. "
           f"Вывод: прирост по дереву метрик — произведение множителей внутри сегмента, взвешенное долей выручки.")
    program = PROGRAM.format(fmt=fmt_src, rA=rA, rB=rB, x=x, y=y, z=z)
    return numeric_mcq(FAMILY_ID, seed, rng, ctx=ctx, stem=stem, good=good, pool=pool, traps=traps, fmt=fmt,
                       program=program, why=why, code=code,
                       params={"uA": uA, "rA": rA, "uB": uB, "rB": rB, "x": x, "y": y, "z": z},
                       note="Программа пересчитывает выручку каждого сегмента как произведение метрик точными дробями.")

"""common.db.principal_db_conn_budget_mcq — mcq_concept (Principal): бюджет соединений к БД на выкладку.

K экземпляров приложения за балансировщиком, пиковый поток λ запросов в секунду на весь сервис; каждый запрос держит
соединение из пула в среднем t мс (p99 тоже показан — ловушка). Балансировщик неравномерен: самому загруженному
экземпляру достаётся доля в s раз больше средней. Пул экземпляра должен быть занят не больше чем на ρ (иначе
очередь за соединением растёт нелинейно). На время выкладки (maxSurge) одновременно живут K + u экземпляров, у
каждого полный пул; R соединений на БД держатся в резерве (миграции, администрирование, репликация).
Вопрос: какое наименьшее max_connections нужно на БД, чтобы выкладка в пик не упёрлась в лимит.

Ответ: (K + u) · p + R, где p = ⌈λ · t · s / (K · ρ)⌉ (закон Литтла: занято λ·t соединений). Три взаимодействующих
ограничения (неравномерность, целевая занятость, выкладка) + резерв — Principal. Ловушки: p99 вместо среднего,
без неравномерности, без целевой занятости, без экземпляров выкладки, без резерва. ``brute`` подбирает p перебором
(наименьший пул, при котором занятость самого загруженного экземпляра ≤ ρ) — независимо от формулы с округлением.
"""
from __future__ import annotations

from assessment_bank.families._w2010_kit import num, numeric_variant
from assessment_bank.gen_utils import plural

FAMILY_ID = "common.db.principal_db_conn_budget_mcq"

CONTEXTS = ["сервис корзины интернет-магазина", "API личного кабинета банка", "сервис бронирования столиков",
            "бэкенд мобильного такси", "сервис уведомлений", "API каталога маркетплейса", "сервис расписаний",
            "бэкенд онлайн-школы"]

MODEL = '''
def pool(P, t_ms, skew=True, rho=True):
    s = P["S"] if skew else 100
    r = P["Rho"] if rho else 100
    num = P["lam"] * t_ms * s
    den = 1000 * P["K"] * r
    return -(-num // den)

def answer(P):
    return (P["K"] + P["u"]) * pool(P, P["t"]) + P["R"]

def brute(P):
    p = 1
    while P["lam"] * P["S"] / 100 / P["K"] * P["t"] / 1000 > p * P["Rho"] / 100 + 1e-12:
        p += 1
    return (P["K"] + P["u"]) * p + P["R"]

def traps(P):
    return {
        "p99": (P["K"] + P["u"]) * pool(P, P["t99"]) + P["R"],
        "no_skew": (P["K"] + P["u"]) * pool(P, P["t"], skew=False) + P["R"],
        "no_rho": (P["K"] + P["u"]) * pool(P, P["t"], rho=False) + P["R"],
        "no_surge": P["K"] * pool(P, P["t"]) + P["R"],
        "no_reserve": (P["K"] + P["u"]) * pool(P, P["t"]),
        "naive": P["K"] * pool(P, P["t"], skew=False, rho=False) + P["R"],
        "reserve_each": (P["K"] + P["u"]) * (pool(P, P["t"]) + P["R"]),
        "two_queries": (P["K"] + P["u"]) * pool(P, int(P["t"] * 1.35)) + P["R"],
        "double_surge": (P["K"] + 2 * P["u"]) * pool(P, P["t"]) + P["R"],
        "blue_green": 2 * P["K"] * pool(P, P["t"]) + P["R"],
    }

def fmt(x):
    return f"{x:,}".replace(",", "\\u00a0")
'''


def _sample(rng):
    t = rng.choice([8, 12, 15, 20, 25, 30, 40])
    return {"K": rng.choice([4, 6, 8, 10, 12]), "u": rng.choice([1, 2, 3]), "lam": rng.choice(range(800, 6001, 200)),
            "t": t, "t99": t * rng.choice([4, 5, 6]), "S": rng.choice([130, 140, 150, 160]),
            "Rho": rng.choice([60, 70, 75]), "R": rng.choice([10, 15, 20, 30])}


def _stem(P, ctx):
    return (f"{ctx[0].upper() + ctx[1:]}: {P['K']} {plural(P['K'], 'экземпляр', 'экземпляра', 'экземпляров')} "
            f"приложения за балансировщиком, в пик — {num(P['lam'])} запросов в секунду на весь сервис. Каждый запрос "
            f"держит соединение из пула в среднем {P['t']} мс (p99 — {P['t99']} мс). Балансировщик неравномерен: "
            f"самому загруженному экземпляру достаётся в {num(P['S'] / 100, 1)} раза больше запросов, чем в среднем. "
            f"Чтобы не росла очередь за соединением, пул экземпляра должен быть занят не больше чем на {P['Rho']} %; "
            f"пулы у всех экземпляров одинаковые. Выкладка идёт с maxSurge {P['u']}: на это время живут ещё "
            f"{P['u']} {plural(P['u'], 'экземпляр', 'экземпляра', 'экземпляров')} с полным пулом. На БД "
            f"{P['R']} соединений держатся в резерве (миграции, администрирование, репликация).\n\n"
            "Какое наименьшее значение max_connections нужно на БД, чтобы выкладка в пик не упёрлась в лимит?")


def _explain(P, a, traps):
    p = -(-(P["lam"] * P["t"] * P["S"]) // (1000 * P["K"] * P["Rho"]))
    busy = P["lam"] * P["t"] / 1000
    return (f"Закон Литтла: в среднем занято λ·t = {num(busy, 1)} соединений на сервис, на самый загруженный экземпляр "
            f"— {num(busy * P['S'] / 100 / P['K'], 2)}; при занятости ≤ {P['Rho']} % пул экземпляра — не меньше "
            f"{p}. На выкладке живут {P['K']} + {P['u']} экземпляров: ({P['K']} + {P['u']}) · {p} + {P['R']} резерва = "
            f"{a}.")


TRAP_DESC = {"p99": "время удержания p99 вместо среднего (закон Литтла — по среднему)",
             "no_skew": "без неравномерности балансировщика", "no_rho": "без целевой занятости пула",
             "no_surge": "без экземпляров выкладки (maxSurge)", "no_reserve": "без резерва на БД",
             "naive": "пул по среднему потоку без запаса и без выкладки",
             "reserve_each": "резерв прибавлен к пулу каждого экземпляра",
             "two_queries": "запас +35 % времени удержания на повторную проверку в транзакции",
             "double_surge": "двойной maxSurge на случай одновременного отката",
             "blue_green": "выкладка посчитана как удвоение парка (blue-green), а не maxSurge"}


def generate(seed: int):
    return numeric_variant(FAMILY_ID, seed, contexts=CONTEXTS, sample=_sample, model=MODEL, stem=_stem,
                           explain=_explain, rel=0.06, abs_min=3, trap_desc=TRAP_DESC)

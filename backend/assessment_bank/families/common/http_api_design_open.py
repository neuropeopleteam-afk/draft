def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    what, acc, coll, ctx, money = rng.choice(DOMAINS)
    conseq = ("часть дублей приводит к двойному списанию денег" if money else
              "дубли ломают отчёты и рассылают повторные уведомления")
    topic = rng.choice(sorted(TOPICS))
    T = TOPICS[topic]
    stem = T["text"].format(what=what, acc=acc, conseq=conseq, field="amount" if money else "size",
                            obj="{value, currency}" if money else "{value, unit}", coll=coll, rows=rng.choice([40, 120, 300, 800]),
                            dup=rng.choice([50, 200, 1500]), clients=rng.choice([60, 250, 900]),
                            size=rng.choice([2, 5, 10]))
    stem = f"Контекст: {ctx}. " + stem + " Ответ — 8–15 предложений."
    rubric = rubric_from({**T, "notes": "Оценка по критериям рубрики; эталоны — ориентиры уровня, "
                                         "а не требуемая формулировка."})
    ak = AnswerKey(kind="rubric", value="rubric",
                   explanation="Открытый ответ оценивается по рубрике (сильный/средний/слабый).")
    return build_variant(FAMILY_ID, seed, stem=stem, answer_key=ak, rubric=rubric, context=ctx,
                         verification="rubric_only", language="text", params={"topic": topic})

"""common.strategy.tech_strategy_open — open_answer (Principal): техническая стратегия инженерной организации на два квартала.

Дано: число команд, метрики поставки (частота выкладок, время от коммита до продакшна, доля неудачных
изменений, время восстановления), доля времени на инциденты, бизнес-цель на два квартала и бюджет
времени на техническую работу. Узкое место в метриках задаётся параметром варианта (качество изменений,
очередь поставки или восстановление) — кандидат должен его диагностировать по числам, выбрать ставки и явно
сказать, чего не делаем, выстроить порядок с обратимыми шагами и контрольными точками, объяснить, как
согласовать команды. Это Principal: решение на уровне организации с компромиссами, а не список практик.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import scenario_variant

FAMILY_ID = "common.strategy.tech_strategy_open"

CONTEXTS = ["маркетплейс", "онлайн-банк", "платформа найма", "логистика", "телемедицина", "агрегатор путешествий"]

BOTTLENECKS = {
    "quality": dict(
        metrics=dict(deploy="{deploys} выкладок в неделю", lead="{lead} дня", cfr="{cfr_hi} %", mttr="{mttr_lo} ч"),
        diag=("узкое место — качество изменений: доля неудачных изменений {cfr_hi} % при нормальном времени "
              "восстановления; команды часто выкладывают и часто чинят, отсюда {toil} % времени на инциденты"),
        bets=("ставки: контрактные и интеграционные тесты на 5–7 самых аварийных границ между сервисами, "
              "канареечная выкладка с автоматическим откатом по SLO, флаги функций для отделения выкладки от "
              "включения; не делаем сейчас: переписывание монолита и смену языка — они не снижают долю неудачных "
              "изменений в горизонте двух кварталов"),
        target="доля неудачных изменений ≤ 15 % к концу второго квартала, время на инциденты ≤ 15 %"),
    "flow": dict(
        metrics=dict(deploy="1 выкладка в {weeks} недели", lead="{lead_hi} дней", cfr="{cfr_lo} %", mttr="{mttr_lo} ч"),
        diag=("узкое место — поток поставки: изменения неделями ждут общего релиза и ручного регресса "
              "(от коммита до продакшна {lead_hi} дней), при этом доля неудачных изменений {cfr_lo} % — "
              "приемлемая; большие пачки изменений делают каждый релиз рискованным"),
        bets=("ставки: автоматизировать регресс критичных сценариев, перейти от общего релиза к независимым "
              "выкладкам по сервисам с канарейкой, сократить размер пачки (trunk-based, флаги функций); не "
              "делаем сейчас: микросервисное дробление всего монолита — сначала разрезаем релизный поезд, а не код"),
        target="время от коммита до продакшна ≤ 2 дней, выкладки — ежедневно по каждому сервису"),
    "recovery": dict(
        metrics=dict(deploy="{deploys} выкладок в неделю", lead="{lead} дня", cfr="{cfr_lo} %", mttr="{mttr_hi} ч"),
        diag=("узкое место — восстановление: инциденты редкие, но каждый длится {mttr_hi} ч — нет быстрого отката, "
              "наблюдаемость не позволяет локализовать отказ, дежурство не налажено; отсюда {toil} % времени на "
              "инциденты при невысокой доле неудачных изменений"),
        bets=("ставки: откат за минуты (неизменяемые артефакты, обратимые миграции expand/contract), "
              "наблюдаемость по SLO с трассировкой ключевых путей, дежурство с инструкциями действий и разбором "
              "каждого инцидента; не делаем сейчас: расширение тестового покрытия «вообще» — оно не сокращает "
              "время восстановления"),
        target="время восстановления ≤ 1 ч для 80 % инцидентов, откат любой выкладки ≤ 10 мин"),
}


def _build(rng, ctx):
    kind = rng.choice(sorted(BOTTLENECKS))
    B = BOTTLENECKS[kind]
    v = dict(teams=rng.choice([8, 12, 15, 20, 25]), deploys=rng.choice([10, 15, 25]), weeks=rng.choice([2, 3]),
             lead=rng.choice([2, 3]), lead_hi=rng.choice([12, 18, 25]), cfr_hi=rng.choice([28, 34, 41]),
             cfr_lo=rng.choice([8, 11]), mttr_lo=rng.choice([1, 2]), mttr_hi=rng.choice([7, 10, 16]),
             toil=rng.choice([25, 30, 35, 40]), cap=rng.choice([20, 25, 30]),
             goal=rng.choice(["выход в две новые страны", "запуск подписки", "открытый API для партнёров",
                              "мобильное приложение для продавцов"]))
    m = {k: s.format(**v) for k, s in B["metrics"].items()}
    stem = (f"Вы — главный инженер (Principal) компании ({ctx}): {v['teams']} продуктовых команд, монолит и десяток "
            f"сервисов вокруг него. Метрики поставки за квартал: частота выкладок — {m['deploy']}; время от коммита "
            f"до продакшна — {m['lead']}; доля неудачных изменений — {m['cfr']}; время восстановления — {m['mttr']}; "
            f"на инциденты и ручную рутину уходит около {v['toil']} % времени инженеров. Бизнес-цель на два квартала — "
            f"{v['goal']}; на техническую работу руководство готово отдать не больше {v['cap']} % мощности команд.\n\n"
            "Предложите техническую стратегию на два квартала: диагноз по метрикам, 2–3 ставки и что сознательно "
            "НЕ делаете, порядок шагов с контрольными точками и критериями остановки, как измерите результат и как "
            "договоритесь с командами и руководством. Ответ — 15–25 предложений.")
    diag = B["diag"].format(**v)
    criteria = [
        ("diagnosis", f"Диагноз по числам условия, а не общими словами: {diag}", 0.25),
        ("bets", (f"Ставки с явными компромиссами и отказами: {B['bets']}; связывает ставки с целью «{v['goal']}» и "
                  f"укладывается в {v['cap']} % мощности"), 0.25),
        ("sequencing", ("Порядок и обратимость: пилот на 1–2 командах, контрольная точка через 4–6 недель с "
                        "критерием «продолжать/остановить», затем тиражирование; называет риски (просадка поставки "
                        "фич, сопротивление команд) и как их снимает"), 0.2),
        ("measurement", f"Измерение: целевые значения с датами ({B['target']}), базовая линия текущего квартала, "
                        "кто и где смотрит метрики; метрики не превращаются в план для команд", 0.15),
        ("alignment", ("Согласование в инженерных терминах: RFC или дизайн-ревью ставок, владельцы (платформенная "
                       "команда или гильдия), как высвобождается мощность (сокращение рутины), как объясняет "
                       "руководству связь с бизнес-целью"), 0.15),
    ]
    strong = (f"Диагноз: {diag}. Поэтому {B['bets']}. Ставки обслуживают цель «{v['goal']}»: новые фичи пойдут "
              f"быстрее и безопаснее, если сначала снять узкое место. Бюджет {v['cap']} % делю так: половина — "
              f"платформенная команда на общие инструменты, половина — время в продуктовых командах на внедрение. "
              f"Порядок: шесть недель пилота на двух командах с самыми плохими метриками, контрольная точка с "
              f"критерием «метрика сдвинулась хотя бы на треть — тиражируем, нет — пересматриваем ставку», затем "
              f"волнами по 3–4 команды. Цели к концу второго квартала: {B['target']}; базовая линия — текущий "
              f"квартал, метрики смотрим на ежемесячном техсовете, но не ставим их командам как план, чтобы их не "
              f"подгоняли. Риски: просадка фич в первые недели — закладываю её в план с руководством; "
              f"сопротивление команд — каждую ставку оформляю как RFC с обсуждением, первыми идут добровольцы. "
              f"Руководству объясняю в терминах цели: сейчас {v['toil']} % времени инженеров уходит на инциденты и "
              f"рутину — возврат даже трети этого времени равен нескольким командам.")
    medium = (f"Нужно улучшить метрики: добавить автотесты, наладить CI/CD и мониторинг. Начать с пилота на паре "
              f"команд, потом распространить. Следить за частотой выкладок и долей неудачных изменений.")
    weak = "Нужно переписать монолит на микросервисы и нанять больше инженеров."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=f"Узкое место варианта — {kind}; диагноз другого узкого места без опоры на числа — не засчитывается.",
                explanation=f"Узкое место по метрикам — {kind}: {diag}.",
                params=dict(kind=kind, teams=v["teams"], cap=v["cap"], toil=v["toil"], goal=v["goal"]))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

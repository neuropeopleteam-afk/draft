"""common.strategy.migration_plan_mcq — mcq_concept (Principal): план миграции хранилища без простоя и с откатом.

Данные переносятся из старого хранилища в новое под нагрузкой (записи идут всё время). Варианты ответа —
четыре плана из пяти шагов: двойная запись, перенос истории, сверка, переключение чтения, остановка записи в
старое (точка невозврата). Верен ровно один: двойная запись → перенос истории без перезаписи более новых
версий → сверка → чтение из нового → остановка записи в старое.

Дистракторы — содержательные ошибки миграций; тонкий дистрактор присутствует всегда (от него зависит
трудность), два других выбираются из трёх:
  * overwrite_backfill (всегда) — порядок верный, но перенос истории перезаписывает строки снимком, сделанным
    до начала переноса: обновления, пришедшие двойной записью во время переноса, затираются старой версией;
  * backfill_first — перенос до двойной записи: записи между снимком и включением двойной записи теряются;
  * stop_before_read — запись в старое остановлена до переключения чтения: читатели видят устаревшие данные;
  * read_before_backfill — чтение переключено до переноса истории: старые записи «пропадают».
Ключ проверяется исполнением: программа-модель проигрывает каждый план на событиях (записи между шагами и
во время переноса, чтения после каждого шага) и проверяет инварианты «нет потерянных обновлений» и «каждое
чтение возвращает последнюю версию»; печатает букву единственного плана без нарушений.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import numeric_mcq
from assessment_bank.gen_utils import make_rng

FAMILY_ID = "common.strategy.migration_plan_mcq"

CONTEXTS = [
    ("store", "профили кандидатов", "PostgreSQL 11 на своём сервере", "управляемый PostgreSQL 16"),
    ("store", "заказы маркетплейса", "MySQL", "PostgreSQL"),
    ("store", "история платежей", "Oracle", "PostgreSQL"),
    ("store", "события доставки", "MongoDB", "PostgreSQL с секционированием"),
    ("column", "таблица заказов", "колонка `addr`", "колонка `delivery_address`"),
    ("column", "таблица вакансий", "колонка `salary`", "колонка `salary_range`"),
    ("column", "таблица клиентов", "колонка `phone`", "колонка `phone_e164`"),
    ("service", "остатки на складах", "монолитная база", "сервис остатков"),
    ("service", "записи к врачам", "общая база клиник", "сервис расписаний"),
    ("service", "подписки пользователей", "база монолита", "сервис подписок"),
]

# Формулировки шагов по подтипам (перенос хранилища, переименование колонки, вынос данных в сервис);
# у каждого шага — несколько равнозначных формулировок, в варианте выбирается одна на шаг для всех планов.
STEPS = {
    "store": {
        "D": ["включить двойную запись (каждая запись — в старое и в новое)",
              "писать каждое изменение и в старое, и в новое хранилище"],
        "B": ["перенести историю, не перезаписывая в новом более новую версию строки",
              "скопировать историю, пропуская строки, у которых в новом версия новее"],
        "Bw": ["перенести историю, записывая в новое снимок старого как есть",
               "скопировать историю снимком старого поверх того, что уже есть в новом"],
        "V": ["сверить старое и новое (контрольные суммы по диапазонам ключей)",
              "сравнить хранилища по контрольным суммам диапазонов ключей"],
        "R": ["переключить чтение на новое", "читать из нового хранилища"],
        "S": ["прекратить запись в старое", "перестать писать в старое хранилище"],
    },
    "column": {
        "D": ["писать значение в обе колонки", "каждое изменение записывать и в старую, и в новую колонку"],
        "B": ["заполнить новую колонку из старой, не трогая строки, где новая уже свежее",
              "дозаполнить новую колонку только там, где её значение старее старой"],
        "Bw": ["заполнить новую колонку копией старой во всех строках",
               "скопировать старую колонку в новую поверх текущих значений"],
        "V": ["сравнить колонки по всем строкам и посчитать расхождения",
              "проверить запросом, что колонки совпадают во всех строках"],
        "R": ["читать новую колонку", "переключить код чтения на новую колонку"],
        "S": ["перестать писать в старую колонку", "убрать запись в старую колонку"],
    },
    "service": {
        "D": ["монолит пишет и в свою таблицу, и через API сервиса",
              "каждое изменение монолит отправляет и в свою таблицу, и в сервис"],
        "B": ["перенести историю в сервис, пропуская записи, у которых в сервисе версия новее",
              "загрузить историю в сервис с проверкой версии: более новые записи не трогать"],
        "Bw": ["перенести историю в сервис, перезаписывая записи снимком из монолита",
               "загрузить в сервис снимок таблицы монолита поверх имеющихся записей"],
        "V": ["сверить данные монолита и сервиса по контрольным суммам",
              "сравнить данные монолита и сервиса выборочно и по контрольным суммам"],
        "R": ["клиенты читают из сервиса", "переключить чтение клиентов на API сервиса"],
        "S": ["монолит перестаёт писать в свою таблицу", "отключить запись в таблицу монолита"],
    },
}
PLANS = {
    "good": ["D", "B", "V", "R", "S"],
    "overwrite_backfill": ["D", "Bw", "V", "R", "S"],
    "backfill_first": ["B", "D", "V", "R", "S"],
    "stop_before_read": ["D", "B", "V", "S", "R"],
    "read_before_backfill": ["D", "R", "B", "V", "S"],
}

PROGRAM = """plans = {plans}
N_KEYS = {n_keys}
HOT = {hot}                       # ключ, который обновляют во время переноса истории

def run(plan):
    old = {{k: 1 for k in range(N_KEYS)}}       # версия строки в старом хранилище
    new = {{}}
    latest = dict(old)
    dual = False; stop_old = False; read_new = False; bad = []
    def write(k):
        latest[k] = latest.get(k, 0) + 1
        if not stop_old:
            old[k] = latest[k]
        if dual or stop_old:
            new[k] = latest[k]
    def read_all(tag):
        src = new if read_new else old
        for k in latest:
            if src.get(k) != latest[k]:
                bad.append((tag, k)); return
    for i, step in enumerate(plan):
        if step == "D":
            dual = True
        elif step in ("B", "Bw"):
            snapshot = dict(old)               # перенос читает старое...
            write(HOT)                         # ...а приложение тем временем обновляет строку
            for k, ver in snapshot.items():
                if step == "B" and new.get(k, 0) >= ver:
                    continue                   # не перезаписывать более новую версию
                new[k] = ver
        elif step == "V":
            pass                               # сверка не меняет данных; расхождение заметит только при чтении
        elif step == "R":
            read_new = True
        elif step == "S":
            stop_old = True
        write(1 + (i * 3) % (N_KEYS - 1))      # запись между шагами (HOT после переноса не трогаем)
        write(N_KEYS + i)                      # новая строка
        read_all(step)
    read_all("end")
    return not bad

opts = __OPTS__
ok = [letter for letter, text in opts.items() if run(plans[text])]
print(ok[0] if len(ok) == 1 else "AMBIGUOUS")
"""


def _text(plan: list[str], words: dict) -> str:
    return " → ".join(f"{i}) {words[s]}" for i, s in enumerate(plan, 1))


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    kind, what, src, dst = rng.choice(CONTEXTS)
    words = {k: rng.choice(v) for k, v in STEPS[kind].items()}
    rps = rng.choice([150, 300, 600, 1200])
    rows = rng.choice(["40 млн", "120 млн", "300 млн", "1,1 млрд"])
    others = rng.sample(["backfill_first", "stop_before_read", "read_before_backfill"], 2)
    chosen = ["overwrite_backfill"] + sorted(others)
    texts = {k: _text(PLANS[k], words) for k in ["good"] + chosen}
    goal = ("ни одно обновление не теряется, и каждое чтение возвращает последнюю версию" if rng.random() < 0.5
            else "не теряется ни одно изменение, а чтение всегда видит последнее значение")
    if kind == "store":
        stem = (f"Нужно перенести «{what}» из «{src}» в «{dst}» без простоя: {rows} строк, запись идёт всё время "
                f"(около {rps} изменений в секунду, строки обновляются, в том числе пока идёт перенос). До последнего "
                f"шага должен оставаться откат на старое хранилище. Какой план выполняет обе цели — {goal}?")
    elif kind == "column":
        stem = (f"В «{what}» ({rows} строк) {src} заменяется на {dst} без остановки приложения: около {rps} "
                f"изменений в секунду, строки обновляются и во время заполнения новой колонки. До последнего шага "
                f"нужно сохранить возможность вернуть старый код. Какой план выполняет обе цели — {goal}?")
    else:
        stem = (f"Данные «{what}» ({rows} записей) выносятся из «{src}» в «{dst}» без простоя; около {rps} "
                f"изменений в секунду, записи меняются и во время переноса. До последнего шага должен оставаться "
                f"откат на монолит. Какой план выполняет обе цели — {goal}?")
    plans_by_text = {texts[k]: PLANS[k] for k in texts}
    program = PROGRAM.format(plans=repr(plans_by_text), n_keys=rng.choice([5, 6, 7]), hot=0)
    expl = ("Верен порядок «двойная запись → перенос истории без перезаписи более новых версий → сверка → чтение "
            "из нового → остановка записи в старое»: двойная запись до переноса закрывает окно потерь, сравнение "
            "версий не даёт снимку затереть обновление, пришедшее во время переноса, а остановка записи в старое "
            "последней сохраняет откат. Перенос «снимком как есть» затирает обновления, сделанные во время "
            "переноса (сверка их может не поймать, если строка снова изменится); перенос до двойной записи теряет "
            "записи между снимком и включением; остановка записи до переключения чтения отдаёт устаревшие данные; "
            "чтение до переноса истории «теряет» старые строки.")
    return numeric_mcq(FAMILY_ID, seed, rng, ctx=what, stem=stem, good=texts["good"],
                       distractors=[texts[k] for k in chosen], program=program, explanation=expl,
                       params={"kind": kind, "distractors": chosen, "rps": rps, "rows": rows},
                       note="Ответ проверяется программой-моделью: каждый план проигрывается на событиях записи и "
                            "чтения, проверяются инварианты.")

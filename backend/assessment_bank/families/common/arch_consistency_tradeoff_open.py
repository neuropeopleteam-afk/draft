"""common.arch.consistency_tradeoff_open — open_answer (Lead): модель согласованности для каждой операции системы.

Дана система (предметная область варианта) с репликацией между узлами или регионами: задержка репликации,
задержка между регионами, требование p99. Из пула операций выбраны три с разными «правильными» требованиями
(строгая согласованность / чтение своих записей / монотонное чтение / ограниченная устарелость / итоговая
согласованность), плюс особенность варианта (разрыв связи между регионами, переключение лидера при
асинхронной репликации, «сделать всё строгим» ценой задержки). Кандидат выбирает модель на каждую
операцию с ценой решения, механизм реализации, отвечает на особенность и описывает проверку.
Рубрика 0–4: по критерию на операцию (ожидаемая модель — в критерии), механизм, особенность, проверка.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import scenario_variant

FAMILY_ID = "common.arch.consistency_tradeoff_open"

CONTEXTS = ["маркетплейс", "онлайн-банк", "платформа найма", "сервис бронирования отелей", "социальная сеть",
            "онлайн-школа"]

# операция -> (текст, ожидаемая модель, обоснование для критерия и эталона)
OPS = {
    "debit": ("списание с баланса клиента при оплате", "строгая (линеаризуемая) согласованность",
              "двойное списание или уход в минус недопустимы: запись — через лидера/кворум с проверкой условия "
              "(сравнение версии или условное обновление) и ключом идемпотентности"),
    "reserve": ("резервирование последней единицы товара или места", "строгая согласованность",
                "две брони одного места недопустимы: условная запись через лидера или кворум (R + W > N), "
                "либо единственный владелец ключа"),
    "username": ("регистрация уникального имени пользователя", "строгая согласованность",
                 "уникальность — глобальный инвариант: условная вставка в одном месте истины (уникальный "
                 "индекс у лидера), а не проверка «нет ли такого» на реплике"),
    "profile": ("редактирование своего профиля и показ его автору", "чтение своих записей",
                "автор должен сразу видеть свою правку, остальным допустима задержка: чтение автора — у лидера "
                "или по токену сессии с версией записи, остальные — с реплик"),
    "chat": ("лента сообщений в переписке", "монотонное чтение и причинный порядок",
             "сообщения не должны «исчезать» и переставляться при переключении реплики: привязка сессии к "
             "реплике или чтение не старее последней виденной версии, порядок — по номеру в переписке"),
    "price": ("показ цены в каталоге", "ограниченная устарелость (не старее заданного окна)",
              "показ может отставать на секунды, но не больше окна; при оформлении цена перепроверяется у "
              "источника истины"),
    "likes": ("счётчик лайков или просмотров", "итоговая согласованность",
              "точность в моменте не нужна: счётчики без конфликтов (CRDT, сложение дельт) или пакетная "
              "агрегация, чтение с любой реплики"),
    "feed": ("рекомендательная лента на главной", "итоговая согласованность",
             "устарелость на минуты допустима: кэш и реплики, пересчёт по расписанию; строгость здесь — "
             "только лишняя задержка и цена"),
}
STRICT = {"debit", "reserve", "username"}

TWISTS = {
    "partition": dict(
        text="связь между регионами пропадает в среднем на {part_min} мин раз в квартал",
        crit=("разрыв связи на {part_min} мин: что делает каждая операция — строгие отказывают в записи в "
              "регионе без лидера/кворума (выбор согласованности, а не доступности), остальные продолжают "
              "работать локально и сходятся после восстановления; это согласовано с продуктом"),
        strong=("при разрыве на {part_min} мин строгие операции в отрезанном регионе отказывают с понятным "
                "сообщением — это осознанный выбор согласованности; остальные работают локально и сходятся "
                "после восстановления, конфликты профиля решаю по версии записи.")),
    "failover": dict(
        text=("репликация асинхронная, отставание реплики в пике — до {lag_ms} мс; при отказе лидера реплика "
              "становится лидером автоматически"),
        crit=("переключение лидера при асинхронной репликации теряет до {lag_ms} мс подтверждённых записей: для "
              "строгих операций — синхронная или полусинхронная репликация (или кворумная запись), для "
              "остальных потеря окна допустима; названа цена в задержке записи"),
        strong=("при автоматическом переключении с отставанием до {lag_ms} мс подтверждённые списания могут "
                "потеряться — для строгих операций включаю синхронную репликацию хотя бы на одну реплику "
                "(запись дороже на один круг ≈ {rtt} мс), остальным потеря окна допустима.")),
    "all_strict": dict(
        text=("руководитель предлагает «для простоты» сделать все операции строгими; задержка между регионами — "
              "{rtt} мс, требование p99 чтения — {p99} мс"),
        crit=("ответ на «всё строгое»: строгое чтение через лидера в другом регионе стоит ≥ {rtt} мс и не "
              "укладывается в p99 {p99} мс, плюс теряется доступность при разрыве; строгость — только там, где "
              "нарушение инварианта дороже задержки, с числами"),
        strong=("«всё строгое» означает межрегиональный круг ≥ {rtt} мс на каждом чтении при требовании p99 "
                "{p99} мс — не укладываемся, и при разрыве связи встанет весь сайт; строгость оставляю только "
                "для инвариантов, где ошибка дороже задержки.")),
}


def _build(rng, ctx):
    strict = rng.choice(sorted(STRICT))
    rest = rng.sample(sorted(set(OPS) - STRICT), 2)
    ops = [strict] + rest
    rng.shuffle(ops)
    kind = rng.choice(sorted(TWISTS))
    v = dict(part_min=rng.choice([10, 20, 45]), lag_ms=rng.choice([200, 500, 1500]),
             rtt=rng.choice([40, 70, 120]), p99=rng.choice([50, 80, 100]))
    if kind == "all_strict" and v["p99"] > v["rtt"]:
        v["p99"] = rng.choice([p for p in (30, 50) if p < v["rtt"]] or [v["rtt"] // 2])
    T = TWISTS[kind]
    regions = rng.choice([2, 3])
    ops_txt = "\n".join(f"{i}. {OPS[o][0].capitalize()}." for i, o in enumerate(ops, 1))
    stem = (f"Вы — ведущий инженер «{ctx}». Данные реплицируются между {regions} регионами, задержка между "
            f"регионами ≈ {v['rtt']} мс. Особенность: {T['text'].format(**v)}.\n\nОперации:\n{ops_txt}\n\n"
            "Для каждой операции выберите модель согласованности (строгая, чтение своих записей, монотонное "
            "чтение, ограниченная устарелость, итоговая) и объясните, чем платите за выбор; опишите механизм "
            "реализации, ответьте на особенность и скажите, как проверите, что выбранные гарантии соблюдаются. "
            "Ответ — 10–16 предложений.")
    criteria = []
    ws = [0.17, 0.17, 0.16]
    for i, (o, w) in enumerate(zip(ops, ws), 1):
        criteria.append((f"op{i}_{o}", f"Операция {i} ({OPS[o][0]}): {OPS[o][1]} — {OPS[o][2]}", w))
    criteria += [
        ("mechanism", ("Механизм назван конкретно: лидер или кворум (R + W > N) для строгих, токен сессии с "
                       "версией или привязка к реплике для чтения своих записей, CRDT или агрегация для счётчиков; "
                       "условные записи и ключ идемпотентности"), 0.15),
        ("twist", T["crit"].format(**v), 0.2),
        ("verify", ("Проверка гарантий: метрика отставания реплик и алерт на окно устарелости, тест с разрывом "
                    "связи и переключением лидера (проверка инвариантов после), счётчик нарушений инварианта"), 0.15),
    ]
    strong = " ".join(f"Операция {i} — {OPS[o][1]}: {OPS[o][2]}." for i, o in enumerate(ops, 1))
    strong += (" Строгость стоит задержки записи (круг до лидера или кворума) и доступности при разрыве, "
               "поэтому она только там, где нарушение инварианта дороже. " + T["strong"].format(**v) +
               " Проверяю: отставание реплик — метрика с алертом на окно, учения с разрывом связи и "
               "переключением лидера с проверкой инвариантов (нет двойных списаний, броней, имён), счётчик "
               "нарушений — ноль.")
    medium = ("Деньги и бронирования — строго, остальное — итоговая согласованность; использовать реплики для "
              "чтения и мониторинг отставания.")
    weak = "Возьмём базу с транзакциями — она обеспечит согласованность везде."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=("Ожидаемые модели: " + "; ".join(f"{i} — {OPS[o][1]}" for i, o in enumerate(ops, 1)) +
                       ". Обоснованный более строгий выбор для нестрогой операции — балл 2–3, если названа цена."),
                explanation=("Ожидаемые модели: " + "; ".join(f"{i} — {OPS[o][1]}" for i, o in enumerate(ops, 1))
                             + f"; особенность — {kind}."),
                params=dict(ops=ops, kind=kind, regions=regions, **v))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

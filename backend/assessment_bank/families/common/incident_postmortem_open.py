def _hm(m: int) -> str:
    return f"{10 + m // 60:02d}:{m % 60:02d}"


def _build(rng, ctx):
    kind = rng.choice(sorted(INCIDENTS))
    I = INCIDENTS[kind]
    err = rng.choice([8, 12, 18, 25, 35])
    rps = rng.choice([400, 600, 900, 1500, 2500])
    p99 = rng.choice([4, 6, 9, 12])
    detect = rng.choice([6, 9, 14, 21])
    ack = detect + rng.choice([3, 5, 8])
    mitig = ack + rng.choice([12, 18, 25, 33])
    resolve = mitig + rng.choice([4, 7])
    slo = rng.choice(["99,9", "99,95"])
    rel = rng.choice(["2.14", "2.31", "3.4", "5.12", "7.0"])
    mult = rng.choice([5, 7, 9])
    mult = f"{mult} {plural(mult, 'раз', 'раза', 'раз')}"
    ts = [0, 0, detect, ack, mitig, resolve]
    vals = dict(rel=rel, err=err, p99=p99, mult=mult)
    timeline = "\n".join(f"{_hm(t)} — {e.format(**vals)}" for t, e in zip(ts, I["events"]))
    dur = resolve                       # минут от начала до нормы
    failed = rps * 60 * dur * err / 100
    budget_frac = (1 - float(slo.replace(",", ".")) / 100)
    month_bad_min = budget_frac * 30 * 24 * 60          # «минут полной недоступности» в месяце
    burn = dur * err / 100 / month_bad_min              # доля месячного бюджета ошибок
    stem = (f"Сервис ({ctx}), обычная нагрузка — {rps} запросов/с, SLO — {slo} % успешных запросов за 30 дней. "
            f"Хронология инцидента (время МСК, один день):\n{timeline}\n\n"
            "Напишите основу постмортема без поиска виновных: влияние в цифрах (длительность, примерное число "
            "неуспешных запросов, какая доля месячного бюджета ошибок израсходована); триггер, корневая причина и "
            "способствующие факторы — раздельно; почему обнаружили через столько минут; 4–6 действий с "
            "приоритетом, ролью-владельцем и способом проверки, что мера работает. Ответ — 12–20 предложений.")
    n_min = lambda x: f"{x} {plural(x, 'минута', 'минуты', 'минут')}"
    criteria = [
        ("impact", (f"Влияние в цифрах: длительность около {dur} мин (от {_hm(0)} до {_hm(resolve)}), неуспешных "
                    f"запросов порядка {fmt_num(failed, 0)} ({rps} запросов/с × {err} % × {dur} мин), израсходовано "
                    f"около {round(100 * burn)} % месячного бюджета ошибок при SLO {slo} %; допустимы округления, "
                    f"но не отсутствие расчёта"), 0.25),
        ("causality", (f"Разделяет триггер ({I['trigger']}) и корневую причину ({I['root']}); называет "
                       f"способствующие факторы ({I['factors']}); формулировки системные, без виноватого человека"),
         0.3),
        ("detection", (f"Объясняет обнаружение: от начала до алерта или эскалации {n_min(detect)}, до подтверждения — "
                       f"{n_min(ack)}; предлагает обнаружение по симптому пользователя (алерт по скорости расхода "
                       f"бюджета SLO, синтетическая проверка) с маршрутом на дежурного"), 0.2),
        ("actions", ("Действия конкретные и проверяемые: приоритет (P0/P1), роль-владелец, срок или метрика "
                     "проверки (учения, игровой день, алерт сработал на стенде); устраняют корневую причину, а не "
                     "только триггер; без «быть внимательнее»"), 0.25),
    ]
    strong = (f"Влияние: {dur} мин деградации ({_hm(0)}–{_hm(resolve)}), около {err} % запросов с ошибкой при "
              f"{rps} запросах/с — порядка {fmt_num(failed, 0)} неуспешных запросов. Бюджет SLO {slo} % за 30 дней — "
              f"{fmt_num(100 * budget_frac, 2)} % запросов, то есть эквивалент {fmt_num(month_bad_min, 1)} мин полной "
              f"недоступности; мы израсходовали {dur} × {err} % ≈ {fmt_num(dur * err / 100, 1)} мин, около "
              f"{round(100 * burn)} % месячного бюджета. Триггер — {I['trigger']}. Корневая причина — {I['root']}. "
              f"Способствующие факторы: {I['factors']}. Обнаружение заняло {n_min(detect)}, подтверждение — ещё "
              f"{ack - detect} мин: алерт был не по симптому пользователя. Действия: {I['actions']}. Каждое действие "
              f"закрывается проверкой, а не отметкой в задаче; виноватых нет — меняем систему.")
    medium = (f"Инцидент длился около {dur} минут, ошибок было много. Причина — {I['trigger']}. Нужно добавить "
              f"алерты на дежурного и автоматизировать шаг, который привёл к сбою, и провести учения.")
    weak = "Инженер, выкативший изменение, ошибся; нужно быть внимательнее и проводить ревью тщательнее."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=f"Сценарий {kind}; числа для проверки расчёта — в критерии impact.",
                explanation=(f"Длительность {dur} мин, ≈ {fmt_num(failed, 0)} неуспешных запросов, ≈ {round(100 * burn)} % "
                             f"месячного бюджета; триггер — {I['trigger']}, корневая причина — {I['root']}."),
                params=dict(kind=kind, err=err, rps=rps, dur=dur, detect=detect, ack=ack, slo=slo,
                            failed=round(failed), budget_pct=round(100 * burn)))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

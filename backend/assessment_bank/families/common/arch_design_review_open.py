SLOS = [("99,9", 43), ("99,95", 22), ("99,5", 216)]


def _facts(rng, ctx):
    slo, budget = rng.choice(SLOS)
    vals = dict(ctx=ctx, svc=rng.choice(SERVICES), slo=slo, budget=budget,
                avg=rng.choice([300, 450, 800, 1200, 2000]), peak_mult=rng.choice([3, 4, 6]),
                p99=rng.choice([250, 300, 400, 500]), rtt=rng.choice([60, 90, 120, 150]),
                warm=rng.choice([4, 6, 8]))
    vals["peak"] = f"{vals['peak_mult']} {plural(vals['peak_mult'], 'раз', 'раза', 'раз')}"
    intro = (f"Команда ({ctx}) просит вас как ведущего инженера провести ревью дизайна нового сервиса "
             f"{vals['svc']} перед запуском. Нагрузка — в среднем {vals['avg']} запросов/с, в пик — в "
             f"{vals['peak']} выше; цели: доступность {slo} % за месяц, p99 ≤ {vals['p99']} мс.")
    return vals, intro



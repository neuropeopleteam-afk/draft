"""common.arch.capacity_design_open — open_answer (Lead): развёрнутое архитектурное задание с оценкой ёмкости.

Дано: аудитория в день, действий на пользователя, доля записей, пиковый коэффициент, размер объекта, срок
хранения, репликация, требование к задержке и особенность варианта (горячие ключи, два региона, жёсткий
бюджет). Кандидат оценивает пиковую нагрузку на чтение и запись, объём хранения и кэша (генератор считает
опорные числа — они в рубрике), предлагает архитектуру чтения и записи, разбиение данных, отвечает на
особенность варианта и описывает проверку ёмкости. Рубрика 0–4 по критериям с опорными числами.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant
from assessment_bank.gen_utils import plural

FAMILY_ID = "common.arch.capacity_design_open"

CONTEXTS = [("лента новостей", "публикация", "просмотр ленты"), ("отзывы о товарах", "отзыв", "чтение отзывов"),
            ("чат поддержки", "сообщение", "чтение переписки"), ("лента вакансий", "отклик", "просмотр вакансий"),
            ("фотохостинг", "загрузка фото", "просмотр фото"), ("трекер доставки", "событие доставки", "запрос статуса")]

TWISTS = {
    "hot_keys": dict(
        text="{hot_pct} % чтений приходится на 100 самых популярных объектов",
        crit=("горячие ключи: {hot_pct} % чтений на 100 объектов — одна партиция и один узел кэша не выдержат; "
              "локальный кэш в процессе на секунды, реплики горячих ключей, объединение одинаковых запросов "
              "(single flight), защита от лавины при истечении"),
        strong=("{hot_pct} % чтений на 100 объектов — это ≈ {hot_rps} запросов/с в несколько ключей: распределённый "
                "кэш упрётся в один узел. Держу горячие объекты в локальном кэше процесса на 1–5 с, объединяю "
                "одинаковые промахи в один запрос к базе и сдвигаю время истечения случайным образом.")),
    "two_regions": dict(
        text="пользователи в двух регионах, задержка между ними {lag} мс, требование p99 чтения — {p99} мс",
        crit=("два региона: при задержке {lag} мс и p99 {p99} мс чтение должно обслуживаться в своём регионе — "
              "реплики для чтения в обоих, запись в домашний регион пользователя или асинхронная репликация с "
              "оговорённой задержкой видимости"),
        strong=("при {lag} мс между регионами и p99 {p99} мс межрегиональный запрос на чтении недопустим: в каждом "
                "регионе — реплика и кэш, запись — в домашний регион пользователя, в другой — асинхронно; "
                "задержку видимости до секунд явно согласую с продуктом.")),
    "budget": dict(
        text="бюджет на хранение — не больше {budget_tb} ТБ с учётом реплик",
        crit=("бюджет {budget_tb} ТБ меньше оценки {storage_tb} ТБ: уровни хранения (горячие данные — в базе, "
              "старые — в объектном хранилище со сжатием), сокращение реплик для холодного слоя, политика "
              "удаления — с числами"),
        strong=("оценка {storage_tb} ТБ не помещается в {budget_tb} ТБ, поэтому хранение по уровням: последние "
                "90 дней — в базе с тремя репликами, старше — в объектном хранилище со сжатием (примерно втрое) и "
                "кодированием вместо трёх копий; удаление по сроку хранения автоматическое.")),
}


def _r(x: float) -> str:
    """Округление до двух значащих цифр для опорных чисел."""
    if x >= 100:
        from math import floor, log10
        p = 10 ** (floor(log10(x)) - 1)
        return fmt_num(round(x / p) * p, 0)
    return fmt_num(x, 1)


def _build(rng, ctx_t):
    ctx, write_what, read_what = ctx_t
    kind = rng.choice(sorted(TWISTS))
    dau = rng.choice([2, 5, 12, 30])                     # млн в день
    acts = rng.choice([20, 40, 80])                      # действий на пользователя в день
    wshare = rng.choice([0.02, 0.05, 0.1])
    peak = rng.choice([3, 4, 6])
    size_kb = rng.choice([1, 2, 4, 8])
    years = rng.choice([1, 2, 3])
    total = dau * 1e6 * acts
    avg_rps = total / 86400
    peak_rps = avg_rps * peak
    w_rps, r_rps = peak_rps * wshare, peak_rps * (1 - wshare)
    storage_tb = total * wshare * size_kb * 365 * years * 3 / 1e9
    cache_gb = total * (1 - wshare) * 0.2 * size_kb / 1e6 * 0.1   # 10 % объектов дня дают 80 % чтений (оценка)
    if kind == "budget" and storage_tb < 3:
        kind = rng.choice(["hot_keys", "two_regions"])     # бюджет имеет смысл только при заметном объёме
    T = TWISTS[kind]
    v = dict(hot_pct=rng.choice([30, 45, 60]), lag=rng.choice([40, 70, 120]), p99=rng.choice([80, 120, 150]),
             budget_tb=max(1, round(storage_tb * rng.choice([0.3, 0.4, 0.5]))))
    v["hot_rps"] = _r(r_rps * v["hot_pct"] / 100)
    v["storage_tb"] = _r(storage_tb)
    tw = T["text"].format(**v)
    nums = dict(w=_r(w_rps), r=_r(r_rps), st=_r(storage_tb), cache=_r(max(cache_gb, 1)))
    stem = (f"Вы — ведущий инженер. Проектируете «{ctx}»: {dau} млн активных пользователей в день, в среднем "
            f"{acts} действий на пользователя, из них {fmt_num(100 * wshare, 0)} % — запись ({write_what}), остальное — "
            f"чтение ({read_what}). Пик в {peak} {plural(peak, 'раз', 'раза', 'раз')} выше среднего. Объект — около {size_kb} КБ, хранить "
            f"{years} {'год' if years == 1 else 'года'}, три реплики. Особенность: {tw}.\n\n"
            "Оцените пиковую нагрузку на чтение и запись, объём хранения и кэша (покажите расчёт), предложите "
            "архитектуру путей чтения и записи и разбиение данных, ответьте на особенность и скажите, как "
            "проверите, что система выдержит. Ответ — 12–20 предложений.")
    criteria = [
        ("estimate", (f"Оценка с расчётом: пик ≈ {nums['w']} запросов/с на запись и ≈ {nums['r']} на чтение, хранение "
                      f"≈ {nums['st']} ТБ с репликами (допуск — в пределах двукратного), кэш — порядок десятков ГБ "
                      f"или обоснованная доля горячих данных"), 0.25),
        ("paths", ("Пути чтения и записи: кэш перед хранилищем с ожидаемой долей попаданий, запись через очередь "
                   "или напрямую с обоснованием, отдельные реплики для чтения, ограничения по задержке"), 0.2),
        ("partition", ("Разбиение данных: ключ партиционирования с обоснованием (равномерность, локальность "
                       "запросов), число партиций с запасом роста, перебалансировка"), 0.2),
        ("twist", T["crit"].format(**v), 0.2),
        ("verify", ("Проверка: нагрузочный тест на 1,5–2 × пик, запас ёмкости, метрики насыщения и алерты, "
                    "план роста"), 0.15),
    ]
    strong = (f"Всего {fmt_num(total / 1e6, 0)} млн действий в день — ≈ {_r(avg_rps)} запросов/с в среднем, в пике "
              f"×{peak} ≈ {_r(peak_rps)}: из них ≈ {nums['w']} запись и ≈ {nums['r']} чтение. Хранение: "
              f"{fmt_num(total * wshare / 1e6, 1)} млн объектов в день × {size_kb} КБ × 365 × {years} × 3 реплики ≈ "
              f"{nums['st']} ТБ. Кэш: если 10 % объектов дня дают 80 % чтений, хватает ≈ {nums['cache']} ГБ. Чтение — "
              f"через кэш с ожидаемым попаданием 80–90 % и реплики, запись — в основное хранилище с подтверждением, "
              f"тяжёлую обработку — через очередь. Разбиваю по идентификатору владельца (хэш), партиций — с запасом "
              f"на трёхкратный рост, перебалансировка без простоя. Особенность: "
              + T["strong"].format(**v) + " Проверяю нагрузочным тестом на двукратный пик, слежу за насыщением "
              "(CPU, очередь, доля попаданий кэша) и держу запас 30–50 %.")
    medium = ("Нужен кэш, шардирование базы и очередь для записи; нагрузка большая, поэтому горизонтальное "
              "масштабирование и нагрузочное тестирование.")
    weak = "Возьмём надёжную базу данных и добавим серверов, если будет тормозить."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=f"Опорные числа варианта: запись ≈ {nums['w']}/с, чтение ≈ {nums['r']}/с, хранение ≈ {nums['st']} ТБ.",
                explanation=(f"Пик: запись ≈ {nums['w']}/с, чтение ≈ {nums['r']}/с; хранение ≈ {nums['st']} ТБ; "
                             f"особенность — {kind}."),
                params=dict(kind=kind, dau=dau, acts=acts, wshare=wshare, peak=peak, size_kb=size_kb, years=years))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

"""backend.strategy.sharding_plan_open — open_answer (Principal): план масштабирования базы до упора по диску и записи.

Дана одна основная база (PostgreSQL) с репликами чтения: объём данных и прирост в месяц, предел диска,
поток записи и его рост, предел записи основного узла (по нагрузочному тесту). Из чисел варианта
считаются опорные сроки для рубрики: месяцев до упора по диску и месяцев до упора по записи — что
наступит раньше и сколько времени есть. Кандидат выбирает путь (вертикальный рост, разгрузка
архивом/холодным хранилищем, секционирование, шардирование по ключу, распределённая СУБД) с ценой,
ключ шардирования по профилю запросов варианта, онлайн-миграцию (двойная запись или CDC, перенос по
арендаторам, сверка, откат), этапы при заданной команде и сроке.
Особенность варианта: «горячий» арендатор с большой долей записи, доля межарендаторных отчётных
запросов, сезонный пик раньше упора.
Рубрика 0–4: сроки по числам, выбор пути с ценой, ключ, миграция с откатом, особенность, этапы и метрики.
"""
from __future__ import annotations

import math

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant

FAMILY_ID = "backend.strategy.sharding_plan_open"

CONTEXTS = [("платформа найма", "работодатель"), ("SaaS для бухгалтерии", "организация"),
            ("маркетплейс", "продавец"), ("CRM для малого бизнеса", "компания-клиент"),
            ("платформа онлайн-школ", "школа"), ("сервис доставки для ресторанов", "ресторан")]

TWISTS = {
    "hot_tenant": dict(
        text="один {tenant} даёт {hot} % всей записи, и его доля растёт",
        crit=("горячий арендатор ({hot} % записи): шардирование только по арендатору упрётся в один шард — "
              "выделенный шард для него или составной ключ (арендатор + хэш сущности) внутри арендатора, "
              "проверка, что его пик помещается в предел одного узла"),
        strong=("один {tenant} даёт {hot} % записи — при ключе «арендатор» его шард станет новым узким местом; "
                "выношу его на выделенный шард, а внутри — составной ключ (арендатор, хэш сущности), проверяю "
                "его пик нагрузочным тестом на одном узле.")),
    "reports": dict(
        text="{rep} % запросов — отчёты по всем арендаторам сразу (руководство и аналитика)",
        crit=("межарендаторные отчёты ({rep} % запросов): после шардирования это рассылка по всем шардам — "
              "выносятся в аналитическое хранилище через CDC (с допустимой задержкой), а не исполняются "
              "по шардам; согласовано, какая устарелость отчётов допустима"),
        strong=("{rep} % запросов — отчёты по всем арендаторам: на шардах это рассылка по всем узлам, поэтому "
                "отчёты переезжают в аналитическое хранилище через CDC с задержкой в минуты, что согласую с "
                "владельцами отчётов.")),
    "peak": dict(
        text="через {peak_m} мес. — сезонный пик, запись в пике в {peak_x} раза выше обычной",
        crit=("сезонный пик через {peak_m} мес. с записью ×{peak_x}: упор по записи в пике наступает раньше "
              "расчётного — до пика нужен временный запас (вертикальный рост, разгрузка тяжёлых записей, "
              "очередь), миграция не должна идти в пик (заморозка изменений)"),
        strong=("через {peak_m} мес. пик с записью ×{peak_x} — упор по записи в пике раньше расчётного, "
                "поэтому до пика беру временный запас (узел крупнее, разгрузка тяжёлых записей в очередь), а "
                "миграцию переношу на после пика и замораживаю изменения на время пика.")),
}


def _months(cur: float, cap: float, growth_per_month: float, compound: bool) -> float:
    if cur >= cap:
        return 0.0
    if compound:
        return math.log(cap / cur) / math.log(1 + growth_per_month)
    return (cap - cur) / growth_per_month


def _build(rng, ctx_t):
    ctx, tenant = ctx_t
    for _ in range(500):
        size_tb = rng.choice([2.5, 4, 6, 9])
        disk_tb = rng.choice([10, 16, 20])
        grow_tb = rng.choice([0.2, 0.3, 0.5, 0.8])           # ТБ в месяц
        wps = rng.choice([3000, 5000, 8000, 12000])          # записей в секунду в пике
        cap_wps = rng.choice([15000, 20000, 25000])          # предел основного узла по нагрузочному тесту
        g = rng.choice([0.04, 0.06, 0.08, 0.1])               # рост записи в месяц
        m_disk = _months(size_tb, disk_tb * 0.8, grow_tb, False)   # до 80 % диска
        m_write = _months(wps, cap_wps * 0.7, g, True)            # до 70 % предела записи
        if 4 <= min(m_disk, m_write) <= 30 and abs(m_disk - m_write) >= 2:
            break
    team = rng.choice([4, 6, 8])
    kind = rng.choice(sorted(TWISTS))
    v = dict(tenant=tenant, hot=rng.choice([18, 25, 35]), rep=rng.choice([3, 8, 15]),
             peak_m=max(2, int(min(m_disk, m_write)) - rng.choice([2, 3])), peak_x=rng.choice([2, 3]))
    first = "диску" if m_disk < m_write else "записи"
    m_first, m_second = sorted([m_disk, m_write])
    T = TWISTS[kind]
    stem = (f"Вы — главный инженер «{ctx}». Все данные — в одной основной базе PostgreSQL с двумя репликами "
            f"чтения; почти все запросы — в пределах одного арендатора ({tenant}). Сейчас: {fmt_num(size_tb, 1)} ТБ "
            f"данных, прирост ≈ {fmt_num(grow_tb, 1)} ТБ в месяц, диск основного узла — {disk_tb} ТБ (порог "
            f"эксплуатации — 80 %). Запись в пике — {fmt_num(wps, 0)} в секунду, растёт на {fmt_num(100 * g, 0)} % "
            f"в месяц; нагрузочный тест показал предел основного узла ≈ {fmt_num(cap_wps, 0)} записей в секунду "
            f"(порог — 70 %). Команда платформы — {team} инженеров. Особенность: {T['text'].format(**v)}.\n\n"
            "Предложите стратегию на полтора-два года: когда и во что упрёмся (посчитайте), какой путь выбираете "
            "и чем он хуже альтернатив, ключ шардирования (если шардируете), как мигрировать без остановки и с "
            "откатом, ответ на особенность, этапы с учётом команды и метрики, по которым поймёте, что план "
            "работает. Ответ — 12–18 предложений.")
    criteria = [
        ("numbers", (f"Сроки посчитаны: до 80 % диска ≈ {fmt_num(m_disk, 0)} мес. ((0,8 × {disk_tb} − "
                     f"{fmt_num(size_tb, 1)}) / {fmt_num(grow_tb, 1)}), до 70 % предела записи ≈ "
                     f"{fmt_num(m_write, 0)} мес. (рост сложным процентом); раньше упрёмся в {first} — через "
                     f"≈ {fmt_num(m_first, 0)} мес.; от этого срока строится план"), 0.18),
        ("path", ("Выбор пути с ценой: вертикальный рост и архив холодных данных — временный запас, не решение "
                  "по записи; секционирование помогает обслуживанию и архиву, но не пределу записи одного узла; "
                  "шардирование по арендатору (или распределённая СУБД) — решение по записи ценой сложности "
                  "межшардовых запросов, транзакций и эксплуатации; сравнение хотя бы с одной альтернативой"),
         0.18),
        ("key", (f"Ключ шардирования — {tenant} (запросы почти все в пределах арендатора), каталог «арендатор → "
                 f"шард» вместо хэша по модулю (перенос арендатора без перехэширования всех), учёт неравномерности"),
         0.14),
        ("migration", ("Онлайн-миграция: перенос по арендаторам — копия + CDC (или двойная запись) → сверка "
                       "контрольных сумм → переключение арендатора в каталоге → наблюдение; откат — "
                       "переключение назад, пока старая копия обновляется; начинать с малых арендаторов"), 0.18),
        ("twist", T["crit"].format(**v), 0.18),
        ("phases", (f"Этапы под команду из {team}: сначала запас до первого упора (≈ {fmt_num(m_first, 0)} мес.), "
                    f"затем каталог и маршрутизация, затем перенос волнами; метрики — запас по диску и записи "
                    f"в % от порога, доля арендаторов на новых шардах, p99 запросов до/после, расхождения сверки = 0"),
         0.14),
    ]
    strong = (f"Диск: (0,8 × {disk_tb} − {fmt_num(size_tb, 1)}) / {fmt_num(grow_tb, 1)} ≈ {fmt_num(m_disk, 0)} мес.; "
              f"запись: log(0,7 × {fmt_num(cap_wps, 0)} / {fmt_num(wps, 0)}) / log(1 + {fmt_num(g, 2)}) ≈ "
              f"{fmt_num(m_write, 0)} мес. — первым упрёмся в {first} через ≈ {fmt_num(m_first, 0)} мес., вторым — "
              f"через ≈ {fmt_num(m_second, 0)}. Архив холодных данных и узел крупнее дают запас, но предел записи "
              f"одного узла не снимают; распределённая СУБД — это переписывание запросов и новая эксплуатация, "
              f"поэтому выбираю шардирование по ключу «{tenant}» с каталогом «арендатор → шард»: перенос арендатора — "
              f"запись в каталоге, а не перехэширование. Миграция по арендаторам: копия + CDC, сверка "
              f"контрольных сумм, переключение в каталоге, откат — обратное переключение, пока старая копия "
              f"обновляется; начинаю с малых. " + T["strong"].format(**v) +
              f" Команда из {team}: квартал — запас и каталог с маршрутизацией, дальше перенос волнами. Метрики — "
              f"запас по диску и записи в % от порога, доля арендаторов на шардах, p99 до/после, расхождения "
              f"сверки — ноль.")
    medium = ("Перейти на шардирование по арендатору, сначала добавить реплики и секционирование, мигрировать "
              "через двойную запись.")
    weak = "Купить сервер мощнее и добавить ещё реплик — этого хватит надолго."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: до 80 % диска ≈ {m_disk:.1f} мес., до 70 % предела записи ≈ {m_write:.1f} мес.; "
                       f"первым — {first}. Реплики чтения не помогают пределу записи: ответ «добавить реплик» — "
                       f"критерий path не выше 1. Особенность — {kind}."),
                explanation=(f"Первый упор — по {first} через ≈ {m_first:.0f} мес. (диск ≈ {m_disk:.1f}, запись "
                             f"≈ {m_write:.1f}); особенность — {kind}."),
                params=dict(kind=kind, size_tb=size_tb, disk_tb=disk_tb, grow_tb=grow_tb, wps=wps, cap_wps=cap_wps,
                            g=g, team=team, m_disk=round(m_disk, 1), m_write=round(m_write, 1), first=first))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

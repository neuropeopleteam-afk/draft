CTX = [("orders", "status", "state", "маркетплейс"), ("payments", "amount_kop", "amount_minor", "финтех"),
       ("users", "phone", "phone_e164", "соцсеть"), ("bookings", "date", "check_in_date", "туризм"),
       ("invoices", "client", "client_id", "B2B-биллинг")]


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    table, old, new, ctx = rng.choice(CTX)
    topic = rng.choice(sorted(TOPICS))
    T = TOPICS[topic]
    vals = dict(table=table, old=old, new=new, rows=rng.choice([80, 200, 600]),
                pods=rng.choice([4, 12, 30]), consumers=rng.choice([3, 5, 8]),
                lost=rng.choice([2, 5, 20]), ttl=rng.choice([10, 30, 60]),
                burst=rng.choice([300, 2000, 8000]), dup=rng.choice([2, 3]))
    stem = f"Контекст: {ctx}. " + T["text"].format(**vals) + " Ответ — 8–15 предложений."
    spec = {**T, "strong": T["strong"].format(**vals), "notes": "Оценка по критериям рубрики; "
            "эталоны — ориентиры уровня, а не требуемая формулировка."}
    ak = AnswerKey(kind="rubric", value="rubric",
                   explanation="Открытый ответ оценивается по рубрике (сильный/средний/слабый).")
    return build_variant(FAMILY_ID, seed, stem=stem, answer_key=ak, rubric=rubric_from(spec),
                         context=ctx, verification="rubric_only", language="text",
                         params={"topic": topic})

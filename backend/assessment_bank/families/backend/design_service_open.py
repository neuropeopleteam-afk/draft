CTX = ["маркетплейс", "сервис доставки еды", "онлайн-кинотеатр", "банк", "сервис бронирования отелей",
       "B2B-платформа закупок"]
ENDPOINTS = ["GET /orders/{id}", "POST /checkout", "GET /catalog/search", "GET /profile",
             "POST /payments"]


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    topic = rng.choice(sorted(TOPICS))
    T = TOPICS[topic]
    ctx = rng.choice(CTX)
    p_from = rng.choice([180, 250, 400])
    vals = dict(ctx=ctx, endpoint=rng.choice(ENDPOINTS),
                when=rng.choice(["пятницу", "понедельник", "среду"]),
                p_from=p_from, p_to=p_from * rng.choice([3, 5, 8]), sample=rng.choice([1, 5, 10]),
                sources=rng.choice([6, 12, 25]), peak=rng.choice(["50 тыс.", "200 тыс.", "1 млн"]),
                outage=rng.choice([5, 15, 40]), normal=rng.choice([80, 120, 200]),
                slow=rng.choice([10, 20, 30]), rps=rng.choice([150, 400, 900]),
                devs=rng.choice([25, 40, 70]), teams=rng.choice([3, 5, 8]),
                consumers=rng.choice([3, 6, 9]), retention=rng.choice([7, 14, 30]))
    stem = f"Контекст: {ctx}. " + T["text"].format(**vals) + " Ответ — 8–15 предложений."
    spec = {**T, "strong": T["strong"].format(**vals), "weak": T["weak"].format(**vals),
            "notes": "Оценка по критериям рубрики; эталоны — ориентиры уровня, а не требуемая "
                     "формулировка. Конкретные числа из условия в сильном ответе используются."}
    ak = AnswerKey(kind="rubric", value="rubric",
                   explanation="Открытый ответ оценивается по рубрике (сильный/средний/слабый).")
    return build_variant(FAMILY_ID, seed, stem=stem, answer_key=ak, rubric=rubric_from(spec),
                         context=ctx, verification="rubric_only", language="text",
                         params={"topic": topic})

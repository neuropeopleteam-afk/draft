CONTEXTS = ["сервис заказов", "API личного кабинета", "сервис уведомлений", "платёжный шлюз",
            "сервис отчётов", "интеграция с CRM"]


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    idx = rng.randrange(len(SCENARIOS))
    scen, correct, distr, why = SCENARIOS[idx]
    s = rng.choice([1, 2, 3, 5])
    n = rng.choice([10, 20, 50, 100])
    k = rng.choice([10_000, 100_000, 1_000_000])
    vals = dict(s=s, n=n, c=rng.choice([4, 8, 16]), k=k, total=n * k, p=rng.choice([5, 10, 20]),
                s2=s + rng.choice([2, 5, 10]))
    ctx = rng.choice(CONTEXTS)
    stem = f"Контекст: {ctx}. " + scen.format(**vals)
    opts, key = make_options(rng, (correct.format(**vals), None),
                             [(d.format(**vals), None) for d in distr])
    ak = AnswerKey(kind="option", value=key, explanation=why)
    return build_variant(FAMILY_ID, seed, stem=stem, options=opts, answer_key=ak, context=ctx,
                         verification="reference_table", language="text", params={"scenario": idx})

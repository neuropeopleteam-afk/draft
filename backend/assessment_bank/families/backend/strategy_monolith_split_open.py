"""backend.strategy.monolith_split_open — open_answer (Principal): дробить ли монолит и как.

Дан монолит (возраст, размер, число команд, общая база), главная боль задаётся параметром варианта (общий
релизный поезд, узкое место масштабирования одного модуля или размытое владение) и бизнес-цель. Кандидат
решает, нужно ли выделять сервисы, какие первыми и почему (по движущим силам, а не «по моде»), как
провести границы данных, в каком порядке и с какими контрольными точками, чего это стоит платформенно и как
понять, что пора остановиться. Уровень Principal: решение с компромиссами на годы, а не список паттернов.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import scenario_variant

FAMILY_ID = "backend.strategy.monolith_split_open"

CONTEXTS = [
    ("маркетплейс", ["каталог", "корзина и заказы", "платежи", "доставка", "отзывы"]),
    ("платформа найма", ["вакансии", "отклики", "поиск кандидатов", "биллинг", "уведомления"]),
    ("онлайн-банк", ["карты", "переводы", "кредиты", "антифрод", "уведомления"]),
    ("агрегатор путешествий", ["поиск предложений", "бронирования", "платежи", "лояльность", "поддержка"]),
    ("онлайн-школа", ["каталог курсов", "оплаты", "расписание", "домашние задания", "сертификаты"]),
]

PAINS = {
    "release": dict(
        text=("единый релизный поезд: {teams} команд выкладываются вместе раз в {weeks} недели, около {share} % "
              "откатов вызваны чужими изменениями в общем релизе"),
        first=("первым выделяю модуль «{mod_a}»: он меняется чаще всех и у него ясная граница, — это сразу разрежет "
               "релизный поезд; до этого — модульные границы внутри монолита и независимая выкладка его частей "
               "за флагами"),
        metric="частота выкладок модуля «{mod_a}» — ежедневно, доля откатов из-за чужих изменений — ниже 5 %"),
    "scaling": dict(
        text=("модуль «{mod_b}» даёт около {share} % нагрузки CPU в пик и масштабируется только вместе со всем "
              "монолитом; в распродажи приходится держать {x} копий всего приложения"),
        first=("первым выделяю «{mod_b}» — у него свой профиль нагрузки и ясный интерфейс; прежде чем дробить, "
               "проверяю дешёвые меры (кэш, отдельный пул воркеров, реплики чтения): если их хватает, сервис "
               "не нужен"),
        metric="стоимость инфраструктуры в пик — минус треть, p99 модуля «{mod_b}» в пик — в пределах SLO"),
    "ownership": dict(
        text=("около {share} % инцидентов затрагивают код без одной команды-владельца; изменение в «{mod_a}» требует "
              "согласования четырёх команд, общая база — {tables} таблиц, на которые пишут все"),
        first=("сначала — владение, а не сервисы: закрепляю модули за командами и запрещаю писать в чужие таблицы "
               "(модульный монолит с проверкой зависимостей в CI); выделять «{mod_a}» в сервис — только когда "
               "граница данных устоялась"),
        metric="доля инцидентов без владельца — ниже 10 %, изменения «{mod_a}» — силами одной команды"),
}


def _build(rng, ctx_t):
    ctx, mods = ctx_t
    kind = rng.choice(sorted(PAINS))
    P = PAINS[kind]
    mod_a, mod_b = rng.sample(mods, 2)
    v = dict(teams=rng.choice([6, 9, 12, 16]), weeks=rng.choice([2, 3]), share=rng.choice([30, 40, 55, 60]),
             x=rng.choice([12, 20, 30]), tables=rng.choice([280, 420, 650]), mod_a=mod_a, mod_b=mod_b,
             age=rng.choice([6, 8, 11]), loc=rng.choice(["700 тыс.", "1,2 млн", "2 млн"]),
             goal=rng.choice(["открытый API для партнёров", "выход в новую страну", "мобильное приложение нового "
                              "поколения", "B2B-кабинет для крупных клиентов"]))
    pain = P["text"].format(**v)
    first = P["first"].format(**v)
    metric = P["metric"].format(**v)
    stem = (f"Вы — главный инженер (Principal), компания — {ctx}. Монолиту {v['age']} лет, {v['loc']} строк, над ним "
            f"работают {v['teams']} команд, база общая ({v['tables']} таблиц). Главная боль: {pain}. Через три квартала "
            f"бизнес хочет {v['goal']}. Руководство спрашивает: «переходим на микросервисы?».\n\n"
            "Дайте позицию: дробить или нет, что выделять первым и почему; как провести границы данных и перенести "
            "их без простоя; порядок шагов с контрольными точками и критериями остановки; что нужно платформе и "
            "сколько это стоит; как измерите успех. Ответ — 15–25 предложений.")
    criteria = [
        ("decision", (f"Решение от движущих сил, а не «микросервисы для всех»: связывает с болью ({pain}); "
                      f"{first}"), 0.25),
        ("data", ("Границы данных: владение таблицами одной командой, запрет чужих записей, перенос через "
                  "«душитель» (strangler) с антикоррупционным слоем, данные — через события/outbox или CDC, "
                  "двойная запись или сверка на время перехода; без распределённых транзакций по умолчанию"), 0.25),
        ("sequencing", ("Порядок и обратимость: пилот на одном модуле, контрольная точка через 1–2 квартала с "
                        "критерием «продолжать/остановиться», маршрутизация трафика с откатом; модульный монолит "
                        "как допустимый конечный результат"), 0.2),
        ("cost", ("Цена и предпосылки: трассировка и метрики по сервисам, отдельная выкладка, контрактные тесты, "
                  "дежурство; оценка в людях и кварталах; рост задержки и отказов сети как плата за разделение"),
         0.15),
        ("metrics", f"Метрики успеха и остановки с числами: {metric}; базовая линия до начала", 0.15),
    ]
    strong = (f"Позиция: не «переходим на микросервисы», а снимаем конкретную боль — {pain}. Поэтому {first}. "
              f"Границы режу по данным: у каждого модуля свои таблицы, чужие записи запрещены проверкой в CI; "
              f"выделение — «душителем»: шлюз маршрутизирует часть запросов в новый сервис, антикоррупционный слой "
              f"переводит старую модель, данные идут событиями через outbox, на время перехода — сверка старого и "
              f"нового. Распределённых транзакций не ввожу — где нужна согласованность, саги с компенсацией. "
              f"Порядок: квартал на модульные границы и пилот, контрольная точка с критерием ({metric}), затем "
              f"решение — продолжать или остановиться на модульном монолите; это допустимый итог. Цена: платформа "
              f"(трассировка, выкладка по сервисам, контрактные тесты, дежурство) — порядка 2–3 человек на два "
              f"квартала, плюс плата за сеть — задержки и частичные отказы, их закладываю в SLO. Цель «{v['goal']}» "
              f"выигрывает: новый интерфейс строится на выделенных границах, а не поверх общего кода.")
    medium = ("Монолит лучше постепенно разбивать на микросервисы, начиная с самых независимых модулей, по паттерну "
              "strangler. Нужны CI/CD, мониторинг и контрактные тесты.")
    weak = "Да, переписываем всё на микросервисы на Go за два квартала, каждой команде — свой сервис."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=f"Боль варианта — {kind}; ответ «дробить всё» без связи с болью — не выше среднего уровня.",
                explanation=f"Боль варианта — {kind}: {pain}. Ожидаемое решение: {first}.",
                params=dict(kind=kind, mod_a=mod_a, mod_b=mod_b, teams=v["teams"], goal=v["goal"]))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

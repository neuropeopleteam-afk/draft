"""data_eng.strategy.principal_governance_open — open_answer (Principal): управление данными в компании без бюрократии.

Дана компания варианта: число наборов данных в хранилище, доля с владельцем и описанием, инциденты
качества в месяц и доля из них, вызванных изменениями в источниках, доля наборов с персональными данными,
число потребителей (отчёты, модели). Опорные числа для рубрики: сколько наборов без владельца (наборы ×
(1 − доля)) и сколько инцидентов в месяц снимут контракты данных на источниках (инциденты × доля «из-за
источника»); сколько наборов с персональными данными надо разметить и закрыть.
Кандидат предлагает: владение (доменные команды — владельцы своих наборов, центральная — платформа и
стандарты), каталог с происхождением данных (lineage), контракты данных на границе источник → хранилище
с проверкой в CI источника, уровни критичности и SLA качества (свежесть, полнота) для критичных,
классификацию и доступ к персональным данным (152-ФЗ: минимизация, маскирование, журнал доступа),
приоритеты и метрики — без «комитета по данным» на каждый шаг.
Особенность: проверка регулятора через полгода, слияние с другой компанией (два хранилища), требование
«самообслуживания» аналитики.
Рубрика 0–4: числа и приоритеты, владение и каталог, контракты и SLA, персональные данные и доступ,
особенность, метрики и этапы.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant

FAMILY_ID = "data_eng.strategy.principal_governance_open"

CONTEXTS = ["банк", "сеть клиник", "маркетплейс", "страховая компания", "телеком-оператор", "онлайн-ритейлер"]

TWISTS = {
    "regulator": dict(
        text="через {months} мес. проверка регулятора по обработке персональных данных",
        crit=("проверка через {months} мес.: в первую очередь — классификация и доступ для ≈ {pd_sets} наборов с "
              "персональными данными (разметка в каталоге, маскирование в аналитических слоях, доступ по ролям и "
              "журнал доступа, сроки хранения и удаление), реестр обработок; остальное управление — после"),
        strong=("проверка через {months} мес. задаёт порядок: сначала ≈ {pd_sets} наборов с персональными данными — "
                "разметка в каталоге, маскирование в аналитике, доступ по ролям с журналом, сроки хранения; "
                "реестр обработок готовлю к проверке, остальное — следом.")),
    "merger": dict(
        text="компания поглощает другую, у которой своё хранилище и свои определения ключевых метрик",
        crit=("слияние: два хранилища и разные определения метрик — словарь ключевых метрик с одним владельцем на "
              "метрику, слой согласованных определений (семантический слой) поверх обоих хранилищ на переходный "
              "период, сопоставление ключей клиентов; переносить данные — после согласования определений"),
        strong=("у поглощаемой компании свои определения метрик — сначала словарь ключевых метрик с владельцем на "
                "каждую и семантический слой поверх обоих хранилищ, сопоставление ключей клиентов; перенос данных "
                "— после согласования определений, иначе получим две разные «выручки» в одном отчёте.")),
    "self_service": dict(
        text="руководство хочет «самообслуживание»: {analysts} аналитиков должны сами находить и брать данные",
        crit=("самообслуживание для {analysts} аналитиков: каталог с поиском, описанием, владельцем, происхождением и "
              "оценкой качества; сертифицированные наборы («золотые») отдельно от черновых; доступ по запросу с "
              "автоматическим одобрением для неперсональных данных; без этого самообслуживание множит ошибки"),
        strong=("чтобы {analysts} аналитиков брали данные сами, им нужен каталог с поиском, владельцем, "
                "происхождением и оценкой качества, отдельный слой сертифицированных наборов и доступ по запросу с "
                "автоматическим одобрением для неперсональных — иначе самообслуживание умножит расхождения.")),
}


def _build(rng, ctx):
    sets = rng.choice([800, 2000, 5000])
    owned = rng.choice([0.2, 0.35, 0.5])
    inc = rng.choice([12, 25, 40])                   # инцидентов качества в месяц
    src_share = rng.choice([0.5, 0.6, 0.7])          # доля из-за изменений в источниках
    pd_share = rng.choice([0.15, 0.25, 0.4])
    consumers = rng.choice([300, 900, 2500])
    team = rng.choice([4, 6, 9])
    kind = rng.choice(sorted(TWISTS))
    no_owner = round(sets * (1 - owned))
    inc_src = round(inc * src_share)
    pd_sets = round(sets * pd_share)
    v = dict(months=rng.choice([4, 6]), pd_sets=fmt_num(pd_sets, 0), analysts=rng.choice([80, 150, 300]))
    T = TWISTS[kind]
    stem = (f"Вы — главный инженер данных; компания — {ctx}. В хранилище ≈ {fmt_num(sets, 0)} наборов данных, владелец и "
            f"описание есть у {fmt_num(100 * owned, 0)} %; потребителей (отчёты, модели, выгрузки) — ≈ {fmt_num(consumers, 0)}. "
            f"Инцидентов качества — ≈ {inc} в месяц, {fmt_num(100 * src_share, 0)} % из них — из-за изменений в "
            f"источниках, о которых никто не предупредил. Персональные данные есть примерно в "
            f"{fmt_num(100 * pd_share, 0)} % наборов, где именно — точно не знают. Команда платформы данных — {team} "
            f"человек. Особенность: {T['text'].format(**v)}.\n\nПредложите стратегию управления данными на год: что "
            "делаете в первую очередь (посчитайте масштаб), кто владеет данными, что входит в каталог, как "
            "предотвращать поломки из-за источников, как работать с персональными данными и доступом, ответ на "
            "особенность и метрики — без бюрократии, которая остановит команды. Ответ — 12–18 предложений.")
    criteria = [
        ("numbers", (f"Масштаб и приоритеты: ≈ {fmt_num(no_owner, 0)} наборов без владельца ({fmt_num(sets, 0)} × "
                     f"{fmt_num(1 - owned, 2)}) — начать с критичных (по числу потребителей и происхождению); "
                     f"контракты на источниках снимут до ≈ {inc_src} из {inc} инцидентов в месяц; ≈ "
                     f"{fmt_num(pd_sets, 0)} наборов с персональными данными разметить"), 0.18),
        ("ownership", (f"Владение и каталог: доменные команды — владельцы своих наборов (федеративно), команда из "
                       f"{team} — платформа, стандарты и инструменты, а не владелец всего; каталог с владельцем, "
                       f"описанием, происхождением (lineage), критичностью; неиспользуемые наборы — на вывод"), 0.16),
        ("contracts", ("Контракты данных на границе источник → хранилище: схема, смысл полей, свежесть, проверка "
                       "совместимости в CI источника и уведомление потребителей; уровни критичности и SLA качества "
                       "(свежесть, полнота, уникальность) с проверками только для критичных"), 0.18),
        ("pd", ("Персональные данные: автоматическая классификация и разметка в каталоге, маскирование или "
                "обезличивание в аналитических слоях, доступ по ролям и по запросу с журналом, сроки хранения и "
                "удаление, минимизация (152-ФЗ)"), 0.16),
        ("twist", T["crit"].format(**v), 0.18),
        ("metrics", ("Этапы и метрики: квартал — каталог и владельцы критичных, контракты на самых «шумных» "
                     "источниках; метрики — доля критичных наборов с владельцем и SLA, инциденты качества в месяц "
                     "(в том числе из-за источников), время обнаружения, доля размеченных наборов с ПД, время "
                     "выдачи доступа"), 0.14),
    ]
    strong = (f"Масштаб: ≈ {fmt_num(no_owner, 0)} наборов без владельца, ≈ {inc_src} из {inc} инцидентов в месяц — из-за "
              f"источников, ≈ {fmt_num(pd_sets, 0)} наборов с персональными данными. Владение федеративное: доменные "
              f"команды владеют своими наборами, команда из {team} даёт платформу и стандарты; начинаю с критичных по "
              f"числу потребителей и происхождению, неиспользуемые вывожу. Каталог — владелец, описание, "
              f"происхождение, критичность. На границе источник → хранилище — контракты данных с проверкой "
              f"совместимости в CI источника; SLA качества и проверки — только для критичных. Персональные данные "
              f"размечаю автоматической классификацией, в аналитике маскирую, доступ — по ролям и по запросу с "
              f"журналом, сроки хранения соблюдаю. " + T["strong"].format(**v) + " Метрики: доля критичных с "
              "владельцем и SLA, инциденты в месяц и из-за источников, время обнаружения, доля размеченных ПД, "
              "время выдачи доступа.")
    medium = ("Внедрить каталог данных, назначить владельцев, добавить проверки качества и ограничить доступ к "
              "персональным данным.")
    weak = "Создать комитет по данным, который будет согласовывать все изменения в хранилище."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: ≈ {no_owner} наборов без владельца; ≈ {inc_src} инцидентов в месяц из-за "
                       f"источников; ≈ {pd_sets} наборов с ПД. «Комитет согласует всё» — критерий ownership 0. "
                       f"Особенность — {kind}."),
                explanation=(f"≈ {no_owner} без владельца, ≈ {inc_src} инцидентов/мес из-за источников, ≈ {pd_sets} с ПД; "
                             f"особенность — {kind}."),
                params=dict(kind=kind, sets=sets, owned=owned, inc=inc, src_share=src_share, pd_share=pd_share,
                            consumers=consumers, team=team, no_owner=no_owner, inc_src=inc_src, pd_sets=pd_sets))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

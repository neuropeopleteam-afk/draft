def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    ctx = rng.choice(CTX)
    topic = rng.choice(sorted(TOPICS))
    T = TOPICS[topic]
    stem = T["text"].format(rate=rng.choice([20, 50, 120]), lag=rng.choice([10, 15, 30]),
                            late=rng.choice([2, 5, 8]), tables=rng.choice([60, 200, 450]),
                            n_prov=rng.choice([3, 5, 8]), hh=rng.choice(["05", "06", "07"]),
                            ms=rng.choice([20, 30, 50]), rps=rng.choice([300, 1500, 4000]))
    stem = f"Контекст: {ctx}. " + stem + " Ответ — 8–15 предложений."
    rubric = rubric_from({**T, "notes": "Оценка по критериям рубрики; эталоны — ориентиры уровня, а не "
                                        "требуемая формулировка и не единственно верная архитектура."})
    ak = AnswerKey(kind="rubric", value="rubric",
                   explanation="Открытый ответ оценивается по рубрике (сильный/средний/слабый).")
    return build_variant(FAMILY_ID, seed, stem=stem, answer_key=ak, rubric=rubric, context=ctx,
                         verification="rubric_only", language="text", params={"topic": topic})

"""data_eng.etl.lead_cdc_design_open — open_answer (Lead): поток изменений (CDC) из рабочей базы в хранилище.

Дана рабочая база варианта (PostgreSQL) и хранилище: поток изменений строк в пике, средний размер события,
пропускная способность одной партиции брокера, объём таблиц для начальной выгрузки и скорость её чтения,
скорость роста журнала предзаписи (WAL). Кандидат проектирует: чтение журнала (логическая репликация),
начальный снимок и переход на поток без потерь и дублей, ключ партиционирования и порядок по ключу,
удаления, применение в хранилище идемпотентным слиянием (MERGE по ключу и номеру позиции журнала),
эволюцию схемы, сверку. Опорные числа для рубрики: поток в МБ/с и число партиций с запасом; время начальной
выгрузки; сколько места займёт журнал, если потребитель простаивает N часов (слот репликации держит WAL).
Особенность варианта: переименование столбца в источнике, простой потребителя и рост WAL, «горячий» ключ.
Рубрика 0–4: снимок и переход, порядок и партиции с числами, применение и удаления, особенность, сверка и мониторинг.
"""
from __future__ import annotations

import math

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant

FAMILY_ID = "data_eng.etl.lead_cdc_design_open"

CONTEXTS = [("заказы маркетплейса", "orders"), ("платежи интернет-банка", "payments"),
            ("отклики на вакансии", "applications"), ("остатки на складах", "stock"),
            ("поездки сервиса такси", "trips"), ("полисы страховой компании", "policies")]

TWISTS = {
    "schema": dict(
        text="команда источника собирается переименовать столбец и сменить тип суммы с целого на десятичный",
        crit=("эволюция схемы: реестр схем с правилами совместимости (добавление — можно, переименование и смена "
              "типа — как новый столбец с переходным периодом), контракт данных с командой источника, проверка "
              "совместимости в их CI; загрузчик не падает молча и не теряет столбец"),
        strong=("переименование и смена типа — несовместимые изменения: в реестре схем правило «только обратно "
                "совместимые», переименование делаем как новый столбец с переходным периодом, контракт данных и "
                "проверка совместимости — в CI команды источника.")),
    "wal": dict(
        text="потребитель потока однажды простоял {down} ч, и диск рабочей базы чуть не переполнился",
        crit=("простой потребителя {down} ч: слот логической репликации держит WAL — ≈ {wal_gb} ГБ ({wal_rate} ГБ/ч × "
              "{down}); алерт на отставание слота, лимит удерживаемого WAL (max_slot_wal_keep_size) с планом "
              "пересоздания снимка, запас диска; потребитель — с автоматическим перезапуском"),
        strong=("за {down} ч простоя слот репликации удержит ≈ {wal_gb} ГБ журнала ({wal_rate} ГБ/ч) — это угроза "
                "рабочей базе; ставлю алерт на отставание слота, ограничиваю удерживаемый WAL и при превышении "
                "пересоздаю снимок, а не роняю базу.")),
    "hot_key": dict(
        text="у одного крупного клиента ≈ {hot} % всех изменений, порядок по нему важен",
        crit=("горячий ключ ({hot} % изменений): при партиционировании по ключу клиента его партиция — узкое место "
              "(≈ {hot_mb} МБ/с против предела {part_mb} МБ/с); ключ партиционирования — первичный ключ строки "
              "(порядок нужен по строке, а не по клиенту) или выделение клиента, проверка задержки по партициям"),
        strong=("{hot} % изменений у одного клиента — при ключе «клиент» его партиция получит ≈ {hot_mb} МБ/с при "
                "пределе {part_mb}; порядок нужен по строке, поэтому партиционирую по первичному ключу строки и "
                "слежу за задержкой по партициям.")),
}


def _build(rng, ctx_t):
    ctx, table = ctx_t
    eps = rng.choice([3000, 8000, 20000, 50000])         # изменений строк в секунду в пике
    ev_kb = rng.choice([0.8, 1.5, 3])
    part_mb = rng.choice([3, 5, 10])                      # МБ/с на партицию (с учётом потребителя)
    size_gb = rng.choice([400, 1200, 3000])
    snap_mb = rng.choice([100, 200, 400])                 # МБ/с чтения снимка
    wal_rate = rng.choice([5, 15, 40])                    # ГБ WAL в час
    down = rng.choice([6, 12, 24])
    kind = rng.choice(sorted(TWISTS))
    mbps = eps * ev_kb / 1000
    parts = max(3, math.ceil(mbps * 2 / part_mb))         # запас ×2
    snap_h = size_gb * 1000 / snap_mb / 3600
    hot = rng.choice([20, 35, 50])
    v = dict(down=down, wal_rate=wal_rate, wal_gb=fmt_num(wal_rate * down, 0), hot=hot,
             hot_mb=fmt_num(mbps * hot / 100, 1), part_mb=part_mb)
    T = TWISTS[kind]
    stem = (f"Вы — ведущий инженер данных. Нужно доставлять изменения таблиц «{ctx}» (основная — `{table}`) из рабочей "
            f"базы PostgreSQL в хранилище с задержкой до минуты вместо ночной выгрузки. В пике — ≈ {fmt_num(eps, 0)} "
            f"изменений строк в секунду, событие — ≈ {fmt_num(ev_kb, 1)} КБ; одна партиция брокера с потребителем "
            f"держит ≈ {part_mb} МБ/с. Начальная выгрузка — ≈ {fmt_num(size_gb, 0)} ГБ, читать можно со скоростью "
            f"≈ {snap_mb} МБ/с, не мешая рабочей нагрузке. База пишет ≈ {wal_rate} ГБ журнала предзаписи в час. "
            f"Особенность: {T['text'].format(**v)}.\n\nСпроектируйте поток изменений: чем читать изменения, как "
            "сделать начальный снимок и перейти на поток без потерь и дублей, сколько партиций и какой ключ "
            "(посчитайте), как применять изменения и удаления в хранилище, ответ на особенность и как проверите, "
            "что хранилище совпадает с источником. Ответ — 10–16 предложений.")
    criteria = [
        ("snapshot", (f"Чтение журнала через логическую репликацию (слот, Debezium или аналог), а не опрос по "
                      f"updated_at; начальный снимок ≈ {fmt_num(size_gb, 0)} ГБ / {snap_mb} МБ/с ≈ {fmt_num(snap_h, 1)} ч — "
                      f"согласованный снимок с позицией журнала (LSN) и продолжение потока с этой позиции, без окна "
                      f"потерь"), 0.2),
        ("order", (f"Поток ≈ {fmt_num(eps, 0)} × {fmt_num(ev_kb, 1)} КБ ≈ {fmt_num(mbps, 1)} МБ/с → с запасом ×2 ≈ "
                   f"{parts} партиций по {part_mb} МБ/с; ключ партиционирования — первичный ключ строки (порядок "
                   f"изменений одной строки сохраняется), порядок между строками не гарантируется и не нужен"),
         0.2),
        ("apply", ("Применение идемпотентным слиянием (MERGE/upsert) по первичному ключу с номером позиции журнала: "
                   "старое событие не затирает новое, повтор безопасен; удаления — по событию удаления (tombstone) "
                   "мягко или физически; дубли при доставке «хотя бы раз» гасятся по позиции"), 0.2),
        ("twist", T["crit"].format(**v), 0.22),
        ("verify", ("Сверка: регулярные контрольные суммы и счётчики по диапазонам ключей источник ↔ хранилище, "
                    "метрики задержки (от фиксации до хранилища) и отставания слота, алерты, план повторной "
                    "загрузки диапазона"), 0.18),
    ]
    strong = (f"Читаю журнал через логическую репликацию (слот + Debezium), а не опросом по updated_at — так видны "
              f"удаления и нет пропусков. Начальный снимок ≈ {fmt_num(size_gb, 0)} ГБ / {snap_mb} МБ/с ≈ {fmt_num(snap_h, 1)} ч "
              f"делаю согласованным с позицией журнала и продолжаю поток с неё. Поток ≈ {fmt_num(mbps, 1)} МБ/с — с "
              f"запасом ×2 нужно {parts} партиций по {part_mb} МБ/с; ключ — первичный ключ строки, порядок нужен "
              f"только внутри строки. В хранилище — MERGE по ключу с номером позиции журнала: старое событие не "
              f"затирает новое, повтор безопасен, удаления — по событию удаления. " + T["strong"].format(**v) +
              " Сверяю контрольными суммами по диапазонам ключей и слежу за задержкой и отставанием слота.")
    medium = ("Поставить Debezium и Kafka, читать изменения из журнала базы и загружать их в хранилище через upsert.")
    weak = "Выгружать таблицы целиком каждые пять минут вместо ночной выгрузки."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: ≈ {mbps:.1f} МБ/с → {parts} партиций; снимок ≈ {snap_h:.1f} ч; WAL за {down} ч "
                       f"простоя ≈ {wal_rate * down} ГБ. Опрос по updated_at без удалений — критерий snapshot не выше 1. "
                       f"Особенность — {kind}."),
                explanation=f"≈ {mbps:.1f} МБ/с, {parts} партиций, снимок ≈ {snap_h:.1f} ч; особенность — {kind}.",
                params=dict(kind=kind, eps=eps, ev_kb=ev_kb, part_mb=part_mb, size_gb=size_gb, snap_mb=snap_mb,
                            wal_rate=wal_rate, down=down, mbps=round(mbps, 2), parts=parts, snap_h=round(snap_h, 2)))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

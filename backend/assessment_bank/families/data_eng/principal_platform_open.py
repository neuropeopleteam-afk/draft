"""data_eng.strategy.principal_platform_open — open_answer (Principal): стратегия платформы данных компании.

Дано: MPP-хранилище и десятки конвейеров у центральной команды, число доменных команд-поставщиков, главная
боль варианта (стоимость лицензий и вычислений растёт, витрины ломаются от изменений у поставщиков, бизнесу
нужна свежесть в минутах вместо суток). Кандидат решает, куда двигать архитектуру (оставить хранилище, open
table formats и lakehouse, гибрид) с ценой, как ввести контракты данных и владение доменами, в каком порядке
мигрировать с параллельным прогоном и сверкой, чем измерять. Уровень Principal: решение на годы для всей
компании.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import scenario_variant

FAMILY_ID = "data_eng.strategy.principal_platform_open"

CONTEXTS = ["банк", "ритейл-сеть", "маркетплейс", "платформа найма", "логистическая компания", "страховая компания"]

PAINS = {
    "cost": dict(
        text="расходы на хранилище растут на {growth} % в год, {cold} % данных никто не читал полгода",
        core=("холодные и сырые данные — в объектное хранилище в открытом табличном формате (Iceberg, Delta), "
              "горячие витрины остаются в MPP; учёт затрат по витринам и владельцам, удаление невостребованного"),
        metric="стоимость хранения и вычислений на терабайт и на витрину, доля холодных данных в дорогом слое"),
    "trust": dict(
        text="за квартал {incidents} инцидентов «сломанных» отчётов из-за изменений у поставщиков",
        core=("контракты данных на границе поставщика (схема, семантика, свежесть, правила совместимости) с "
              "проверкой в CI поставщика, ворота качества перед публикацией; архитектуру хранения пока не трогаю"),
        metric="число инцидентов из-за изменений у поставщиков, доля витрин под контрактом, время обнаружения"),
    "freshness": dict(
        text="бизнесу нужна свежесть {minutes} минут для {share} % витрин вместо суточной загрузки",
        core=("поток (CDC из источников, потоковая обработка) только для витрин, которым нужна свежесть; "
              "остальным — суточные пакеты; единая модель данных для потоковых и пакетных путей"),
        metric="свежесть витрин из списка — p95 задержки ≤ целевых минут, стоимость потокового пути на витрину"),
}


def _build(rng, ctx):
    kind = rng.choice(sorted(PAINS))
    P = PAINS[kind]
    v = dict(pipelines=rng.choice([150, 300, 600]), domains=rng.choice([8, 12, 20]), tb=rng.choice([80, 200, 500]),
             growth=rng.choice([40, 60, 80]), cold=rng.choice([50, 65, 80]), incidents=rng.choice([9, 14, 22]),
             minutes=rng.choice([5, 15, 30]), share=rng.choice([10, 15, 25]), people=rng.choice([6, 10, 14]))
    pain = P["text"].format(**v)
    stem = (f"Вы — главный инженер данных, компания — {ctx}. MPP-хранилище на {v['tb']} ТБ, "
            f"{v['pipelines']} конвейеров ведёт центральная команда из {v['people']} человек, данные поставляют "
            f"{v['domains']} доменных команд. Главная боль: {pain}. Руководство спрашивает, переходить ли на "
            f"lakehouse «целиком».\n\n"
            "Предложите стратегию на 1–2 года: архитектура хранения и обработки (что остаётся, что переезжает и "
            "почему), контракты данных и владение, порядок миграции и как не сломать отчёты, чем измерите успех и "
            "чем рискуете. Ответ — 15–25 предложений.")
    criteria = [
        ("decision", f"Решение от боли ({pain}), а не «lakehouse целиком»: {P['core']}", 0.25),
        ("ownership", ("Контракты и владение: доменные команды владеют своими наборами данных и контрактами "
                       f"(схема, свежесть, совместимость), центральная команда из {v['people']} человек — платформа, "
                       "шаблоны и ворота качества, а не все конвейеры"), 0.2),
        ("migration", ("Миграция: по витринам в порядке ценности или стоимости, параллельный прогон старого и "
                       "нового пути со сверкой итогов, переключение потребителей, критерий отключения старого"), 0.2),
        ("tradeoffs", ("Цена и риски: стоимость двух систем на переходе, компетенции команды, производительность "
                       "интерактивных запросов, «вечная миграция» — ограничение по сроку и бюджету"), 0.2),
        ("metrics", f"Метрики с базовой линией: {P['metric']}", 0.15),
    ]
    strong = (f"Отвечаю на боль — {pain} — а не на моду. Поэтому {P['core']}. Переезд «целиком» не планирую: две "
              f"системы на переходе стоят денег, а выигрыша для части витрин нет. Владение: {v['domains']} доменных "
              f"команд отвечают за свои наборы данных и контракты — схема, семантика, свежесть, правила "
              f"совместимости, проверка в CI поставщика; центральная команда из {v['people']} человек строит "
              f"платформу, шаблоны конвейеров и ворота качества, а не ведёт все {v['pipelines']} конвейеров сама. "
              f"Миграция — по витринам в порядке выгоды: для каждой параллельный прогон старого и нового пути, "
              f"ежедневная сверка итогов, переключение потребителей, затем отключение старого по критерию «месяц без "
              f"расхождений». Риски: стоимость двойного контура, нехватка компетенций, скорость интерактивных "
              f"запросов; ограничиваю переход сроком и бюджетом, раз в квартал пересматриваю. Метрики: {P['metric']}; "
              f"базовая линия — текущий квартал.")
    medium = ("Нужно перейти на lakehouse с открытыми форматами, внедрить контракты данных и data mesh, переносить "
              "витрины постепенно.")
    weak = "Нужно перенести всё в lakehouse за полгода — это современно и дешевле."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=f"Боль варианта — {kind}; решение должно следовать из неё.",
                explanation=f"Боль — {kind}: {pain}. Ожидаемо: {P['core']}.",
                params=dict(kind=kind, pipelines=v["pipelines"], domains=v["domains"], people=v["people"]))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

"""frontend.strategy.design_system_platform_open — open_answer (Principal): дизайн-система как внутренняя платформа.

Дана компания варианта: K продуктовых команд, у каждой — свои копии базовых компонентов (кнопки, поля,
таблицы, модальные окна), доля экранов на общей библиотеке, число найденных дефектов доступности, срок
ребрендинга. Опорные числа для рубрики: сколько реализаций одного компонента правится при ребрендинге
(команды × компоненты без общей библиотеки) против одной правки в пакете; сколько экранов нужно перевести
к сроку (экранов × (1 − доля на библиотеке)) и какой темп переноса это требует.
Кандидат выбирает модель (центральная команда, федеративная с моделью вклада, гибрид), слои (токены
→ примитивы → составные компоненты), версионирование и доставку изменений (семантические версии, автоматические
правки кода — codemods, окно поддержки старых версий), адаптацию, метрики, ответ на особенность.
Особенность: крупная команда на другом фреймворке, жёсткий срок ребрендинга, доступность — требование
регулятора с аудитом.
Рубрика 0–4: числа и выбор модели с ценой, слои и версии, адаптация и доставка, особенность, метрики.
"""
from __future__ import annotations

import math

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant

FAMILY_ID = "frontend.strategy.design_system_platform_open"

CONTEXTS = ["банк с десятком продуктов", "группа компаний электронной коммерции", "государственная платформа услуг",
            "телеком-оператор", "экосистема сервисов для бизнеса", "платформа онлайн-образования"]

TWISTS = {
    "other_fw": dict(
        text="самая крупная команда ({big} % экранов) пишет на другом фреймворке и не хочет переходить",
        crit=("другой фреймворк у команды с {big} % экранов: общий слой, не зависящий от фреймворка — токены "
              "(цвета, отступы, типографика) и, при необходимости, веб-компоненты для примитивов; обёртки под "
              "второй фреймворк дешевле принудительного переписывания; цена — двойная поддержка обёрток"),
        strong=("команда с {big} % экранов на другом фреймворке — не заставляю переписывать: общий слой — "
                "токены и веб-компоненты для примитивов, тонкие обёртки под оба фреймворка; платим двойной "
                "поддержкой обёрток, но это дешевле переписывания {big} % экранов.")),
    "rebrand": dict(
        text="ребрендинг через {months} мес. — к этому сроку новый стиль должен быть везде",
        crit=("ребрендинг через {months} мес.: стиль через токены и тему (смена значений в одном месте), "
              "перевод экранов с копий на пакет — по приоритету трафика, темп ≈ {pace} экранов в месяц; экраны, "
              "которые не успеют, — временный слой переопределения стилей, а не ручная перекраска копий"),
        strong=("до ребрендинга {months} мес. — новый стиль идёт через токены и тему (одна правка значений), а "
                "перевод экранов на пакет — по трафику, ≈ {pace} экранов в месяц; что не успеет — временный слой "
                "переопределения стилей, а не ручная перекраска {copies} копий.")),
    "a11y_audit": dict(
        text="доступность стала требованием регулятора: через {months} мес. внешний аудит, сейчас найдено {defects} дефектов",
        crit=("аудит доступности через {months} мес. ({defects} дефектов): дефекты чинятся в общих компонентах "
              "один раз и доходят до всех через версию пакета; автоматические проверки (axe) в CI и визуальные "
              "регрессионные тесты пакета; копии без библиотеки — главный источник повторяющихся дефектов"),
        strong=("{defects} дефектов доступности при аудите через {months} мес. — чиню их в общих компонентах один "
                "раз, до команд они доходят версией пакета; в CI пакета — axe и визуальные регрессии, а копии без "
                "библиотеки — первые кандидаты на перевод, потому что повторяют одни и те же дефекты.")),
}


def _build(rng, ctx):
    teams = rng.choice([8, 12, 16, 24])
    comps = rng.choice([12, 18, 25])
    screens = rng.choice([400, 700, 1200])
    share = rng.choice([0.2, 0.3, 0.45])               # доля экранов на общей библиотеке
    months = rng.choice([4, 6, 9])
    copy_share = rng.choice([0.6, 0.75, 0.9])          # доля команд с собственными копиями
    ds_team = rng.choice([2, 3, 4])
    copies = round(teams * copy_share) * comps
    to_move = round(screens * (1 - share))
    pace = math.ceil(to_move / months)
    kind = rng.choice(sorted(TWISTS))
    v = dict(big=rng.choice([30, 40]), months=months, pace=pace, copies=fmt_num(copies, 0),
             defects=rng.choice([140, 260, 420]))
    T = TWISTS[kind]
    stem = (f"Вы — главный инженер фронтенда; компания — {ctx}. {teams} продуктовых команд; у "
            f"{fmt_num(100 * copy_share, 0)} % из них свои копии базовых компонентов (≈ {comps} компонентов: кнопки, "
            f"поля, таблицы, модальные окна), общая библиотека покрывает {fmt_num(100 * share, 0)} % из ≈ "
            f"{fmt_num(screens, 0)} экранов. Команда дизайн-системы — {ds_team} человек. Особенность: "
            f"{T['text'].format(**v)}.\n\nПредложите стратегию на год: модель работы дизайн-системы (кто делает "
            "компоненты и как вносят вклад команды) и её цену, слои и версионирование, как доставлять изменения "
            "до команд без «большого переписывания», ответ на особенность и метрики, по которым через полгода "
            "поймёте, что стратегия работает. Посчитайте, во что сейчас обходится любая общая правка и какой темп "
            "переноса экранов нужен. Ответ — 12–18 предложений.")
    criteria = [
        ("numbers", (f"Числа: общая правка (стиль, дефект доступности) сейчас — ≈ {fmt_num(copies, 0)} реализаций "
                     f"({round(teams * copy_share)} команд с копиями × {comps} компонентов) против одной правки в "
                     f"пакете; перевести ≈ {fmt_num(to_move, 0)} экранов, за {months} мес. — ≈ {pace} экранов в "
                     f"месяц; команда из {ds_team} человек сама этого не сделает — нужен вклад команд"), 0.18),
        ("model", (f"Модель с ценой: центральная команда из {ds_team} не успевает за {teams} командами — "
                   f"федеративная модель (вклад команд по правилам, ревью и стандарты у центральной), либо гибрид "
                   f"«ядро централизованно, составные — вкладом»; названа цена (ревью, споры о дизайне, качество "
                   f"вклада)"), 0.16),
        ("layers", ("Слои: токены (цвета, отступы, типографика) → примитивы → составные компоненты; семантическое "
                    "версионирование, журнал изменений, окно поддержки старой версии, ломающие изменения — с "
                    "автоматической правкой кода (codemod)"), 0.16),
        ("adoption", ("Доставка и адаптация: перевод по приоритету трафика и боли, а не всё сразу; шаблоны и "
                      "песочница компонентов (Storybook), линтер на импорт копий, «платформа как продукт» — "
                      "поддержка, обратная связь, дорожная карта по запросам команд"), 0.16),
        ("twist", T["crit"].format(**v), 0.2),
        ("metrics", ("Метрики: доля экранов на библиотеке (сейчас " + fmt_num(100 * share, 0) + " %) и её рост, "
                     "отставание команд по версиям пакета, время доставки общей правки до продакшена, число "
                     "повторяющихся дефектов доступности, удовлетворённость команд"), 0.14),
    ]
    strong = (f"Сейчас любая общая правка — ≈ {fmt_num(copies, 0)} реализаций ({round(teams * copy_share)} команд × "
              f"{comps} компонентов) вместо одной; перевести нужно ≈ {fmt_num(to_move, 0)} экранов, за {months} мес. — "
              f"≈ {pace} в месяц, команда из {ds_team} человек не успеет одна. Поэтому модель федеративная: ядро "
              f"(токены, примитивы) делает центральная команда, составные компоненты вносят команды по правилам и "
              f"ревью — платим временем ревью и спорами о дизайне. Слои — токены → примитивы → составные, "
              f"семантические версии, окно поддержки старой версии, ломающие изменения с codemod. Перевожу по "
              f"трафику, линтер запрещает новые импорты копий, Storybook и шаблоны снижают порог. "
              + T["strong"].format(**v) + f" Метрики через полгода: доля экранов на библиотеке растёт с "
              f"{fmt_num(100 * share, 0)} %, отставание по версиям, время доставки общей правки, повторяющиеся "
              f"дефекты доступности, опрос команд.")
    medium = ("Сделать общую библиотеку компонентов с версиями и Storybook и постепенно перевести команды на неё.")
    weak = "Обязать все команды за квартал переписать интерфейс на новую библиотеку."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: ≈ {copies} реализаций на общую правку; ≈ {to_move} экранов, ≈ {pace} в месяц. "
                       f"«Всем переписать за квартал» — критерий adoption 0. Особенность — {kind}."),
                explanation=f"≈ {copies} реализаций на общую правку, темп ≈ {pace} экранов в месяц; особенность — {kind}.",
                params=dict(kind=kind, teams=teams, comps=comps, screens=screens, share=share, months=months,
                            copy_share=copy_share, ds_team=ds_team, copies=copies, to_move=to_move, pace=pace))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

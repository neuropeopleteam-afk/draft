def _build(rng, ctx):
    pages = rng.sample(sorted(PAGES), 3)
    if not {"catalog", "product", "search"} & set(pages):   # хотя бы одна «тяжёлая» общая страница
        pages[0] = rng.choice(["catalog", "product", "search"])
    kind = rng.choice(sorted(TWISTS))
    if kind == "personal_price" and "product" not in pages and "catalog" not in pages:
        pages[rng.randrange(3)] = "product"
    rps = rng.choice([800, 1500, 3000, 5000])
    render_ms = rng.choice([60, 90, 120, 180])
    n_cat = rng.choice([2000, 5000, 12000])
    n_prod = rng.choice([80000, 200000, 500000])
    n_help = rng.choice([300, 800, 1500])
    revalidate = rng.choice([300, 600, 900])
    n_pop = rng.choice([1000, 3000, 8000])
    cores_ssr = rps * render_ms / 1000
    # самая дорогая по пересборке из выбранных кэшируемых страниц: (подпись, число страниц, период обновления, с)
    regen = {"catalog": ("категории", n_cat, revalidate), "product": ("каркасы карточек", n_prod, revalidate),
             "help": ("статьи справки", n_help, revalidate), "search": ("популярные комбинации поиска", n_pop, 60),
             "landing": ("лендинг", 1, revalidate)}
    heavy = max((p for p in pages if p in regen), key=lambda p: regen[p][1] / regen[p][2])
    r_label, r_n, r_period = regen[heavy]
    cores_isr = r_n / r_period * render_ms / 1000
    v = dict(n_cat=n_cat, n_prod=n_prod, n_help=n_help, n_pop=fmt_num(n_pop, 0), weak=rng.choice([30, 40, 55]),
             inp=rng.choice([350, 450, 600]))
    T = TWISTS[kind]
    pages_txt = "\n".join(f"{i}. " + PAGES[p][0].format(**v).capitalize() + "." for i, p in enumerate(pages, 1))
    stem = (f"Вы — ведущий фронтенд-инженер; сайт — {ctx}. Поток в пике — {fmt_num(rps, 0)} запросов страниц в "
            f"секунду, серверная отрисовка одной страницы занимает ≈ {render_ms} мс процессорного времени, пересборку "
            f"по таймеру можно настроить раз в {revalidate} с (поиск — кэш на 60 с). Сейчас всё отрисовывается на сервере на каждый запрос "
            f"без кэша. Особенность: {T['text'].format(**v)}.\n\nТипы страниц:\n{pages_txt}\n\n"
            "Для каждого типа выберите стратегию отрисовки (на клиенте, серверная на каждый запрос, статическая "
            "генерация, пересборка по таймеру или событию, кэш CDN, потоковая отрисовка, островки) и объясните цену "
            "выбора; посчитайте, сколько процессорных ядер на отрисовку нужно сейчас и сколько после ваших решений, "
            "ответьте на особенность и скажите, как проверите результат. Ответ — 10–16 предложений.")
    ws = [0.15, 0.15, 0.15]
    criteria = [(f"page{i}_{p}", f"Тип {i}. Ожидается: {PAGES[p][1]}. Почему: {PAGES[p][2]}", w)
                for i, (p, w) in enumerate(zip(pages, ws), 1)]
    criteria += [
        ("load", (f"Расчёт: сейчас ≈ {fmt_num(rps, 0)} × {render_ms} мс ≈ {fmt_num(cores_ssr, 0)} ядер только на "
                  f"отрисовку; самое дорогое из кэшируемого — {r_label}: ≈ {fmt_num(r_n, 0)} / {r_period} с × "
                  f"{render_ms} мс ≈ {fmt_num(cores_isr, 2)} ядра на пересборку; итог зависит от доли попаданий в CDN, "
                  f"которая названа"), 0.18),
        ("twist", T["crit"].format(**v), 0.22),
        ("verify", ("Проверка: LCP, INP, TTFB по реальным пользователям (RUM, 75-й перцентиль) до и после, доля "
                    "попаданий в CDN, нагрузка на серверы отрисовки в пике, нагрузочный тест сценария «пустой кэш»"),
         0.15),
    ]
    strong = " ".join(f"Тип {i} — {PAGES[p][1]}, потому что {PAGES[p][2]}." for i, p in enumerate(pages, 1))
    strong += (f" Сейчас {fmt_num(rps, 0)} × {render_ms} мс ≈ {fmt_num(cores_ssr, 0)} ядер уходит только на отрисовку; "
               f"пересборка самого дорогого из кэшируемого ({r_label}, {fmt_num(r_n, 0)} за {r_period} с) — "
               f"≈ {fmt_num(cores_isr, 2)} ядра, остальное отдаёт CDN. " + T["strong"].format(**v) + " Проверяю LCP, INP и TTFB по RUM (75-й перцентиль) до и "
               "после, долю попаданий в CDN и нагрузочный тест сценария «пустой кэш».")
    medium = ("Каталог и лендинги — статическая генерация, личный кабинет — SPA, карточки — серверная отрисовка; "
              "добавить CDN.")
    weak = "Перейти на Next.js и включить серверную отрисовку везде — это лучше для SEO."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: без кэша ≈ {cores_ssr:.0f} ядер; пересборка ({r_label}) ≈ {cores_isr:.2f} ядра. "
                       "Персональный контент в общем кэше — критерий соответствующего типа 0. "
                       f"Ожидаемые стратегии: " + "; ".join(f"{i} — {PAGES[p][1]}" for i, p in enumerate(pages, 1)) +
                       f". Особенность — {kind}."),
                explanation=("Ожидаемые стратегии: " + "; ".join(f"{i} — {PAGES[p][1]}" for i, p in enumerate(pages, 1))
                             + f"; без кэша ≈ {cores_ssr:.0f} ядер; особенность — {kind}."),
                params=dict(pages=pages, kind=kind, rps=rps, render_ms=render_ms, revalidate=revalidate, heavy=heavy,
                            cores_ssr=round(cores_ssr, 1), cores_isr=round(cores_isr, 2), **v))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

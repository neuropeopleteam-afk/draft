"""frontend.strategy.legacy_migration_open — open_answer (Principal): стратегия ухода с устаревшего фронтенда.

Дано: большое клиентское приложение на устаревшем стеке (AngularJS 1.x, Backbone + jQuery или серверные шаблоны
с jQuery), число команд и экранов, главная причина (конец поддержки и уязвимости, найм, производительность)
и срок бизнеса. Кандидат выбирает между переписыванием и постепенной миграцией, решает, нужны ли
микрофронтенды или хватит модульного монорепозитория, описывает механику сосуществования (оболочка,
маршрутизация по разделам, общая сессия, дизайн-токены), порядок с метриками и критериями остановки,
организацию работы команд и риски двойной поддержки. Уровень Principal: решение на годы для многих команд.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import scenario_variant

FAMILY_ID = "frontend.strategy.legacy_migration_open"

CONTEXTS = ["кабинет работодателя", "интернет-банк", "кабинет продавца маркетплейса", "система записи клиник",
            "кабинет логиста", "CRM отдела продаж"]

STACKS = ["AngularJS 1.x", "Backbone и jQuery", "серверные шаблоны с jQuery"]

DRIVERS = {
    "eol": dict(
        text="поддержка {stack} закончилась, в зависимостях {cves} известных уязвимостей без исправлений",
        first=("первыми переношу разделы с самым большим риском — вход, платежи, загрузка файлов; остальное — по "
               "частоте изменений; до переноса — изоляция старого кода (CSP, отдельный поддомен для старых "
               "разделов, обновлённые точечно зависимости)"),
        metric="число известных уязвимостей в продакшн-зависимостях — 0 в разделах с данными клиентов"),
    "hiring": dict(
        text="вакансии на {stack} закрываются по полгода, {leave} % разработчиков за год ушли, называя стек причиной",
        first=("первыми переношу разделы с наибольшей частотой изменений — там больше всего работы и найма; редко "
               "меняемые разделы могут жить на старом стеке дольше"),
        metric="доля изменений, сделанных в новом стеке, — 80 % через три квартала; время ввода нового разработчика"),
    "perf": dict(
        text="LCP на мобильных — {lcp} с по 75-му перцентилю, конверсия мобильных на треть ниже десктопа",
        first=("первыми переношу входные страницы с наибольшим мобильным трафиком (поиск, карточка) с серверной "
               "отрисовкой; внутренние разделы — позже"),
        metric="LCP p75 на мобильных ≤ 2,5 с на перенесённых страницах, конверсия мобильных — рост против контроля"),
}


def _build(rng, ctx):
    kind = rng.choice(sorted(DRIVERS))
    D = DRIVERS[kind]
    v = dict(stack=rng.choice(STACKS), teams=rng.choice([5, 8, 12]), screens=rng.choice([140, 260, 400]),
             cves=rng.choice([7, 12, 19]), leave=rng.choice([20, 30, 35]), lcp=rng.choice(["4,8", "6,1", "7,5"]),
             quarters=rng.choice([4, 6, 8]))
    drv = D["text"].format(**v)
    stem = (f"Вы — главный инженер (Principal). Приложение «{ctx}»: {v['screens']} экранов на {v['stack']}, над ним "
            f"работают {v['teams']} команд. Главная причина что-то менять: {drv}. Продукт не может остановить развитие "
            f"больше чем на квартал, горизонт — {v['quarters']} кварталов.\n\n"
            "Предложите стратегию: переписывание или постепенная миграция; микрофронтенды или модульный "
            "монорепозиторий; как старое и новое будут сосуществовать; порядок разделов, метрики и критерии "
            "остановки; как организовать команды и чем рискуете. Ответ — 15–25 предложений.")
    criteria = [
        ("decision", (f"Решение с обоснованием от причины ({drv}): постепенная миграция по разделам вместо "
                      f"переписывания с нуля (развитие не останавливается, риск распределён); микрофронтенды — "
                      f"только если нужна независимая выкладка {v['teams']} команд, с ценой (дубли зависимостей, "
                      f"сложность сборки), иначе модульный монорепозиторий"), 0.25),
        ("coexistence", ("Механика сосуществования: оболочка или обратный прокси маршрутизирует разделы на старое или "
                         "новое, общая сессия и авторизация, единые дизайн-токены для обоих стеков, совместимость "
                         "адресов и закладок, без загрузки двух фреймворков на одной странице"), 0.25),
        ("sequencing", (f"Порядок и критерии: {D['first']}; каждый раздел — за флагом с канарейкой и откатом; "
                        f"контрольная точка с критерием «продолжать/пересмотреть»"), 0.2),
        ("metrics", f"Измерение: {D['metric']}; плюс доля ошибок и Web Vitals по разделам до и после", 0.15),
        ("org_risks", ("Команды и риски: платформенная группа на оболочку и дизайн-систему, правило «новое — только "
                       "в новом стеке», обучение; риски двойной поддержки, просадки производительности и «вечной "
                       "миграции» — как ограничивает (срок жизни старого стека, бюджет на перенос в каждом квартале)"),
         0.15),
    ]
    strong = (f"Причина — {drv}, поэтому переписывать с нуля не буду: продукт не может стоять больше квартала, а "
              f"переписывание {v['screens']} экранов — это годы без отдачи и потерянные знания о поведении. Иду "
              f"постепенно, по разделам: оболочка (обратный прокси на краю) маршрутизирует каждый раздел на старое или "
              f"новое приложение, сессия и авторизация общие, дизайн-токены вынесены в общий пакет и подключены к "
              f"обоим стекам, адреса сохраняются. Два фреймворка на одной странице не смешиваю. Микрофронтенды "
              f"вводить не спешу: для {v['teams']} команд хватает модульного монорепозитория с независимой выкладкой "
              f"разделов; микрофронтенды оправданы, только если командам нужна полностью независимая выкладка, и "
              f"тогда плачу дублями зависимостей и сложной сборкой. Порядок: {D['first']}. Каждый раздел включаю "
              f"флагом на долю пользователей с откатом; после первых двух разделов — контрольная точка. Метрики: "
              f"{D['metric']}; ошибки и Web Vitals по разделам. Организация: платформенная группа из 2–3 человек "
              f"ведёт оболочку и дизайн-систему; правило «новый код — только в новом стеке»; в каждом квартале "
              f"бюджет на перенос, иначе миграция станет вечной. Риски — двойная поддержка и просадки "
              f"производительности на стыках; ограничиваю их сроком жизни старого стека в {v['quarters']} кварталов.")
    medium = (f"Нужно постепенно переписывать приложение на React по разделам, чтобы не останавливать разработку, "
              f"и использовать микрофронтенды, чтобы команды работали независимо.")
    weak = "Нужно переписать всё приложение на современный фреймворк за один квартал силами всех команд."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=f"Причина варианта — {kind}; порядок разделов должен следовать из неё.",
                explanation=f"Причина — {kind}: {drv}. Ожидаемо: постепенная миграция по разделам; {D['first']}.",
                params=dict(kind=kind, stack=v["stack"], teams=v["teams"], screens=v["screens"]))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

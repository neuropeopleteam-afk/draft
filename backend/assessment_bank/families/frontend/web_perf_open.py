CTX = ["маркетплейс", "банк", "онлайн-кинотеатр", "агрегатор билетов", "CRM", "новостной портал"]


def generate(seed: int):
    rng = make_rng(FAMILY_ID, seed)
    topic = rng.choice(sorted(TOPICS))
    T = TOPICS[topic]
    vals = dict(ctx=rng.choice(CTX), lcp=rng.choice(["4,1", "5,3", "6,8"]),
                kb=rng.choice([900, 1400, 2300]), rows=rng.choice(["10 000", "25 000", "60 000"]),
                inp=rng.choice([450, 800, 1300]), cls=rng.choice(["0,28", "0,41", "0,63"]))
    stem = T["text"].format(**vals) + " Ответ — 8–15 предложений."
    spec = {**T, "strong": T["strong"].format(**vals),
            "notes": "Оценка по критериям рубрики; эталоны — ориентиры уровня."}
    ak = AnswerKey(kind="rubric", value="rubric",
                   explanation="Открытый ответ оценивается по рубрике (сильный/средний/слабый).")
    return build_variant(FAMILY_ID, seed, stem=stem, answer_key=ak, rubric=rubric_from(spec),
                         context=vals["ctx"], verification="rubric_only", language="text",
                         params={"topic": topic})

"""frontend.arch.realtime_collab_open — open_answer (Lead): совместное редактирование в реальном времени.

Дан продукт варианта (документы, доска, таблица, план занятий): одновременных редакторов на документ,
операций в секунду на пользователя, всего открытых соединений, длина журнала операций. Кандидат выбирает
модель слияния правок (OT с сервером-арбитром, CRDT, блокировки по фрагментам) с ценой, транспорт и
переподключение (подтверждённый номер операции, повторная отправка неподтверждённых), хранение (журнал
операций и снимки), присутствие и курсоры отдельно от данных. Опорные числа для рубрики: операций в секунду
на документ (редакторы × частота), рост журнала в сутки и шаг снимка, поток переподключений после
выкладки (соединения / окно разброса).
Особенность варианта: правки офлайн до часа, «шторм» переподключений после выкладки, документ на
десятки тысяч элементов (время открытия).
Рубрика 0–4: модель слияния с ценой, транспорт и переподключение, хранение, особенность, проверка.
"""
from __future__ import annotations

from assessment_bank.families.common._lead_kit import fmt_num, scenario_variant

FAMILY_ID = "frontend.arch.realtime_collab_open"

# продукт, формы слова «объект»: им., вин., род., род. мн., им. мн.; род. элемента
CONTEXTS = [
    ("редактор документов", dict(nom="документ", acc="документ", gen="документа", gen_pl="документов",
                                 pl="документы", item_gen="абзаца")),
    ("онлайн-доска для схем", dict(nom="доска", acc="доску", gen="доски", gen_pl="досок", pl="доски",
                                   item_gen="фигуры")),
    ("совместная таблица", dict(nom="таблица", acc="таблицу", gen="таблицы", gen_pl="таблиц", pl="таблицы",
                                item_gen="ячейки")),
    ("редактор планов занятий", dict(nom="план", acc="план", gen="плана", gen_pl="планов", pl="планы",
                                     item_gen="блока занятия")),
    ("редактор макетов интерфейса", dict(nom="макет", acc="макет", gen="макета", gen_pl="макетов", pl="макеты",
                                         item_gen="слоя")),
    ("редактор сценариев опросов", dict(nom="сценарий", acc="сценарий", gen="сценария", gen_pl="сценариев",
                                        pl="сценарии", item_gen="вопроса")),
]

TWISTS = {
    "offline": dict(
        text="пользователи в поездках правят {acc} офлайн до часа, потом подключаются",
        crit=("правки офлайн до часа: локальная очередь операций с номерами, при подключении — повторная "
              "отправка с последнего подтверждённого номера и слияние; CRDT сходится без арбитра, OT требует "
              "перебазирования длинной очереди на сервере; пользователю показывается, что его правки слиты, "
              "конфликт правок в одном элементе — явно, а не молча"),
        strong=("офлайн-правки копятся в локальной очереди с номерами; при подключении клиент шлёт всё после "
                "последнего подтверждённого номера, слияние — по модели (CRDT сходится сам, при OT сервер "
                "перебазирует очередь), а одновременную правку одного элемента показываю явно.")),
    "storm": dict(
        text="при выкладке сервера все {conns} соединений рвутся одновременно",
        crit=("«шторм» переподключений: {conns} соединений разом — экспоненциальная задержка со случайным "
              "разбросом (jitter) на клиенте, плавная выкладка с перебалансировкой (drain) вместо одновременного "
              "разрыва; при разбросе {spread} с поток ≈ {storm_rps} подключений в секунду — сверить с пределом "
              "балансировщика и авторизации"),
        strong=("{conns} соединений, рвущихся разом, — это шторм подключений и авторизаций; клиент "
                "переподключается с экспоненциальной задержкой и случайным разбросом, сервер при выкладке "
                "отпускает соединения постепенно; при разбросе {spread} с выходит ≈ {storm_rps} подключений в "
                "секунду — проверяю, что балансировщик и авторизация это держат.")),
    "big_doc": dict(
        text="крупные {pl} — до {elems} элементов, открытие сейчас занимает ≈ {open_s} с",
        crit=("крупный документ ({elems} элементов, открытие ≈ {open_s} с): открывать со снимка, а не "
              "проигрыванием журнала; ленивая загрузка частей и виртуализация отрисовки; сжатие журнала "
              "(слияние старых операций в снимок)"),
        strong=("крупный объект на {elems} элементов не открываю проигрыванием журнала — отдаю последний снимок "
                "плюс хвост операций, отрисовываю виртуализированно и подгружаю части по мере прокрутки; старые "
                "операции сливаю в снимок.")),
}


def _build(rng, ctx_t):
    ctx, F = ctx_t
    editors = rng.choice([5, 10, 20, 50])
    ops_user = rng.choice([2, 4, 8])                 # операций в секунду на активного редактора
    docs_active = rng.choice([2000, 5000, 15000])
    conns = rng.choice([20000, 60000, 150000])
    op_bytes = rng.choice([80, 120, 200])
    active_h = rng.choice([0.5, 1, 2])                # часов правки в пиковом темпе за сутки (суммарно)
    kind = rng.choice(sorted(TWISTS))
    spread = rng.choice([10, 30, 60])
    ops_doc = editors * ops_user
    ops_day = ops_doc * active_h * 3600
    log_mb_day = ops_day * op_bytes / 1e6
    snap_every = rng.choice([500, 1000, 5000])
    v = dict(**F, conns=fmt_num(conns, 0), spread=spread, storm_rps=fmt_num(conns / spread, 0),
             elems=fmt_num(rng.choice([20000, 50000, 100000]), 0), open_s=rng.choice([6, 9, 14]))
    T = TWISTS[kind]
    stem = (f"Вы — ведущий фронтенд-инженер; продукт — {ctx}. Делаете совместное редактирование в реальном времени: "
            f"до {editors} одновременных редакторов на {F['acc']}, в пике каждый делает ≈ {ops_user} операций в секунду "
            f"(ввод, перемещение), одновременно открыто ≈ {fmt_num(docs_active, 0)} {F['gen_pl']} и {fmt_num(conns, 0)} "
            f"соединений; операция в среднем — {op_bytes} байт, суммарно за сутки правка {F['gen']} в пиковом темпе — до {fmt_num(active_h, 1)} ч. "
            f"Особенность: {T['text'].format(**v)}.\n\nОпишите архитектуру: модель слияния одновременных правок и её "
            "цену, транспорт и переподключение без потери и задвоения правок, хранение (журнал, снимки — посчитайте "
            "рост журнала и шаг снимка), присутствие и курсоры, ответ на особенность и как проверите, что правки не "
            "теряются и копии сходятся. Ответ — 10–16 предложений.")
    criteria = [
        ("merge", (f"Модель слияния с ценой: OT с сервером-арбитром (проще хранение, нужен центральный порядок и "
                   f"перебазирование) или CRDT (сходится без арбитра и офлайн, цена — метаданные и размер документа, "
                   f"сборка мусора); блокировка {F['item_gen']} — только как дополнение; выбор обоснован сценарием варианта"),
         0.2),
        ("transport", (f"Транспорт: WebSocket (или аналог) с номерами операций и подтверждениями; при "
                       f"переподключении — повторная отправка неподтверждённых с последнего подтверждённого номера, "
                       f"идемпотентность по id операции; пакетирование при ≈ {ops_doc} операциях в секунду на "
                       f"{F['acc']} ({editors} × {ops_user})"), 0.2),
        ("storage", (f"Хранение: журнал операций растёт на ≈ {fmt_num(ops_day, 0)} операций ≈ {fmt_num(log_mb_day, 0)} МБ "
                     f"на {F['acc']} в активной правке в сутки — снимок каждые ≈ {snap_every} операций (или по времени), открытие "
                     f"= снимок + хвост, сжатие старого журнала; присутствие и курсоры — эфемерный канал без "
                     f"записи в журнал"), 0.2),
        ("twist", T["crit"].format(**v), 0.22),
        ("verify", ("Проверка: тест сходимости (случайные одновременные правки нескольких клиентов с задержками и "
                    "обрывами — итог одинаков у всех и равен серверному), метрики «неподтверждённые операции дольше "
                    "N с», «расхождение копий» и задержка доставки p95"), 0.18),
    ]
    strong = (f"При {editors} редакторах по {ops_user} операций в секунду на {F['acc']} приходится ≈ {ops_doc} операций в "
              f"секунду — пакетирую их по 50–100 мс. Модель — CRDT, если важен офлайн (сходится без арбитра, платим "
              f"метаданными и сборкой мусора), иначе OT с сервером-арбитром (проще хранение, нужен центральный "
              f"порядок). Транспорт — WebSocket с номерами операций и подтверждениями: после обрыва клиент шлёт всё "
              f"после последнего подтверждённого номера, сервер удаляет дубли по id. Журнал растёт на "
              f"≈ {fmt_num(log_mb_day, 0)} МБ на {F['acc']} в активной правке в сутки — снимок каждые ≈ {snap_every} операций, "
              f"открытие = снимок + хвост; курсоры и присутствие — эфемерный канал вне журнала. "
              + T["strong"].format(**v) + " Проверяю тестом сходимости со случайными правками, задержками и "
              "обрывами и метриками неподтверждённых операций и расхождения копий.")
    medium = ("Использовать WebSocket и CRDT-библиотеку (Yjs или Automerge), хранить изменения в базе и "
              "переподключаться при обрыве.")
    weak = "Сохранять документ целиком раз в несколько секунд и показывать последнюю сохранённую версию всем."
    return dict(stem=stem, criteria=criteria, strong=strong, medium=medium, weak=weak,
                notes=(f"Опорные числа: ≈ {ops_doc} операций/с на {F['acc']}; журнал ≈ {log_mb_day:.0f} МБ в сутки на "
                       f"{F['acc']} в активной правке. «Последняя запись побеждает целиком» — критерий merge не выше 1. "
                       f"Особенность — {kind}."),
                explanation=(f"≈ {ops_doc} операций/с на {F['acc']}; журнал ≈ {log_mb_day:.0f} МБ в сутки; особенность — "
                             f"{kind}."),
                params=dict(kind=kind, editors=editors, ops_user=ops_user, conns=conns, op_bytes=op_bytes,
                            active_h=active_h, ops_doc=ops_doc, log_mb_day=round(log_mb_day, 1), spread=spread,
                            snap_every=snap_every))


def generate(seed: int):
    return scenario_variant(FAMILY_ID, seed, contexts=CONTEXTS, build=_build)

def detect_goto(text: str, *, strict: bool = True, path: str | None = None, step: str | None = None) -> str | None:
    t = _norm(text)
    if strict and not _GOTO_VERB.search(t):
        return None
    for rx, sid in _GOTO:
        if re.search(rx, t):
            return resolve_shared(sid, t, path, step)
    return None



def num_words(n: int, *, gen: bool = False, fem: bool = False) -> str:
    """Число 0…999 словами (именительный или родительный падеж; одна/две — для женского рода)."""
    n = max(0, min(999, int(n)))
    if n == 0:
        return _U_G[0] if gen else _U[0]
    parts: list[str] = []
    h, r = divmod(n, 100)
    if h:
        parts.append((_HUND_G if gen else _HUND)[h])
    if 10 <= r < 20:
        parts.append((_TEEN_G if gen else _TEEN)[r - 10])
    else:
        tn, u = divmod(r, 10)
        if tn:
            parts.append((_TENS_G if gen else _TENS)[tn])
        if u:
            if gen:
                parts.append("одной" if fem and u == 1 else _U_G[u])
            else:
                parts.append(_U_F.get(u, _U[u]) if fem else _U[u])
    return " ".join(parts)


def plural(n: int, one: str, few: str, many: str) -> str:
    n = abs(int(n)) % 100
    if 11 <= n <= 14:
        return many
    return one if n % 10 == 1 else few if 2 <= n % 10 <= 4 else many


def _pc_words(v: float) -> str:
    """0,9774 → «девяносто семь и семь десятых процента» (для реплик обзора — числа словами)."""
    x = round(float(v) * 100, 1)
    w_int, w_frac = int(x), int(round((x - int(x)) * 10))
    if w_frac:
        return f"{num_words(w_int)} и {num_words(w_frac, fem=True)} {plural(w_frac, 'десятая', 'десятых', 'десятых')} процента"
    return f"{num_words(w_int)} {plural(w_int, 'процент', 'процента', 'процентов')}"



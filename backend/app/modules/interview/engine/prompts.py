def _materials(spec: SessionSpec) -> str:
    lines = [f"Собеседник: {spec.candidate_name}. Вопросов по плану: {spec.max_questions}. Время: {spec.duration_min} мин."]
    ctx = spec.context
    if isinstance(ctx, DefenseContext):
        lines.append(f"Режим: защита. Направление теста: {ctx.role or 'не указано'}; заявленный уровень: {ctx.grade or 'не указан'}.")
        lines.append("Задания и письменные ответы собеседника:")
        for i, t in enumerate(ctx.tasks, 1):
            topics = ", ".join(t.topics) if t.topics else "по сути ответа"
            lines.append(f"{i}. [{t.id}] «{t.title or 'задание'}»{f' ({t.kind})' if t.kind else ''}. Темы: {topics}.")
            if t.prompt:
                lines.append(f"   Задание: {t.prompt}")
            lines.append(f"   Письменный ответ: {t.answer}")
            if t.integrity_flags:
                marks = "; ".join(INTEGRITY_LABELS.get(f, f) for f in t.integrity_flags)
                lines.append(f"   Признаки при наборе (собеседнику не называть; спрашивать предметнее): {marks}")
    elif isinstance(ctx, InterviewContext):
        lines.append(f"Режим: интервью. Потребность: «{ctx.need_title}».")
        if ctx.need_summary:
            lines.append(f"Что можно рассказать о позиции: {ctx.need_summary}")
        if ctx.confirmed_skills:
            lines.append(f"Подтверждено тестом, об этом не спрашивать: {', '.join(ctx.confirmed_skills)}.")
        lines.append("Навыки для проверки:")
        for i, s in enumerate(ctx.unconfirmed_skills, 1):
            lines.append(f"{i}. {s.name}{f' — нужный уровень: {s.level}' if s.level else ''}{f' ({s.why})' if s.why else ''}")
        if ctx.format_questions:
            lines.append("Вопросы о формате (один, если останется время): " + "; ".join(ctx.format_questions))
    lines.append("План вопросов:")
    for p in plan(spec):
        ref = f"задание [{p.task_id}]" if p.task_id else f"навык «{p.skill}»"
        lines.append(f"{p.k}. {ref} — {p.angle}")
    return "\n".join(lines)


def transcript_text(transcript: Transcript, host: str = "ВЕДУЩИЙ") -> str:
    lines = []
    for u in transcript.items:
        if u.who == "candidate":
            lines.append(f"СОБЕСЕДНИК [{u.n}]: {u.text}")
        else:
            lines.append(f"{host}: {u.text}")
    return "\n".join(lines) or "(разговор ещё не начался)"


def host_messages(spec: SessionSpec, transcript: Transcript, service_line: str, host: str, product: str) -> list[dict]:
    system = HOST_SYSTEM.format(host=host, product=product)
    user = f"МАТЕРИАЛЫ (собеседник их не видит)\n{_materials(spec)}\n\nРАСШИФРОВКА\n{transcript_text(transcript)}\n\n{service_line}"
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def service_line(spec: SessionSpec, item: PlanItem | None, kind: str, minute: float, answers: int, short_answer: bool) -> str:
    left = max(0, spec.duration_min - minute)
    parts = [f"минута {max(1, round(minute))} из {spec.duration_min}, осталось около {round(left)} мин", f"ответов собеседника: {answers}"]
    if kind == "closing":
        what = ("ответы переданы как подтверждение результатов теста, итог увидит работодатель, результат теста не меняется"
                if spec.mode == "defense" else "итог интервью увидит работодатель, решение принимает человек")
        parts.append(f"вопросов больше не задавай: поблагодари по имени, скажи, что {what}, попрощайся; kind = closing")
    elif kind == "repeat":
        parts.append("собеседник не понял или ответ не дошёл: переформулируй последний вопрос проще; kind = repeat")
    elif item is not None:
        ref = f"задание [{item.task_id}] «{item.title}»" if item.task_id else f"навык «{item.skill}»"
        if kind == "opening":
            what = "по его письменным ответам" if spec.mode == "defense" else "о его опыте"
            parts.append(f"начало: поздоровайся по имени, одной фразой скажи, что будет {spec.max_questions} коротких вопроса {what}, и сразу задай вопрос 1; kind = opening")
        else:
            parts.append(f"сейчас задай вопрос {item.k} из {spec.max_questions}; kind = question")
        parts.append(f"вопрос {item.k}: {ref} — угол: {item.angle}")
        if short_answer:
            parts.append("последний ответ короткий: одной фразой отреагируй нейтрально и всё равно переходи к этому вопросу")
        if left <= 1:
            parts.append("времени почти нет: вопрос короче обычного")
    return f"(служебно: {'; '.join(parts)})"


def judge_input(spec: SessionSpec, transcript: Transcript) -> str:
    return f"МАТЕРИАЛЫ\n{_materials(spec)}\n\nРАСШИФРОВКА (номера — у реплик собеседника)\n{transcript_text(transcript)}"

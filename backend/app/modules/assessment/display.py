"""Слой показа задания (А4, 21.10; правило А3): служебная шапка генератора волны 20.10 в условии не показывается.

Шапка «Обратный расчёт входа «…» с учётом факторов: ….» / «Прямой расчёт показателя «…» с учётом факторов: ….» стоит
в начале условия у 1 049 семейств (во всех вариантах). Банк заморожен (хэш 913ad19f6a259aff) — шапку отрезаем при
показе кандидату и в сохранённой для разбора/PDF копии условия; состояние сессии (public.stem), симуляция и боты не
меняются. Правило и проверка на 1 049 × 20 = 20 980 условиях (0 промахов) — у А3 (письмо 21.10).
"""
from __future__ import annotations

import re

GENERATOR_HEADER = re.compile(r"^(?:Обратный расчёт входа «[^»]*»|Прямой расчёт показателя «[^»]*») с учётом факторов: [^\n]*?\.\s+")


def display_stem(stem: str | None) -> str | None:
    """Условие для показа: без служебной шапки генератора (только начало stem; варианты и вопрос не трогаются)."""
    if not stem:
        return stem
    return GENERATOR_HEADER.sub("", stem, count=1)

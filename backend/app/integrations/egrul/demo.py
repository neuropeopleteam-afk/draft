"""Демо-сведения ФНС для демо-компаний без ИНН (индекс доверия).

Демо-компании (is_demo, ИНН не указан) в ФНС не запрашиваются: настоящих реквизитов у них нет. Раньше такая
компания получала 0 баллов за реестр и «Низкий» индекс — кандидат жюри видел, что его собственный работодатель
«низкого доверия», и это подрывало доверие к самой функции. Теперь:

* «обычная» демо-компания — правдоподобные демо-сведения «из ФНС» (действует, дата регистрации 2015–2021 годов,
  название совпадает) с явной пометкой «демо»: в тексте причин, в сводке реестра и в ответе API (``demo: true``).
  Сведения условные, в реестре их нет, ИНН и ОГРН не придумываются;
* «плохая» демо-компания (BAD_NAMES) — сценарий низкого индекса: записи в реестре нет, почта не на домене сайта.
  Это вакансия-приманка платформы и «плохой» работодатель песочницы жюри: на них видно, как индекс предупреждает.

Дата регистрации — детерминированная функция названия: она не меняется между запросами и пересевами.
"""
from __future__ import annotations

from datetime import date, timedelta
import hashlib

BAD_NAMES = frozenset({"Демо: Студия Интерфейсов", "Демо жюри: Быстрый заработок"})
DEMO_NOTE = "демо-сведения для показа, ФНС не запрашивалась"


def is_demo_company(company) -> bool:
    """Демо-компания без ИНН — та, к которой применяются демо-сведения."""
    return bool(company.is_demo) and not company.inn


def is_bad(company) -> bool:
    return company.name in BAD_NAMES


def registered_at(name: str) -> str:
    """Условная дата регистрации: 1 марта 2015 — 31 декабря 2021, одна и та же для одного названия."""
    h = int(hashlib.sha1(name.encode("utf-8")).hexdigest()[:8], 16)
    return (date(2015, 3, 1) + timedelta(days=h % 2497)).isoformat()


def registry_data(company) -> dict:
    """Сводка «реестра» для хорошей демо-компании: то, что показывается как сведения ФНС (с пометкой «демо»)."""
    return {"status": "demo_found", "demo": True, "name": company.name, "short_name": company.name,
            "registered_at": registered_at(company.name), "liquidated_at": None, "director": None,
            "director_role": None, "ogrn": None, "source": "демо", "note": DEMO_NOTE}

"""Числа в речи — словами по-русски (av17, решение владельца 21.10 18:55)."""
from app.modules.interview.concierge_numsay import spoken


def test_percent_and_bank():
    assert spoken("точный грейд — 77,6 %") == "точный грейд — семьдесят семь и шесть десятых процента"
    assert spoken("1 646 семейств, 38 131 проверка") == "тысяча шестьсот сорок шесть семейств, тридцать восемь тысяч сто тридцать одна проверка"
    assert spoken("у 2,1 % кандидатов") == "у двух и одной десятой процента кандидатов"


def test_ranges_money_gender():
    assert spoken("на руки 275–430 тыс. ₽") == "на руки от двухсот семидесяти пяти до четырёхсот тридцати тысяч рублей"
    assert spoken("±1 ступень, 2 задания, 2 попытки, 1 задание") == "плюс-минус одна ступень, два задания, две попытки, одно задание"
    assert spoken("75 из 100") == "семьдесят пять из ста"


def test_codes_untouched():
    for t in ("C-88QTWX", "индекс v6", "ISO 27001", "2026 год"):
        assert spoken(t) == t


def test_word_percent_and_dative():
    assert spoken("77,6 процентов по 6 ступеням") == "семьдесят семь и шесть десятых процента по шести ступеням"
    assert spoken("к 2 кандидатам, по 21 баллу") == "к двум кандидатам, по двадцати одному баллу"
    assert spoken("5 процентов, 1 процент") == "пять процентов, один процент"
